#!/usr/bin/env python3
"""The unanchored-pass ratchet: a `pass` cell whose evidence names no anchor is prose nothing checks, and its count
per repository may only go down.

    pass_anchor_ratchet.py [--owner NAME] [--source DIR]
    pass_anchor_ratchet.py --only NAME=DIR
    pass_anchor_ratchet.py --write-baseline [--source DIR]
    pass_anchor_ratchet.py --check-baseline

An anchor is a code span `path#token` in an evidence string, read as scripts/conformance_roster_check.py reads it
(anchors_in); the roster check resolves each anchor to exactly one place, so a cell with one is tied to the tree. A
`pass` cell whose evidence has none is counted for its repository. The repositories are those of release-train.toml's
crates that are not exempt; each is read at its default branch (--source DIR reads DIR/<repo> at origin/main instead,
--only reads one directory's committed manifest at HEAD). conformance/pass-anchor-baseline.toml holds one count per
repository, 0 included: at 0 the repository refuses any unanchored pass outright.

The rules, on every repository read:
  * a count above the baseline is red (a new unanchored pass);
  * a count below the baseline is red until the baseline is lowered in the same commit;
  * a repository with a manifest and no row is red, and a row for a repository not in the roster is red;
  * 0 manifests read is red (a check that compared nothing passes nothing).
The total of the counts is printed on its own line, the number the roster report shows.

--check-baseline reads no repository: the baseline's form (one count per row, an integer 0 or more, at least one row)
and its rows against the roster. A ci/ branch runs it, since another repository's count is not red on a ci/ branch
that cannot change it; Conformance (live) compares the counts.

Exit 0 when every count equals its row, 1 on a finding, 2 when something could not be read or nothing was compared.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import conformance_roster_check as crc  # noqa: E402

ROOT = HERE.parent
BASELINE = ROOT / "conformance" / "pass-anchor-baseline.toml"
ROSTER = ROOT / "release-train.toml"


def unanchored(text: str) -> list[str]:
    """the gates whose status is `pass` and whose evidence names no anchor, in gate order"""
    manifest = tomllib.loads(text)
    out = []
    for gate, cell in manifest.items():
        if not (isinstance(cell, dict) and gate.startswith("G") and gate[1:].isdigit()):
            continue
        if cell.get("status") != "pass":
            continue
        evidence = cell.get("evidence") or []
        if not any(True for e in evidence if isinstance(e, str) for _ in crc.anchors_in(e)):
            out.append(gate)
    return sorted(out, key=lambda g: int(g[1:]))


def load_baseline(path: Path = BASELINE) -> dict[str, int]:
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    rows = data.get("repository")
    if not isinstance(rows, dict) or not rows:
        raise crc.InputError(f"{path}: no [repository.\"…\"] row")
    out = {}
    for repo, row in rows.items():
        n = row.get("unanchored") if isinstance(row, dict) else None
        if not isinstance(n, int) or isinstance(n, bool) or n < 0:
            raise crc.InputError(f"{path}: {repo}: `unanchored` must be a count (an integer, 0 or more)")
        out[repo] = n
    return out


def compare(read: dict[str, list[str]], baseline: dict[str, int], roster: set[str]) -> list[str]:
    findings = []
    for repo, gates in sorted(read.items()):
        n = len(gates)
        if repo not in baseline:
            findings.append(f"{repo}: no row in the baseline ({n} unanchored pass: {', '.join(gates) or '-'})")
        elif n > baseline[repo]:
            findings.append(f"{repo}: {n} unanchored pass > baseline {baseline[repo]} (a pass without an anchor: "
                            f"{', '.join(gates)})")
        elif n < baseline[repo]:
            findings.append(f"{repo}: {n} unanchored pass < baseline {baseline[repo]} (lower the baseline in this commit)")
    for repo in sorted(set(baseline) - roster):
        findings.append(f"{repo}: a row for a repository the roster does not list")
    return findings


def render(rows: dict[str, int]) -> str:
    out = ["# Generated by scripts/pass_anchor_ratchet.py --write-baseline: per release-train repository, the `pass`",
           "# cells of its alice-law-conformance.toml whose evidence names no anchor. Counts only go down; 0 refuses any.", ""]
    for repo in sorted(rows):
        out += [f'[repository."{repo}"]', f"unanchored = {rows[repo]}", ""]
    return "\n".join(out)


def read_local(d: Path, ref: str) -> str | None:
    p = subprocess.run(["git", "-C", str(d), "show", f"{ref}:{crc.MANIFEST}"], capture_output=True, text=True, encoding="utf-8")
    return p.stdout if p.returncode == 0 else None


def read_all(owner: str, source: Path | None, repos: list[str]) -> dict[str, list[str]]:
    fetch = None if source else crc.gh_fetcher(owner)
    read: dict[str, list[str]] = {}
    for repo in repos:
        if source:
            text = read_local(source / repo, "origin/main")
        else:
            text = fetch(repo)[0]
        if text is not None:
            read[repo] = unanchored(text)
    return read


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--owner", default="ext-sakamoro")
    ap.add_argument("--source", type=Path, help="DIR/<repo> local clones, read at origin/main")
    ap.add_argument("--only", help="NAME=DIR: one repository's committed manifest (HEAD) against its row")
    ap.add_argument("--write-baseline", action="store_true")
    ap.add_argument("--check-baseline", action="store_true", help="the baseline's form and rows only, no repository read")
    ap.add_argument("--baseline", type=Path, default=BASELINE)
    a = ap.parse_args(argv)
    try:
        roster = set(crc.repo_crates(crc.load_toml(ROSTER)))
        if a.check_baseline:
            rows = load_baseline(a.baseline)
            off = sorted(set(rows) - roster)
            for repo in off:
                print(f"found: {repo}: a row for a repository the roster does not list")
            print(f"pass_anchor_ratchet: baseline {len(rows)} row(s), {sum(rows.values())} unanchored pass in all, "
                  f"{len(off)} finding(s)")
            return 1 if off else 0
        if a.only:
            name, _, d = a.only.partition("=")
            text = read_local(Path(d), "HEAD")
            if not name or text is None:
                raise crc.InputError(f"--only {a.only}: no committed {crc.MANIFEST}")
            read = {name: unanchored(text)}
            baseline = load_baseline(a.baseline)
            findings = compare(read, {name: baseline[name]} if name in baseline else {}, {name})
        else:
            read = read_all(a.owner, a.source, sorted(roster))
            if a.write_baseline:
                if not read:
                    raise crc.InputError("no manifest read: nothing to write")
                a.baseline.write_text(render({r: len(g) for r, g in read.items()}), encoding="utf-8")
                print(f"pass_anchor_ratchet: wrote {a.baseline} ({len(read)} repositories)")
                return 0
            findings = compare(read, load_baseline(a.baseline), roster)
    except (crc.InputError, tomllib.TOMLDecodeError, OSError, KeyError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    if not read:
        print("error: no manifest read (compared nothing)", file=sys.stderr)
        return 2
    for f in findings:
        print(f"found: {f}")
    total = sum(len(g) for g in read.values())
    print(f"pass_anchor_ratchet: {len(read)} manifests read, {total} unanchored pass in all, {len(findings)} finding(s)")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
