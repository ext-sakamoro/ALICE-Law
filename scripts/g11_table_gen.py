#!/usr/bin/env python3
"""ALICE-Law G11 table generator: writes a crate's conformance/g11.toml from what ALICE-Law already knows,
so the rows of a checker shared across crates are written once.

A row comes from one of two places:
  conformance/g11-shared-rows.toml (ALICE-Law)  one entry per shared checker: its canary, its zero test and
                                                its shared paths. The crate gets the row for gate G when its
                                                alice-law-conformance.toml names the checker in G's evidence,
                                                G is pass there, and ALICE-Law's conformance/shared-files.toml
                                                (at the revision .github/shared-files-pin names) lists the
                                                checker for the crate. `shared` keeps the entry's paths that
                                                table lists for the crate.
  conformance/g11-own.toml (the crate)          the crate's own rows, in the table's row format, copied as
                                                they are (a checker of its own, or a cargo test oracle).
The table is the generated rows and the crate's own rows, ordered by gate and checker.

Each row's canary and zero are resolved the way scripts/g11_table_check.py resolves them; a row that does
not resolve is reported and still written, so the check names it too. Nothing is written in place of a row
that does not exist: a pass gate without a row is listed, and the crate's G11 stays unmet until it has one.

Exit 0 when every pass gate has a row and every row resolves (and with --check, the file is the generated
one byte for byte); 1 otherwise, naming each gap; 2 when it compared nothing (no pass gate, or no row) or
cannot read what it needs.

    python3 scripts/g11_table_gen.py --repo DIR --name ALICE-<crate> (--write | --check)
        [--catalog FILE]      the shared-rows catalog (default: conformance/g11-shared-rows.toml next to
                              this script's scripts/ directory)
        [--law REV=DIR ...]   read ALICE-Law at REV from DIR instead of fetching it (the tests)
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import re
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("g11_table_check", HERE / "g11_table_check.py")
chk = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(chk)

CATALOG = HERE.parent / "conformance" / "g11-shared-rows.toml"
OWN = "conformance/g11-own.toml"
FIELDS = ("gate", "checker", "canary", "zero", "shared")
HEADER = """\
# ALICE-Law G11 table of this repository: one row per checker of a gate alice-law-conformance.toml declares
# pass. Generated by ALICE-Law's scripts/g11_table_gen.py (fetched at the revision .github/g11-table-pin
# names): the rows of shared checkers come from ALICE-Law's conformance/g11-shared-rows.toml, the other rows
# are conformance/g11-own.toml copied. Edit conformance/g11-own.toml, not this file.
"""


def gate_key(row: dict) -> tuple:
    m = re.fullmatch(r"G(\d+)", str(row.get("gate", "")))
    return (int(m[1]) if m else 1 << 30, str(row.get("gate", "")), str(row.get("checker", "")))


def mentions(text: str, path: str) -> bool:
    """`path` occurs in `text` as a whole path (not as the tail of a longer one)"""
    return re.search(r"(?<![\w./-])" + re.escape(path) + r"(?![\w.-])", text) is not None


def value(v) -> str:
    if isinstance(v, list):
        return "[" + ", ".join(value(x) for x in v) + "]"
    return json.dumps(v, ensure_ascii=False)


def render(rows: list[dict]) -> str:
    out = [HEADER]
    for r in rows:
        out.append("\n[[row]]\n")
        for k in FIELDS:
            out.append(f"{k} = {value(r[k])}\n")
    return "".join(out)


RUN_TESTS_RE = re.compile(r"scripts/run_tests\.sh\s+(?P<names>\S+)\s+--(?:\s|$)")


def leg_gap(tree, checker: str, canary: str) -> str | None:
    """When the checker is a place in a workflow or in scripts/preflight.sh that runs scripts/run_tests.sh,
    the canary must be a test of a binary that line names: run_tests.sh's zero test says nothing about a leg
    the canary does not run in. None otherwise, or when the line cannot be read (the check names that)."""
    m = chk.ANCHOR_REF_RE.match(checker or "")
    if not m or chk.anchor_gap(tree, m["path"], m["token"]):
        return None
    text = tree.read(m["path"]) or ""
    token = m["token"].split(">")[-1]
    at = text.find(token, text.find(m["token"].split(">")[0]) if ">" in m["token"] else 0)
    line = text[text.rfind("\n", 0, at) + 1:text.find("\n", at) if text.find("\n", at) >= 0 else len(text)]
    leg = RUN_TESTS_RE.search(line)
    if not leg:
        return None
    names = {n.split("=")[0] for n in leg["names"].split(",")}
    c = chk.RS_REF_RE.match(canary or "")
    binary = Path(c["path"]).stem if c and "/tests/" in "/" + c["path"] else None
    if binary not in names:
        return f"canary {canary} is not a test of a binary this run_tests.sh line names ({', '.join(sorted(names))})"
    return None


def load_catalog(text: str) -> list[dict]:
    entries = tomllib.loads(text).get("checker", [])
    seen = set()
    for i, e in enumerate(entries, 1):
        for k in ("path", "canary", "zero", "shared"):
            if not e.get(k):
                raise ValueError(f"catalog entry {i}: no {k}")
        if not isinstance(e["shared"], list) or not all(isinstance(p, str) for p in e["shared"]):
            raise ValueError(f"catalog entry {i} ({e['path']}): shared must be a list of paths")
        if e["path"] not in e["shared"]:
            raise ValueError(f"catalog entry {i} ({e['path']}): shared does not list the checker itself")
        if e["path"] in seen:
            raise ValueError(f"catalog entry {i}: {e['path']} is listed twice")
        seen.add(e["path"])
    return entries


def generate(tree, name: str, law_at, catalog: list[dict]) -> tuple[list[dict], list[str], int]:
    """(rows, gaps, pass gates); raises ValueError when it cannot read what it needs"""
    try:
        manifest = tomllib.loads(tree.read(chk.MANIFEST) or "")
    except tomllib.TOMLDecodeError as e:
        raise ValueError(f"{chk.MANIFEST}: {e}")
    passing = sorted((g for g, v in manifest.items()
                      if isinstance(v, dict) and v.get("status") == "pass" and g != "G11"),
                     key=lambda g: gate_key({"gate": g}))
    own: list[dict] = []
    if OWN in tree.paths:
        try:
            own = tomllib.loads(tree.read(OWN) or "").get("row", [])
        except tomllib.TOMLDecodeError as e:
            raise ValueError(f"{OWN}: {e}")

    cache: dict[str, tuple] = {}

    def law(pin: str):
        if pin not in cache:
            rev, why = chk.pin_rev(tree, pin)
            if why:
                cache[pin] = (None, f"law@{pin}: {why}")
            else:
                lt = law_at(rev)
                cache[pin] = (lt, None) if lt is not None else (None, f"law@{pin}: ALICE-Law {rev} could not be read")
        return cache[pin]

    lt, why = law(chk.SHARED_PIN.removeprefix(".github/"))
    if why:
        raise ValueError(why)
    try:
        table = tomllib.loads(lt.read("conformance/shared-files.toml") or "").get("file", [])
    except tomllib.TOMLDecodeError as e:
        raise ValueError(f"conformance/shared-files.toml: {e}")
    mine = {f.get("path") for f in table if name in f.get("repos", [])}

    gaps: list[str] = []
    rows: list[dict] = []
    for g in passing:
        evidence = "\n".join(e for e in manifest[g].get("evidence", []) if isinstance(e, str))
        for e in catalog:
            if e["path"] in mine and mentions(evidence, e["path"]):
                rows.append({"gate": g, "checker": e["path"], "canary": e["canary"], "zero": e["zero"],
                             "shared": [p for p in e["shared"] if p in mine]})
    made = {(r["gate"], r["checker"]) for r in rows}
    for i, r in enumerate(own, 1):
        missing = [k for k in FIELDS if k not in r]
        if missing:
            gaps.append(f"{OWN} row {i}: no {', '.join(missing)}")
            continue
        if (r["gate"], r["checker"]) in made:
            gaps.append(f"{OWN} row {i} ({r['gate']}): {r['checker']} is a shared checker; its row is generated")
            continue
        rows.append({k: r[k] for k in FIELDS})
    rows.sort(key=gate_key)

    for r in rows:
        for field in ("canary", "zero"):
            gap = chk.ref_gap(tree, r[field], law)
            if gap:
                gaps.append(f"{r['gate']} {r['checker']}: {field} {gap}")
        gap = leg_gap(tree, r["checker"], r["canary"])
        if gap:
            gaps.append(f"{r['gate']} {r['checker']}: {gap}")
    covered = {r["gate"] for r in rows}
    for g in passing:
        if g not in covered:
            gaps.append(f"{g} is pass and has no row (no shared checker of this crate is named in its evidence, "
                        f"and {OWN} has none)")
    return rows, gaps, len(passing)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--repo", required=True, type=Path)
    ap.add_argument("--name", required=True)
    ap.add_argument("--catalog", type=Path, default=CATALOG)
    ap.add_argument("--law", action="append", default=[], metavar="REV=DIR")
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    local = {}
    for spec in a.law:
        rev, _, d = spec.partition("=")
        local[rev] = chk.Tree.of_dir(Path(d))
    try:
        catalog = load_catalog(a.catalog.read_text(encoding="utf-8"))
        rows, gaps, gates = generate(chk.Tree.of_dir(a.repo), a.name, lambda rev: local.get(rev) or chk.git_law(rev),
                                     catalog)
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError, ValueError) as e:
        print(f"g11_table_gen: {e}", file=sys.stderr)
        return 2
    text = render(rows)
    target = a.repo / chk.TABLE
    if a.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(text.encode("utf-8"))
    else:
        try:
            have = target.read_bytes().decode("utf-8")
        except (OSError, UnicodeDecodeError):
            have = None
        if have != text:
            gaps.append(f"{chk.TABLE} is not the generated table (run scripts/g11_table_gen.py --write)")
    for gap in gaps:
        print(f"error: {gap}", file=sys.stderr)
    generated = sum(1 for r in rows if any(r["checker"] == e["path"] for e in catalog))
    print(f"g11_table_gen: {a.name}: {len(rows)} rows ({generated} from the catalog), {gates} pass gates, "
          f"{len(gaps)} gaps")
    if not rows or not gates:
        print("g11_table_gen: compared nothing (no row or no pass gate)", file=sys.stderr)
        return 2
    return 1 if gaps else 0


if __name__ == "__main__":
    sys.exit(main())
