class InputError(Exception):
    """an input that cannot be read, or a manifest the block must not render"""


def show(repo: str, rev: str, path: str) -> str | None:
    """the file at rev, or None when it is not there"""
    r = subprocess.run(["git", "-C", repo, "show", f"{rev}:{path}"], capture_output=True)
    if r.returncode != 0:
        return None
    return r.stdout.decode("utf-8")


def resolve(repo: str, rev: str) -> str:
    r = subprocess.run(["git", "-C", repo, "rev-parse", "--verify", f"{rev}^{{commit}}"], capture_output=True,
                       text=True)
    if r.returncode != 0:
        raise InputError(f"{repo}: no commit {rev} (fetch it)")
    return r.stdout.strip()


def cell(text: str) -> str:
    """one table cell: one line, `|` escaped, cut at a word boundary"""
    t = " ".join(re.sub(r"<[^<>]*>", " ", str(text)).split()).replace("|", "\\|")  # one inert line
    if len(t) > NOTE_LEN:
        t = t[:NOTE_LEN].rsplit(" ", 1)[0] + " …"
    return t


def law_facts(law: str, rev: str, crate: str) -> dict:
    roster_text = show(law, rev, "release-train.toml")
    gates_text = show(law, rev, "conformance/gates.toml")
    e2e_toml = show(law, rev, "e2e/Cargo.toml")
    e2e_test = show(law, rev, "e2e/tests/law_to_storage_roundtrip.rs")
    golden = show(law, rev, "e2e/golden/run.digest")
    if None in (roster_text, gates_text, e2e_toml, e2e_test, golden):
        raise InputError(f"ALICE-Law {rev[:12]}: an input file is missing")
    roster = tomllib.loads(roster_text).get("crate", {})
    if crate not in roster:
        raise InputError(f"{crate} is not in release-train.toml at ALICE-Law {rev[:12]}")
    entry = roster[crate]
    dm = roster.get("alice-det-math", {}).get("version")
    sid = re.search(r'const SEMANTICS_HEX: &str = "([0-9a-f]{64})";', e2e_test)
    if dm is None or sid is None:
        raise InputError(f"ALICE-Law {rev[:12]}: no alice-det-math entry or no SEMANTICS_HEX")
    deps = tomllib.loads(e2e_toml).get("dependencies", {})
    req = deps.get(crate)
    if isinstance(req, dict):
        req = req.get("version")
    workflow = show(law, rev, ".github/workflows/e2e.yml") or ""
    gates = tomllib.loads(gates_text).get("gate", [])
    if not gates:
        raise InputError(f"ALICE-Law {rev[:12]}: conformance/gates.toml lists no gate")
    return {
        "version": entry.get("version", "?"), "state": entry.get("state", "?"),
        "law_dependency": entry.get("law-dependency", True), "det_math": dm, "semantics": sid.group(1),
        "e2e_req": req, "digest": golden.strip(), "manifest_path": entry.get("manifest-path", "Cargo.toml"),
        # the job that requires the two digests to be equal, and both runners named whole
        "arches": (bool(re.search(r"^\s+digest-compare:\s*$", workflow, re.M))
                   and bool(re.search(r"runner:\s*macos-15\s*$", workflow, re.M))
                   and bool(re.search(r"runner:\s*macos-15-intel\s*$", workflow, re.M))),
        "gates": [(g["id"], g["name"]) for g in gates],
    }


def crate_facts(repo: str, rev: str, manifest_path: str = "Cargo.toml") -> dict:
    """the crate's alice-det-math requirement and features (from its manifest, `manifest-path` in the roster
    for a crate inside a workspace), and the repository's conformance manifest"""
    cargo = show(repo, rev, manifest_path)
    if cargo is None:
        raise InputError(f"{repo}: no {manifest_path} at {rev}")
    data = tomllib.loads(cargo)
    tables = [data.get("dependencies", {})] + [t.get("dependencies", {}) for t in data.get("target", {}).values()]
    dm = None
    for table in tables:
        for key, spec in table.items():
            package = spec.get("package", key) if isinstance(spec, dict) else key
            if package == "alice-det-math":  # also a renamed or target-specific dependency
                dm = spec
                break
        if dm is not None:
            break
    if isinstance(dm, dict) and dm.get("workspace"):
        root = show(repo, rev, "Cargo.toml")
        dm = tomllib.loads(root or "").get("workspace", {}).get("dependencies", {}).get("alice-det-math")
    if isinstance(dm, dict):
        dm = dm.get("version")
    declared = data.get("features", {})
    features = {k for k in declared if k != "default"}
    # an optional dependency is a feature of its own unless a feature names it as `dep:<name>`
    named = {v[4:] for values in declared.values() for v in values if isinstance(v, str) and v.startswith("dep:")}
    for table in tables:
        for key, spec in table.items():
            if isinstance(spec, dict) and spec.get("optional") and key not in named:
                features.add(key)
    features = sorted(features)
    text = show(repo, rev, MANIFEST)
    manifest = tomllib.loads(text) if text is not None else None
    return {"det_math": dm, "features": features, "manifest": manifest}


# a path: a first word with a `/` in it, or a file name with an extension
PATH_TOKEN_RE = re.compile(r"^(?:[\w.\-]*/[\w.\-/]*|[\w.\-]+\.(?:rs|toml|py|yml|yaml|md|sh|txt|json))$")


def evidence_list(where: str, evidence) -> list[str]:
    """the evidence as a list of strings (a single string or another type is refused, not iterated);
    empty strings are not evidence"""
    if evidence is None:
        return []
    if not isinstance(evidence, list) or not all(isinstance(e, str) for e in evidence):
        raise InputError(f"{MANIFEST} {where}: evidence must be a list of strings")
    return [e for e in evidence if e.strip()]


def warn(text: str) -> None:
    print(f"warning: {text}", file=sys.stderr)


def missing_evidence(repo: str, rev: str, evidence: list) -> list[str]:
    """the evidence entries that name a path (their first word has a `/` or a file extension) not at rev"""
    out = []
    for e in evidence:
        token = str(e).split(" ", 1)[0]
        if PATH_TOKEN_RE.match(token) and show_exists(repo, rev, token.rstrip("/")) is False:
            out.append(token)
    return out


def show_exists(repo: str, rev: str, path: str) -> bool:
    return subprocess.run(["git", "-C", repo, "cat-file", "-e", f"{rev}:{path}"], capture_output=True).returncode == 0


def gate_rows(manifest: dict | None, gates: list, repo: str = "", rev: str = "") -> list[tuple[str, str, str]]:
    rows = []
    for gid, name in gates:
        e = (manifest or {}).get(gid)
        if not isinstance(e, dict) or "status" not in e:
            rows.append((f"{gid} {name}", "undeclared", ""))
            continue
        status = e["status"]
        if status in LEGACY:
            warn(f"{MANIFEST} {gid}: status {status!r} is the earlier vocabulary, read as {LEGACY[status]!r}")
            status = LEGACY[status]
        if status not in STATUSES:
            raise InputError(f"{MANIFEST} {gid}: status {status!r} is not one of {STATUSES}")
        evidence = evidence_list(gid, e.get("evidence"))
        gone = missing_evidence(repo, rev, evidence) if repo else []
        if gone:
            raise InputError(f"{MANIFEST} {gid}: evidence names paths that are not in the crate: {gone}")
        if status in ("fail-known", "n/a") and not str(e.get("note", "")).strip():
            raise InputError(f"{MANIFEST} {gid}: {status} without a note")
        if status in ("pass", "n/a") and (not evidence or not str(e.get("mutant", "")).strip()):
            # a pass the manifest does not back with evidence and a mutant is not shown as met
            warn(f"{MANIFEST} {gid}: {status} without " + ("evidence" if not evidence else "a mutant")
                 + ", shown as unverified")
            status = "unverified"
        rows.append((f"{gid} {name}", status, cell(e.get("note", ""))))
    return rows


def feature_rows(manifest: dict | None, features: list[str], repo: str = "", rev: str = "") -> list[tuple[str, str, str]]:
    declared = (manifest or {}).get("features", {})
    rows = []
    for f in features:
        e = declared.get(f)
        if not isinstance(e, dict) or e.get("guarantee") not in ("inside", "outside"):
            rows.append((f"`{f}`", "undeclared", ""))
            continue
        evidence = evidence_list(f"features.{f}", e.get("evidence"))
        if e["guarantee"] == "inside" and not evidence:
            raise InputError(f"{MANIFEST} features.{f}: inside the guarantee without evidence")
        gone = missing_evidence(repo, rev, evidence) if repo else []
        if gone:
            raise InputError(f"{MANIFEST} features.{f}: evidence names paths that are not in the crate: {gone}")
        rows.append((f"`{f}`", e["guarantee"], cell(e.get("note", ""))))
    unknown = sorted(set(declared) - set(features))
    if unknown:
        raise InputError(f"{MANIFEST} features: {unknown} are not features of the crate")
    return rows


def render(law: str, law_rev: str, crate: str, repo: str, crate_rev: str, lang: str) -> str:
    sha = resolve(law, law_rev)
    lf = law_facts(law, sha, crate)
    cf, t = crate_facts(repo, crate_rev, lf["manifest_path"]), TEXT[lang]
    st = t["st"]
    req = (t["req_self"] if crate == "alice-det-math"
           else f'`alice-det-math = "{cf["det_math"]}"`' if cf["det_math"] else t["req_none"])
    e2e = (t["e2e_in"].format(name=crate, req=lf["e2e_req"], digest=lf["digest"],
                              arches=t["arches"] if lf["arches"] else "")
           if lf["e2e_req"] else t["e2e_out"])
    out = [f"<!-- law-integration:begin law={sha} -->", t["title"], "", t["generated"].format(law=sha[:12]), "",
           "| | |", "|---|---|",
           f"| {t['train']} | " + t["train_v"].format(crate=crate, version=lf["version"], state=lf["state"],
                                                      dep=t["yes"] if lf["law_dependency"] else t["no"]) + " |",
           f"| {t['arith']} | " + t["arith_v"].format(dm=lf["det_math"], sid=lf["semantics"], req=req,
                                                      req_lead="" if crate == "alice-det-math" else t["req_lead"]) + " |",
           f"| {t['e2e']} | {e2e} |", "", t["conf"], ""]
    if cf["manifest"] is None:
        out += [t["no_manifest"], ""]
    out += [t["gate_h"], "|---|---|---|"]
    out += [f"| {g} | {st[s]} | {n} |" for g, s, n in gate_rows(cf["manifest"], lf["gates"], repo, crate_rev)]
    out += ["", t["feat"], ""]
    frows = feature_rows(cf["manifest"], cf["features"], repo, crate_rev)
    if frows:
        out += [t["feat_h"], "|---|---|---|"] + [f"| {f} | {st[s]} | {n} |" for f, s, n in frows]
    else:
        out.append(t["no_features"])
    out.append(END)
    return "\n".join(out) + "\n"


def blocks(text: str) -> list[tuple[str, str]]:
    """(pinned revision, block text) of each block in a README"""
    found = []
    for m in BEGIN_RE.finditer(text):
        end = text.find(END, m.start())
        if end == -1:
            raise InputError("a begin marker without an end marker")
        found.append((m.group(1), text[m.start():end + len(END)] + "\n"))
    return found


# hand-written conformance claims outside the block: a closed list (a gate id, "Law-conformant" and its forms,
# "conforms to the Law", "Law に準拠 / 適合"); the words alone are not claims ("IEEE 準拠", "a conformance
# claim", a file named alice-law-conformance.toml), measured on the chain READMEs before this list was fixed
_LAW = r"(?:the\s+)?(?:ALICE[- ])?Law\b"
CLAIM_RE = re.compile(r"\bG(?:1[0-4]|[1-9])\b"
                      r"|\b(?:ALICE[- ])?Law[- ](?:conformant|conforming|compliant)\b"
                      r"|\bLaw\s+gates?\b"
                      r"|\bconform(?:s|ing|ant)?\s+(?:to|with)\s+" + _LAW +
                      r"|\bcompl(?:y|ies|iant|iance)\s+with\s+" + _LAW +
                      r"|(?:ALICE[- ])?Law\s*(?:に|へ)?\s*(?:準拠|適合)", re.I)


# a line that is only a link to the gate definitions ("- [Conformance](…/docs/CONFORMANCE.md#g12)"):
# its target (an anchor such as #g12) is not a claim, its text still is checked
LINK_ONLY_RE = re.compile(r"\s*(?:[-*+]\s+)?\[([^\]]*)\]\([^)\s]*CONFORMANCE\.md(?:#[^)\s]*)?\)\s*")


def outside_claims(text: str) -> list[int]:
    """line numbers of claims outside the markers (code fences ignored; on a line that is only a link to
    docs/CONFORMANCE.md, only the link text is read)"""
    hits, inside, fence = [], False, False
    for n, line in enumerate(text.splitlines(), 1):
        if BEGIN_RE.match(line):
            inside = True
        if not inside:
            if line.lstrip().startswith("```"):
                fence = not fence
            elif not fence:
                link = LINK_ONLY_RE.fullmatch(line)
                if CLAIM_RE.search(link.group(1) if link else line):
                    hits.append(n)
        if line == END:
            inside = False
    return hits


def on_main(law: str, sha: str, main: str) -> bool:
    return subprocess.run(["git", "-C", law, "merge-base", "--is-ancestor", sha, main],
                          capture_output=True).returncode == 0


def check(law: str, crate: str, repo: str, crate_rev: str, lint: str, law_main: str = "origin/main") -> int:
    compared, problems, pins = 0, [], set()
    resolve(law, law_main)
    for lang, name in readme_names(lambda n: show(repo, crate_rev, n) is not None).items():
        text = show(repo, crate_rev, name)
        if text is None:
            problems.append(f"{name}: missing")
            continue
        found = blocks(text)
        if len(found) != 1:
            problems.append(f"{name}: {len(found)} law-integration blocks (want 1)")
            continue
        pin, got = found[0]
        pins.add(pin)
        if not on_main(law, resolve(law, pin), law_main):
            problems.append(f"{name}: the pinned ALICE-Law revision {pin[:12]} is not on {law_main}")
        want = render(law, pin, crate, repo, crate_rev, lang)
        compared += 1
        if got != want:
            problems.append(f"{name}: the block differs from the one generated at ALICE-Law {pin[:12]} "
                            f"(run `gen-law-readme-block.py write --law-ref {pin[:12]} ...`)")
        claims = outside_claims(text)
        if claims:
            msg = f"{name}: conformance wording outside the block on lines {claims}"
            if lint == "error":
                problems.append(msg)
            else:
                print(f"warning: {msg}")
    if len(pins) > 1:
        problems.append(f"README.md and README_JP.md pin different ALICE-Law revisions: {sorted(p[:12] for p in pins)}")
    for p in problems:
        print(f"law-readme-block: {p}")
    if compared == 0:
        print("law-readme-block: no block was compared", file=sys.stderr)
        return 2
    print(f"law-readme-block: {compared} blocks compared, {len(problems)} problems")
    return 1 if problems else 0


def write(law: str, law_rev: str, crate: str, repo: str) -> int:
    # the block is rendered from the committed inputs: refuse while they have uncommitted changes
    inputs = [law_facts(law, resolve(law, law_rev), crate)["manifest_path"], MANIFEST]
    dirty = subprocess.run(["git", "-C", repo, "status", "--porcelain", "--", *inputs], capture_output=True,
                           text=True).stdout.strip()
    if dirty:
        raise InputError(f"{repo}: commit {', '.join(inputs)} first (the block is generated from the commit)")
    for lang, name in readme_names(lambda n: Path(repo, n).exists()).items():
        path = Path(repo, name)
        if not path.exists():
            raise InputError(f"{path}: missing (create it first)")
        text = path.read_text(encoding="utf-8")
        block = render(law, law_rev, crate, repo, "HEAD", lang)
        found = blocks(text)
        if len(found) > 1:
            raise InputError(f"{path}: more than one block")
        if found:
            text = text.replace(found[0][1], block, 1) if found[0][1] in text else text.replace(
                found[0][1].rstrip("\n"), block.rstrip("\n"), 1)
        else:
            m = LICENSE_HEADING[lang].search(text)
            if m is None:
                raise InputError(f"{path}: no License heading to place the block before")
            text = text[:m.start()] + block + "\n" + text[m.start():]
        path.write_text(text, encoding="utf-8")
        print(f"law-readme-block: wrote {path}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("render", "write", "check"):
        p = sub.add_parser(name)
        p.add_argument("--law", required=True, help="an ALICE-Law checkout")
        p.add_argument("--crate", required=True, help="the crate's name in release-train.toml")
        p.add_argument("--crate-repo", required=True)
        if name != "check":
            p.add_argument("--law-ref", required=True, help="the ALICE-Law revision to generate from")
        if name != "write":
            p.add_argument("--crate-ref", default="HEAD")
        if name == "render":
            p.add_argument("--lang", choices=sorted(README), required=True)
        if name == "check":
            p.add_argument("--lint", choices=("warn", "error"), default="warn")
            p.add_argument("--law-main", default="origin/main", help="the pin must be on this ALICE-Law ref")
    a = ap.parse_args(argv)
    try:
        if a.cmd == "render":
            sys.stdout.write(render(a.law, a.law_ref, a.crate, a.crate_repo, a.crate_ref, a.lang))
            return 0
        if a.cmd == "write":
            return write(a.law, a.law_ref, a.crate, a.crate_repo)
        return check(a.law, a.crate, a.crate_repo, a.crate_ref, a.lint, a.law_main)
    except (InputError, tomllib.TOMLDecodeError, UnicodeDecodeError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
