#!/usr/bin/env python3
"""Generate, check and write the "ALICE-Law integration" block of a crate's README.

The block states what this repository knows about a crate at one of its revisions:
its release-train entry, the arithmetic generation of the train (the alice-det-math
release and the arithmetic identifier the end to end test pins), whether the end to
end check covers it and with which digest, its G1-G14 conformance as its own
`alice-law-conformance.toml` declares it, and which of its features are inside the
guarantee. It is generated, so a README cannot state more than the manifest does.

The block is a pure function of (the ALICE-Law revision it names, the crate's
`alice-law-conformance.toml` and `Cargo.toml` at the crate commit): no date, no run
id. The revision is written into the block's begin marker, and `check` regenerates
at that revision, so a later change in ALICE-Law does not turn a crate's README
stale on its own; how far the pin is behind is reported here, not by the crate.

    gen-law-readme-block.py render --law DIR --law-ref REV --crate NAME --crate-repo DIR [--crate-ref REV] --lang en|ja
    gen-law-readme-block.py write  --law DIR --law-ref REV --crate NAME --crate-repo DIR
    gen-law-readme-block.py check  --law DIR --crate NAME --crate-repo DIR [--crate-ref REV] [--lint warn|error]

The Japanese README is README_JP.md or README_ja.md, whichever the repository has (both is an error).
`write` puts the block into README.md and the Japanese README of the crate checkout
(replacing the one there, or placing it before the License section). `check` reads
both files at the crate ref: exit 0 when each has exactly one block equal to the
block generated at its pinned revision, 1 when one is missing, differs or the files
disagree on the pin, 2 when nothing was compared or an input cannot be read. A
manifest entry with `status = "pass"` and no evidence, or a feature marked inside
the guarantee without evidence, is refused (exit 2): the block never shows a pass
the manifest does not back. A gate the manifest does not list, and every gate of a
crate with no manifest, is shown as not declared, never as pass.

Outside the markers, `check` also reports conformance claims written by hand (a
closed list of words, code fences and links to docs/CONFORMANCE.md ignored); with
`--lint error` they fail the check. `write` refuses a README without a License
heading to place a new block before (nothing is written), and refuses while the
crate's Cargo.toml or manifest have uncommitted changes. Python 3.11 or later
(tomllib).
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tomllib
from pathlib import Path

BEGIN_RE = re.compile(r"^<!-- law-integration:begin law=([0-9a-f]{40}) -->$", re.M)
END = "<!-- law-integration:end -->"
MANIFEST = "alice-law-conformance.toml"
STATUSES = ("pass", "fail-known", "unverified", "n/a")
LEGACY = {"missing": "unverified"}  # read with a warning until the release-train manifests are rewritten
README = {"en": "README.md", "ja": "README_JP.md"}
# the Japanese README goes by one of these names in the release-train repositories
JA_NAMES = ("README_JP.md", "README_ja.md")


def readme_names(exists) -> dict[str, str]:
    """{lang: file name}: README.md, and the one Japanese README present (README_JP.md when none is);
    both Japanese names present is an input error"""
    ja = [n for n in JA_NAMES if exists(n)]
    if len(ja) > 1:
        raise InputError(f"both {' and '.join(ja)} are present: keep one Japanese README")
    return {"en": "README.md", "ja": ja[0] if ja else JA_NAMES[0]}
LICENSE_HEADING = {"en": re.compile(r"^## License\b", re.M), "ja": re.compile(r"^## ライセンス", re.M)}
NOTE_LEN = 160

