#!/usr/bin/env python3
"""ALICE-Law G11 (c): files shared byte for byte across the ALICE crates.

conformance/shared-files.toml (generated by scripts/gen_shared_files.py) has one [[file]]
entry per shared file: its path, the repositories that carry it (with a path for one that
keeps it elsewhere, and an exemption with its reason for one that legitimately has a
different file at the same path), and either

  - the SHA-256 of its bytes and a source commit on the source repository's main that has
    those bytes (a uniform file), or
  - `pending`: the copies differ today. `variants` maps each SHA-256 found to the
    repositories that have it ("absent" for a listed repository without the file), `target`
    is the SHA-256 that becomes the file's bytes and `owner` the repository that holds them,
    `since` is the date the row became pending and `exit` says what ends it. A pending row
    pins no bytes; a crate's cell is a pass only while each of its own copies on pending rows
    is the row's target (a row still pending on other mains does not hold the crate back:
    --repo prints the copies that are not, and g11_self_check.py refuses a G11 pass while any
    is not); the row is listed and counted in every mode, and one older than PENDING_MAX_DAYS days is a finding (pending is not a parking
    place). A planned row (`planned` = the git blob id the shared-file registry moves the
    file to) is a rollout in progress: its owner has landed the new bytes first. The owner's
    main must hold the target (its SHA-256 and its blob id equal to `planned`), a planned row
    all of whose copies have the target is a finding (it has converged: regenerate), and one
    older than PLANNED_MAX_DAYS days is a finding. A planned row re-rolled to bytes no main
    holds yet records `moved_from` = { planned, target } of the bytes it moves from: its owner
    may hold either pair, a copy may hold an older variant the table recorded (a re-roll found
    mid-rollout: a counted stale copy), and any other value is a finding; --base-table refuses a
    moving row that records a variant the base did not have. With --base-table, a table with more
    unplanned pending rows than the base is a finding (a planned row may be born; an
    unplanned divergence may not grow), and so is a row pending in both whose `since` is
    later than the base's (the age limits cannot be restarted by editing the date), a
    planned row whose planned id differs from the base's without `moved_from` naming the
    base's planned id and target (or a `moved_from` the base does not explain), and a planned
    row of the base that the table no longer lists or lists as uniform at other bytes than its
    target: a planned row leaves the table only at its target (closed by hand and planned
    again later, its clock would restart), so a wrong plan is rolled forward.

    The first move of a uniform row (`first_move = true`): the row is planned before any main
    holds the new bytes, because no copy could take them first (each repository's check
    refuses a copy the table does not record). --base-table accepts it only from a base row
    that is uniform with exactly the bytes `moved_from` names and with every copy recorded at
    them. Before the owner lands it, a first move (and a new file) may be re-rolled to other
    bytes in one commit, from the same bytes as the base's move, keeping its date and the flag;
    a second planned move from other bytes is refused until the first has landed. Live:
    until the owner's main holds the target, the planned bytes must be real: either the owner has
    the planned blob at the path on the tip of its main or a ci/ branch with the target's SHA-256,
    or the table's own repository carries them as `planned/<blob>` next to the table (a file whose
    git blob id is the row's `planned` and whose SHA-256 is its `target`; the owner's check refuses
    a copy its pinned table does not record, so once the crates carry that check the owner cannot
    push the bytes to a ci/ branch before the row exists),
    every other copy is the uniform bytes (no third value, no missing copy), and the owner
    lands within FIRST_MOVE_MAX_DAYS days; the flag stays until the row shows the owner holding
    the target (--base-table), and live reads that record against the owner's main (a planned
    row recording the owner at the target must find its main there). A pending row dated after
    today is a finding (live).

A repository that legitimately has a different file at a shared path is exempted on that
path's entry with its reason, or with `{ reason, until = "YYYY-MM-DD" }` for one that is
converging: after `until` its copy must have the row's bytes (a uniform row's sha256, a pending
row's target), live and in --repo, so the exemption cannot outlive its reason. The discovery
scope itself has no exceptions. A path that looks
shared but is per-repository data (each repository's own content) is an entry with `repos =
[]` and every repository that has it exempted: it pins nothing and compares nothing, and a
repository that gains the path without an exemption is a finding.

  shared_files_check.py --table TABLE [--base-table BASE]
      the schema only (offline: preflight and branch CI), and the pending ratchet
  shared_files_check.py --table TABLE --fetch
      also each uniform entry's source commit fetched from GitHub: an ancestor of its
      repository's main, with the entry's bytes at the entry's path
  shared_files_check.py --table TABLE --live [--expect-copies N] [--today YYYY-MM-DD]
      every listed repository's main fetched from GitHub: each copy of a uniform file equal
      to its entry (with --expect-copies N, exactly N copies of uniform rows compared: the
      lock moves only with the table, since a pending row's copies come and go as its
      rollout lands); the variants of each pending row listed (not a finding); a pending row
      past its time is a finding; and a discovery pass over every file under DISCOVERED of
      the table's repositories: one byte-identical in two or more of them with no entry, or
      a copy of a table path with other bytes in a repository the entry neither lists nor
      exempts, is a finding; a copy with the entry's bytes (or one of a pending row's
      variants) in such a repository is an unlisted holder, a counted note with the date it
      appeared there, because a rollout lands before the table is regenerated (--strict
      makes it a finding: the regeneration and landing path of this repository and the
      pre-publish gate run strict, so the table cannot stay stale into a release) (a shared copy outside DISCOVERED, under tests/ or src/, is checked only once a
      row names it)
  shared_files_check.py --table TABLE ... --lock-file FILE
      in any mode, also the count lock written in FILE (the one `--expect-copies N` of
      .github/workflows/conformance-live.yml) against the table: N must be the number of
      copies of uniform rows the table lists, so a table change that moves it without the
      lock is red offline (preflight, branch CI and the strict pair) instead of only on main
      (gen_shared_files.py --write --lock-file FILE writes both)
  shared_files_check.py --table TABLE --repo DIR --name ALICE-X
      a crate's tree: each uniform file listed for ALICE-X present with the entry's bytes;
      each pending file listed for it present as one of the row's variants (listed as
      pending; the copies that are not yet its target, absent ones included, are printed as
      "own copies not at a pending row's target: N", and the cell is not a pass while N > 0); a table path present for an entry that
      neither lists nor exempts ALICE-X is a finding, except a copy with exactly a uniform
      entry's bytes or a pending row's target, which is a counted "adopting" note (the commit
      that adds a shared file to a crate cannot be listed first; the Law side's strict check
      makes the next table list it)

Every mode prints `compared: files N, repos M, copies K, pending P`. Exit 0 when everything
compared is equal, 1 on a finding, 2 when nothing was compared or the input cannot be read
(an empty table, a crate the table never names, a fetch that failed, no repository read).
"""
from __future__ import annotations

import argparse
import collections
import datetime
import hashlib
import re
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

HEX40 = re.compile(r"^[0-9a-f]{40}$")
HEX64 = re.compile(r"^[0-9a-f]{64}$")
REPO = re.compile(r"^ALICE-[A-Za-z0-9-]+$")
# the account's product repositories outside the ALICE-* names that hold copies of the Law tooling: each entry is
# sha256(<the repository name, lower case>), so the list names none of them; a name is one of them only when it is
# already in lower case and its hash is listed
PRODUCT_REPO_HASHES = {
    "02a148b01541d8673d3b2ada504d8e3cdcf7725fefaac791004ff60620516970",
}
PRODUCT_REPO = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")


def is_repo_name(name: object) -> bool:
    """an ALICE-* repository, or a product repository of PRODUCT_REPO_HASHES: the one rule every check that reads a
    repository name uses"""
    if not isinstance(name, str):
        return False
    if REPO.match(name):
        return True
    return bool(PRODUCT_REPO.match(name)) and hashlib.sha256(name.encode("utf-8")).hexdigest() in PRODUCT_REPO_HASHES


DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
GITHUB = "https://github.com/ext-sakamoro/"
MIN_REASON = 12
PENDING_MAX_DAYS = 21
PLANNED_MAX_DAYS = 14
# the count lock in a workflow: exactly one `--expect-copies N`
LOCK = re.compile(r"--expect-copies[ =]+(\d+)")
DISCOVERED = ("scripts/", "tools/", ".github/workflows/", ".github/actions/")
UNIFORM_KEYS = {"path", "sha256", "source", "repos", "paths", "exempt"}
PENDING_KEYS = {"path", "pending", "repos", "paths", "exempt"}


class Unreadable(Exception):
    """The input cannot be compared (exit 2)."""


def git_blob(data: bytes) -> str:
    """the git blob id of `data` (what the shared-file registry's next= names)"""
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


PLANNED_DIR = "planned"  # next to the table: the bytes of planned rows, by git blob id


def planned_proofs(table: Path) -> dict[str, bytes]:
    """name -> bytes of each file in the planned-bytes directory next to the table (empty when there is none)"""
    d = table.parent / PLANNED_DIR
    if not d.is_dir():
        return {}
    out = {}
    for f in sorted(d.iterdir()):
        if not f.is_file():
            raise Unreadable(f"{f}: the planned-bytes directory holds files only")
        out[f.name] = f.read_bytes()
    return out


def planned_proof_problems(entries: list[dict], proofs: dict[str, bytes]) -> list[str]:
    """each planned-bytes file is named by a pending row's planned id and has that row's bytes, both ways: its git
    blob id is the name and its SHA-256 the row's target. A file no pending row names (a move that converged and was
    regenerated to uniform, or one planted) is a finding, so the directory holds only moves in flight"""
    problems = []
    by_planned = {e["pending"]["planned"]: e for e in entries if is_planned(e)}
    for name, data in sorted(proofs.items()):
        where = f"{PLANNED_DIR}/{name}"
        e = by_planned.get(name)
        if e is None:
            problems.append(f"{where}: no planned row names it (a converged move or a stray file: remove it)")
            continue
        p = e["pending"]
        if git_blob(data) != name:
            problems.append(f"{where}: its git blob id is {git_blob(data)[:12]}, not its name (the row's planned id)")
        if sha256(data) != p["target"]:
            problems.append(f"{where}: sha256 {sha256(data)[:12]}, not the target {p['target'][:12]} of "
                            f"{e['path']}")
    return problems


def is_planned(e: dict) -> bool:
    return "planned" in e.get("pending", {})


def moving_bytes(e: dict) -> set[str]:
    """the SHA-256 a pending row is moving between: its target, and for a planned row moved to new bytes the
    bytes it moves from"""
    p = e["pending"]
    return {p["target"]} | ({p["moved_from"]["target"]} if "moved_from" in p else set())


def pending_counts(entries: list[dict]) -> tuple[int, int]:
    """(planned, unplanned) pending rows"""
    planned = sum(is_planned(e) for e in entries)
    return planned, sum("pending" in e for e in entries) - planned


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def safe_path(p: object) -> bool:
    return (isinstance(p, str) and p != "" and not p.startswith("/") and "\\" not in p
            and all(part not in ("", ".", "..") for part in p.split("/")))


def reason(s: object) -> bool:
    return isinstance(s, str) and len(s.strip()) >= MIN_REASON


def exemption(w: object) -> bool:
    """A reason, or `{ reason = "...", until = "YYYY-MM-DD" }`: after `until` the copy must be the row's bytes."""
    if reason(w):
        return True
    if not isinstance(w, dict) or set(w) != {"reason", "until"} or not reason(w["reason"]):
        return False
    # DATE first: fromisoformat also reads other forms (an ISO week date, digits without dashes) on newer
    # interpreters, so the same table would read differently per Python
    if not isinstance(w["until"], str) or not DATE.match(w["until"]):
        return False
    try:
        datetime.date.fromisoformat(w["until"])
    except ValueError:
        return False
    return True


def expired(e: dict, name: str, today: datetime.date) -> str | None:
    """The `until` of `name`'s exemption on `e` when it has passed, else None."""
    w = e.get("exempt", {}).get(name)
    if isinstance(w, dict) and datetime.date.fromisoformat(w["until"]) < today:
        return w["until"]
    return None


def row_bytes(e: dict) -> str | None:
    """The bytes an expired exemption's copy must have: a uniform row's sha256, or a pending row's target."""
    return e["sha256"] if "sha256" in e else e["pending"]["target"] if "pending" in e else None


def is_repos(v: object) -> bool:
    return (isinstance(v, list) and bool(v) and all(is_repo_name(r) for r in v)
            and len(set(v)) == len(v) and v == sorted(v))


def load_all(text: str) -> tuple[list[dict], list[dict]]:
    """The [[file]] entries of a table, checked against the schema (and an empty list)."""
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise Unreadable(f"not TOML: {e}") from None
    unknown = set(data) - {"file"}
    if unknown:
        raise Unreadable(f"unknown top-level keys: {sorted(unknown)}")
    files = data.get("file", [])
    if not isinstance(files, list) or not files:
        raise Unreadable("no [[file]] entry (compares nothing)")
    seen: set[str] = set()
    previous = ""
    for i, f in enumerate(files, 1):
        where = f"entry {i}"
        if not isinstance(f, dict):
            raise Unreadable(f"{where}: not a table")
        per_repo = f.get("repos") == []
        keys = ({"path", "repos", "exempt"} if per_repo else PENDING_KEYS if "pending" in f else UNIFORM_KEYS)
        required = {"path", "repos"} | (set() if per_repo else {"pending"} if "pending" in f else {"sha256", "source"})
        if set(f) - keys or required - set(f):
            raise Unreadable(f"{where}: unknown keys {sorted(set(f) - keys)}, missing keys {sorted(required - set(f))}")
        path = f["path"]
        if not safe_path(path):
            raise Unreadable(f"{where}: path {path!r} is not a relative path")
        where = f"entry {path}"
        if path in seen:
            raise Unreadable(f"{where}: listed twice")
        if path < previous:
            raise Unreadable(f"{where}: entries are not sorted by path")
        seen.add(path)
        previous = path
        repos = f["repos"]
        if per_repo:
            if not f.get("exempt"):
                raise Unreadable(f"{where}: a per-repository entry (repos = []) must exempt each repository that has it")
            if any(isinstance(w, dict) for w in f["exempt"].values() if isinstance(f["exempt"], dict)):
                raise Unreadable(f"{where}: a per-repository entry (repos = []) has no bytes to converge on, so its "
                                 "exemptions take a reason, never an until date")
        elif not is_repos(repos):
            raise Unreadable(f"{where}: repos must be a sorted list of distinct repository names (ALICE-… or a listed product)")
        if per_repo:
            pass
        elif "pending" in f:
            p = f["pending"]
            if (not isinstance(p, dict) or set(p) - {"planned", "moved_from", "first_move"}
                    != {"since", "exit", "target", "owner", "variants"}):
                raise Unreadable(f"{where}: pending must be {{ since, exit, target, owner, variants[, planned"
                                 "[, moved_from[, first_move]]] }")
            if "first_move" in p and (p["first_move"] is not True or "moved_from" not in p):
                raise Unreadable(f"{where}: pending.first_move must be true, on a planned row with moved_from (the "
                                 "first move of a uniform row to bytes no main holds yet)")
            if not isinstance(p["target"], str) or not HEX64.match(p["target"]):
                raise Unreadable(f"{where}: pending.target must be the SHA-256 that becomes the file's bytes")
            if not is_repo_name(p["owner"]) or p["owner"] not in repos:
                raise Unreadable(f"{where}: pending.owner must be one of the listed repositories")
            if not isinstance(p["since"], str) or not DATE.match(p["since"]):
                raise Unreadable(f"{where}: pending.since must be YYYY-MM-DD")
            try:
                datetime.date.fromisoformat(p["since"])
            except ValueError:
                raise Unreadable(f"{where}: pending.since is not a date") from None
            if not reason(p["exit"]):
                raise Unreadable(f"{where}: pending.exit must say what ends it (at least {MIN_REASON} characters)")
            v = p["variants"]
            if (not isinstance(v, dict) or len(v) < 1 or not all(HEX64.match(k) or k == "absent" for k in v)
                    or not all(is_repos(rs) for rs in v.values())):
                raise Unreadable(f"{where}: pending.variants must map SHA-256 (or \"absent\") to sorted repositories")
            members = [r for rs in v.values() for r in rs]
            if sorted(members) != repos:
                raise Unreadable(f"{where}: pending.variants must cover each listed repository exactly once")
            if "planned" in p:
                if not isinstance(p["planned"], str) or not HEX40.match(p["planned"]):
                    raise Unreadable(f"{where}: pending.planned must be the 40-hex git blob id the registry moves to")
                held = [p["target"]]
                if "moved_from" in p:
                    m = p["moved_from"]
                    if (not isinstance(m, dict) or set(m) != {"planned", "target"} or not isinstance(m["planned"], str)
                            or not HEX40.match(m["planned"]) or not isinstance(m["target"], str)
                            or not HEX64.match(m["target"])):
                        raise Unreadable(f"{where}: pending.moved_from must be {{ planned = \"<40 hex>\", "
                                         "target = \"<SHA-256>\" }, the rollout's earlier bytes")
                    if m["planned"] == p["planned"] or m["target"] == p["target"]:
                        raise Unreadable(f"{where}: pending.moved_from must name other bytes than the target")
                    held.append(m["target"])  # the owner lands the new bytes after the table records them
                if set(v) == {"absent"}:
                    held.append("absent")  # a new file no listed main holds yet: nothing to move from
                if not any(p["owner"] in v.get(t, []) for t in held):
                    raise Unreadable(f"{where}: a planned row's owner must hold the target in its variants")
            elif "moved_from" in p:
                raise Unreadable(f"{where}: pending.moved_from belongs to a planned row")
        else:
            if not isinstance(f["sha256"], str) or not HEX64.match(f["sha256"]):
                raise Unreadable(f"{where}: sha256 is not 64 lower-case hex digits")
            src = f["source"]
            if (not isinstance(src, dict) or set(src) != {"repo", "rev"} or not isinstance(src["repo"], str)
                    or not is_repo_name(src["repo"]) or not isinstance(src["rev"], str)
                    or not HEX40.match(src["rev"])):
                raise Unreadable(f"{where}: source must be {{ repo = \"<repository name>\", rev = \"<40 hex>\" }}")
            if src["repo"] not in repos:
                raise Unreadable(f"{where}: the source repository {src['repo']} is not in repos")
        alt = f.get("paths", {})
        if not isinstance(alt, dict) or not all(r in repos and safe_path(q) for r, q in alt.items()):
            raise Unreadable(f"{where}: paths must map listed repositories to relative paths")
        ex = f.get("exempt", {})
        if not isinstance(ex, dict) or not all(is_repo_name(r) and r not in repos and exemption(w) for r, w in ex.items()):
            raise Unreadable(f"{where}: exempt must map unlisted repositories (ALICE-… or a listed product) to a reason "
                             f"of at least {MIN_REASON} characters, or to {{ reason, until = \"YYYY-MM-DD\" }}")
    return files, []


def load(text: str) -> list[dict]:
    return load_all(text)[0]


def path_in(entry: dict, name: str) -> str:
    return entry.get("paths", {}).get(name, entry["path"])


def uniform_copies(entries: list[dict]) -> int:
    """the copies of uniform rows the table lists: what --live --expect-copies compares when no copy is missing"""
    return sum(len(e["repos"]) for e in entries if "sha256" in e and "pending" not in e)


def lock_in(text: str, where: str) -> int:
    found = LOCK.findall(text)
    if len(found) != 1:
        raise Unreadable(f"{where}: {len(found)} `--expect-copies N` found, the count lock needs exactly one")
    return int(found[0])


def with_lock(text: str, where: str, n: int) -> str:
    lock_in(text, where)
    return LOCK.sub(lambda m: m.group(0)[: m.start(1) - m.start(0)] + str(n), text)


def counts(files: int, repos: int, copies: int, pending: int) -> tuple[int, int, int, int]:
    return files, repos, copies, pending


def summary(c: tuple[int, int, int, int]) -> str:
    return f"compared: files {c[0]}, repos {c[1]}, copies {c[2]}, pending {c[3]}"


def check_repo(entries: list[dict], root: Path, name: str,
               today: datetime.date | None = None) -> tuple[list[str], list[str], tuple]:
    """Findings, pending notes and counts for a crate's tree."""
    problems: list[str] = []
    notes: list[str] = []
    copies = files = pending = 0
    adopting = 0
    for e in entries:
        if name in e["repos"]:
            files += 1
            rel = path_in(e, name)
            f = root / rel
            if "pending" in e:
                pending += 1
                mine = [k for k, rs in e["pending"]["variants"].items() if name in rs]
                if not f.is_file():
                    if mine != ["absent"]:
                        problems.append(f"{rel}: listed for {name} but missing")
                    else:
                        notes.append(f"{rel}: pending, absent here as recorded ({e['pending']['exit']})")
                    continue
                copies += 1
                got = sha256(f.read_bytes())
                # the target is accepted before a regeneration records it as a variant: it is where the row
                # is going, so a crate that already took it is not drift
                if got not in e["pending"]["variants"] and got not in moving_bytes(e):
                    problems.append(f"{rel}: sha256 {got} is none of the pending row's variants nor its target")
                else:
                    on = "the target" if got == e["pending"]["target"] else "not yet the target"
                    notes.append(f"{rel}: pending since {e['pending']['since']}, {on} "
                                 f"(owner {e['pending']['owner']}: {e['pending']['exit']})")
                continue
            if not f.is_file():
                problems.append(f"{rel}: listed for {name} but missing")
                continue
            copies += 1
            got = sha256(f.read_bytes())
            if got != e["sha256"]:
                problems.append(f"{rel}: sha256 {got}, the table has {e['sha256']} "
                                f"(the bytes of {e['source']['repo']} at {e['source']['rev'][:12]})")
        elif name in e.get("exempt", {}):
            until = expired(e, name, today or datetime.datetime.now(datetime.timezone.utc).date())
            f = root / e["path"]
            if until is not None and f.is_file() and sha256(f.read_bytes()) != row_bytes(e):
                problems.append(f"{e['path']}: the exemption of {name} expired on {until} and its copy still differs "
                                "(converge on the row's bytes, or move the date with a reason)")
        else:
            for rel in sorted({e["path"], *e.get("paths", {}).values()}):
                if not (root / rel).is_file():
                    continue
                got = sha256((root / rel).read_bytes())
                # adopting a shared file: the crate's commit that adds it cannot be listed first (the table
                # lists only holders whose main has the path), so a copy with exactly the entry's bytes (or a
                # pending row's target) is a counted note; the Law side's strict check makes the next table
                # list it. A per-repository path, or any other bytes, stays a finding.
                want = (e["sha256"] if "sha256" in e else e["pending"]["target"] if "pending" in e else None)
                if want is not None and got == want:
                    copies += 1
                    adopting += 1
                    notes.append(f"{rel}: adopting: not yet listed for {name}, the same bytes as the entry "
                                 f"(carried by {', '.join(e['repos'])})")
                else:
                    problems.append(f"{rel}: a shared file the table neither lists nor exempts for {name} "
                                    f"(carried by {', '.join(e['repos']) or 'none: per-repository data'})")
    if adopting:
        notes.append(f"adopting: {adopting} copy(ies) with an entry's bytes, not yet listed for {name} "
                     "(the next table lists them)")
    if copies == 0 and not problems and not notes:
        raise Unreadable(f"the table lists no file for {name} (compared nothing)")
    return problems, notes, counts(files, 1, copies, pending)


OFF_TARGET = "own copies not at a pending row's target"


def off_target(entries: list[dict], root: Path, name: str) -> list[str]:
    """the crate's copies on pending rows that are not the row's target (absent included): the per-crate G11 pass
    needs none (a row still pending on other repositories' mains does not hold the crate back)"""
    out = []
    for e in entries:
        if name in e["repos"] and "pending" in e:
            f = root / path_in(e, name)
            if not f.is_file() or sha256(f.read_bytes()) != e["pending"]["target"]:
                out.append(path_in(e, name))
    return out


class Remote:
    """Blob-less clones of the repositories' main, one per repository (blobs fetched lazily)."""

    def __init__(self, base: Path):
        self.base = base
        self.made: dict[str, Path] = {}

    def __call__(self, repo: str) -> Path:
        if repo not in self.made:
            g = self.base / repo
            for args in (["init", "-q", str(g)], ["-C", str(g), "remote", "add", "origin", GITHUB + repo]):
                subprocess.run(["git", *args], check=True, capture_output=True)
            r = subprocess.run(["git", "-C", str(g), "fetch", "-q", "--filter=blob:none", "origin",
                                "+refs/heads/main:refs/remotes/origin/main"], capture_output=True, text=True)
            if r.returncode != 0:
                raise Unreadable(f"{repo}: fetching main failed: {r.stderr.strip()}")
            self.made[repo] = g
        return self.made[repo]

    def prefetch(self, repo: str, rev: str, rels: list[str]) -> None:
        """Fetch the blobs of rels at rev in one request (instead of one lazy fetch each)."""
        prefetch(self(repo), rev, rels)


def prefetch(g: Path, rev: str, rels: list[str]) -> None:
    oids = []
    for rel in sorted(set(rels)):
        r = subprocess.run(["git", "-C", str(g), "rev-parse", "-q", "--verify", f"{rev}:{rel}"],
                           capture_output=True, text=True)
        if r.returncode == 0:
            oids.append(r.stdout.strip())
    missing = [o for o in oids
               if subprocess.run(["git", "-C", str(g), "cat-file", "-e", o], capture_output=True,
                                 env={"GIT_NO_LAZY_FETCH": "1", "PATH": "/usr/bin:/bin:/usr/local/bin:/opt/homebrew/bin"}
                                 ).returncode != 0]
    for i in range(0, len(missing), 200):
        r = subprocess.run(["git", "-C", str(g), "-c", "fetch.negotiationAlgorithm=noop", "fetch", "-q", "--no-tags",
                            "--no-write-fetch-head", "origin", *missing[i:i + 200]], capture_output=True, text=True)
        if r.returncode != 0:
            raise Unreadable(f"{g.name}: fetching {len(missing[i:i + 200])} blob(s) failed: {r.stderr.strip()}")


def show(g: Path, rev: str, rel: str) -> bytes | None:
    s = subprocess.run(["git", "-C", str(g), "show", f"{rev}:{rel}"], capture_output=True)
    return s.stdout if s.returncode == 0 else None


def tree(g: Path, rev: str = "origin/main") -> dict[str, str]:
    """path -> git blob id of every file at rev (no blob is fetched)."""
    out = subprocess.run(["git", "-C", str(g), "ls-tree", "-r", "-z", rev], check=True,
                         capture_output=True, text=True).stdout
    files = {}
    for item in out.split("\0"):
        if item:
            meta, path = item.split("\t", 1)
            mode, kind, blob = meta.split()
            if kind == "blob":
                files[path] = blob
    return files


def fetch_sources(entries: list[dict], remote: Remote) -> tuple[list[str], list[str], tuple]:
    """Each uniform entry's source commit: on its repository's main, with the entry's bytes."""
    problems: list[str] = []
    copies = 0
    uniform = [e for e in entries if "sha256" in e]
    want: dict[tuple[str, str], list[str]] = collections.defaultdict(list)
    for e in uniform:
        want[(e["source"]["repo"], e["source"]["rev"])].append(path_in(e, e["source"]["repo"]))
    for (repo, rev), rels in sorted(want.items()):
        remote.prefetch(repo, rev, rels)
    for e in uniform:
        repo, rev = e["source"]["repo"], e["source"]["rev"]
        g = remote(repo)
        on_main = subprocess.run(["git", "-C", str(g), "merge-base", "--is-ancestor", rev, "origin/main"],
                                 capture_output=True)
        if on_main.returncode != 0:
            problems.append(f"{e['path']}: source {repo} {rev[:12]} is not on {repo}'s main")
            continue
        data = show(g, rev, path_in(e, repo))
        if data is None:
            problems.append(f"{e['path']}: not at {path_in(e, repo)} in {repo} {rev[:12]}")
            continue
        copies += 1
        if sha256(data) != e["sha256"]:
            problems.append(f"{e['path']}: {repo} {rev[:12]} has sha256 {sha256(data)}, the table {e['sha256']}")
    return problems, [], counts(len(uniform), len({e["source"]["repo"] for e in uniform}), copies,
                                sum("pending" in e for e in entries))


FIRST_MOVE_MAX_DAYS = 3


def owner_tips(g: Path) -> list[str]:
    """the owner's main and ci/ branch tips (blob-less), the refs a planned first move's bytes may sit on"""
    r = subprocess.run(["git", "-C", str(g), "fetch", "-q", "--filter=blob:none", "origin",
                        "+refs/heads/ci/*:refs/remotes/origin/ci/*"], capture_output=True, text=True)
    if r.returncode != 0:
        raise Unreadable(f"{g.name}: fetching the ci/ branches failed: {r.stderr.strip()}")
    out = subprocess.run(["git", "-C", str(g), "for-each-ref", "--format=%(refname)", "refs/remotes/origin/main",
                          "refs/remotes/origin/ci/"], capture_output=True, text=True, check=True).stdout.split()
    return out


def first_move_problems(e: dict, found: dict[str, list[str]], remote: Remote, age: int,
                        proof: bytes | None = None) -> list[str]:
    """A first move (a uniform row planned to bytes no main holds yet): the planned bytes are real (the owner has the
    blob at the path on the tip of its main or a ci/ branch, with the target's SHA-256), every other copy is still
    the uniform bytes it moves from (no third value, no missing copy), and the owner lands within FIRST_MOVE_MAX_DAYS
    days"""
    p, m = e["pending"], e["pending"]["moved_from"]
    problems = []
    others = sorted(k for k in found if k not in (p["target"], m["target"]))
    for k in others:
        problems.append(f"{e['path']}: first move: {', '.join(found[k])} "
                        + ("has no copy" if k == "absent" else f"main has sha256 {k[:12]}")
                        + f", not the uniform bytes {m['target'][:12]} it moves from or the target {p['target'][:12]}")
    if p["owner"] in found.get(p["target"], []):
        return problems  # the owner has landed the bytes: they are real
    if age > FIRST_MOVE_MAX_DAYS:
        problems.append(f"{e['path']}: first move planned since {p['since']} and the owner {p['owner']} has not landed "
                        f"{p['planned'][:12]} in more than {FIRST_MOVE_MAX_DAYS} days")
    return problems + planned_bytes_problems(e, remote, proof, "first move")


def planned_bytes_problems(e: dict, remote: Remote, proof: bytes | None, label: str) -> list[str]:
    """the planned bytes of a row whose owner has not landed them are real: the table's repository carries them as
    planned/<blob> (planned_proof_problems holds that file to the row in every mode), or the owner has the blob at the
    path on the tip of its main or a ci/ branch, with the target's SHA-256"""
    p = e["pending"]
    if proof is not None:
        return []
    g = remote(p["owner"])
    rel = path_in(e, p["owner"])
    tips = [t for t in owner_tips(g)
            if subprocess.run(["git", "-C", str(g), "rev-parse", "-q", "--verify", f"{t}:{rel}"],
                              capture_output=True, text=True).stdout.strip() == p["planned"]]
    if not tips:
        return [f"{e['path']}: {label}: the owner {p['owner']} has blob {p['planned'][:12]} at {rel} on the tip of "
                f"neither its main nor a ci/ branch, and there is no {PLANNED_DIR}/{p['planned']} with its bytes (the "
                "planned bytes must exist before they are planned)"]
    data = show(g, tips[0], rel)
    if data is None or sha256(data) != p["target"]:
        return [f"{e['path']}: {label}: blob {p['planned'][:12]} on {tips[0]} of {p['owner']} has sha256 "
                f"{sha256(data)[:12] if data is not None else 'none'}, not the target {p['target'][:12]}"]
    return []


def introduction_problems(e: dict, found: dict[str, list[str]], remote: Remote, age: int,
                          proof: bytes | None = None) -> list[str]:
    """A new file planned into every listed repository, its owner not landed yet: every copy is absent or already the
    target, the planned bytes are real (the owner's ci/ branch tip or the table's planned/ file, as for a first move),
    and the owner lands within FIRST_MOVE_MAX_DAYS days"""
    p = e["pending"]
    problems = [f"{e['path']}: new file: {', '.join(found[k])} main has sha256 {k[:12]}, not the target "
                f"{p['target'][:12]} (the table records no copy yet)" for k in sorted(found) if k not in ("absent", p["target"])]
    if age > FIRST_MOVE_MAX_DAYS:
        problems.append(f"{e['path']}: new file planned since {p['since']} and the owner {p['owner']} has not landed "
                        f"{p['planned'][:12]} in more than {FIRST_MOVE_MAX_DAYS} days")
    return problems + planned_bytes_problems(e, remote, proof, "new file")


def live(entries: list[dict], remote: Remote, today: datetime.date, strict: bool = False,
         proofs: dict[str, bytes] | None = None, base: list[dict] | None = None):
    """Every listed repository's main against the table, and the discovery pass."""
    problems: list[str] = []
    notes: list[str] = []
    copies = pending = 0
    uniform_copies = 0
    unlisted: list[tuple[str, str, str, str]] = []
    repos = sorted({r for e in entries for r in e["repos"]} | {r for e in entries for r in e.get("exempt", {})})
    base_listed = {e["path"]: set(e["repos"]) for e in (base or [])}
    base_planned = {e["path"]: e["pending"] for e in (base or []) if is_planned(e)}
    trees = {r: tree(remote(r)) for r in repos}
    if not trees:
        raise Unreadable("no repository read (compared nothing)")
    for r in repos:
        remote.prefetch(r, "origin/main", [path_in(e, r) for e in entries if r in e["repos"]]
                        + [e["path"] for e in entries if r not in e["repos"] and e["path"] in trees[r]])
    for e in entries:
        if "pending" in e:
            pending += 1
            since = datetime.date.fromisoformat(e["pending"]["since"])
            age = (today - since).days
            if age < 0:
                problems.append(f"{e['path']}: pending since {e['pending']['since']}, after today ({today.isoformat()}): "
                                "a future date switches the age limits off")
            found: dict[str, list[str]] = collections.defaultdict(list)
            owner_blob = None
            for r in e["repos"]:
                data = show(remote(r), "origin/main", path_in(e, r))
                found["absent" if data is None else sha256(data)].append(r)
                copies += data is not None
                if r == e["pending"]["owner"] and data is not None:
                    owner_blob = (sha256(data), git_blob(data))
            if is_planned(e):
                p = e["pending"]
                m = p.get("moved_from")
                # a planned row moved to new bytes: until its owner lands them, the owner holds the earlier pair
                pairs = [(p["target"], p["planned"])] + ([(m["target"], m["planned"])] if m else [])
                # the table's claim that the owner holds the target is read against the owner's main: a recorded
                # landing that has not happened would take a first move's flag off (--base-table reads the variants)
                if p["owner"] in p["variants"].get(p["target"], []) and (owner_blob or ("",))[0] != p["target"]:
                    problems.append(f"{e['path']}: the table records the owner {p['owner']} at the target "
                                    f"{p['target'][:12]}, but its main has "
                                    + (f"sha256 {owner_blob[0][:12]}" if owner_blob else "no copy"))
                if not m and set(p["variants"]) == {"absent"} and owner_blob is None:
                    # a new file planned into every listed repository (the table recorded no copy): until the owner
                    # lands it, its bytes must be real as for a first move, and no copy may hold other bytes
                    problems += introduction_problems(e, found, remote, age, (proofs or {}).get(p["planned"]))
                elif owner_blob not in pairs:
                    got = f"sha256 {owner_blob[0][:12]}, blob {owner_blob[1][:12]}" if owner_blob else "no copy"
                    earlier = f", or the earlier {m['target'][:12]} / {m['planned'][:12]}" if m else ""
                    problems.append(f"{e['path']}: planned row, but the owner {p['owner']} main does not hold the "
                                    f"target (sha256 {p['target'][:12]}, blob {p['planned'][:12]}{earlier}; "
                                    f"it has {got})")
                if m:
                    # a moving rollout carries its target, the bytes it moves from and the older variants the table
                    # recorded (copies a re-roll found mid-rollout): any other value is drift, not a step of it
                    known = moving_bytes(e) | {k for k in p["variants"] if k != "absent"}
                    stray = sorted(k for k in found if k != "absent" and k not in known)
                    for k in stray:
                        problems.append(f"{e['path']}: {', '.join(found[k])} main has sha256 {k[:12]}, none of the "
                                        f"planned target {p['target'][:12]}, the bytes it moves from "
                                        f"{m['target'][:12]} or a variant the table recorded")
                    held = [r for r in found.get(p["target"], [])]
                    present = [r for k, rs in found.items() if k != "absent" for r in rs]
                    stale = sorted(r for k, rs in found.items() if k in known and k != p["target"] for r in rs)
                    notes.append(f"{e['path']}: moving to {p['target'][:12]}: {len(held)} of {len(present)} copies at "
                                 f"the target" + (f"; stale (recorded earlier bytes): {', '.join(stale)}" if stale
                                                  else ""))
                    if m["target"] not in found:
                        notes.append(f"{e['path']}: no main holds the bytes the planned row moved from any more "
                                     "(regenerate the table: moved_from goes)")
                if set(found) == {p["target"]}:
                    b = base_planned.get(e["path"])
                    if (not strict and b is not None and b["planned"] == p["planned"] and b["target"] == p["target"]
                            and set(e["repos"]) == base_listed.get(e["path"], set())):
                        # the landing mode: the base planned it too and the change left it, so the rollout finished
                        # on the mains while the change was checked (the daily run regenerates the table)
                        notes.append(f"{e['path']}: converged since the base (every copy has the target "
                                     f"{p['target'][:12]}; the next table makes it uniform)")
                    else:
                        problems.append(f"{e['path']}: planned row whose every copy has the target: it has converged "
                                        "(regenerate the table)")
                if p.get("first_move"):
                    problems += first_move_problems(e, found, remote, age, (proofs or {}).get(p["planned"]))
                if age > PLANNED_MAX_DAYS:
                    problems.append(f"{e['path']}: planned since {p['since']}, more than {PLANNED_MAX_DAYS} days "
                                    f"(the rollout to {p['planned'][:12]} has not finished)")
            recorded = {k: sorted(v) for k, v in e["pending"]["variants"].items()}
            moved = "" if dict(found) == recorded else " (the variants on the mains have moved since the table)"
            notes.append(f"{e['path']}: pending {age} day(s), {len(found)} variant(s): "
                         + "; ".join(f"{k[:12]} {','.join(v)}" for k, v in sorted(found.items())) + moved)
            if age > PENDING_MAX_DAYS:
                problems.append(f"{e['path']}: pending since {e['pending']['since']}, more than "
                                f"{PENDING_MAX_DAYS} days ({e['pending']['exit']})")
            continue
        if "sha256" not in e:
            continue  # per-repository data: nothing to compare
        for r in e["repos"]:
            rel = path_in(e, r)
            data = show(remote(r), "origin/main", rel)
            if data is None:
                problems.append(f"{rel}: missing on {r} main")
                continue
            copies += 1
            uniform_copies += 1
            if sha256(data) != e["sha256"]:
                problems.append(f"{rel}: {r} main has sha256 {sha256(data)}, the table {e['sha256']}")
    # discovery
    known = {e["path"] for e in entries} | {q for e in entries for q in e.get("paths", {}).values()}
    by_path: dict[str, dict[str, list[str]]] = collections.defaultdict(lambda: collections.defaultdict(list))
    for r, files in trees.items():
        for path, blob in files.items():
            if path.startswith(DISCOVERED):
                by_path[path][blob].append(r)
    for path, blobs in sorted(by_path.items()):
        if path in known:
            continue
        shared = {b: rs for b, rs in blobs.items() if len(rs) >= 2}
        if shared:
            problems.append(f"{path}: byte-identical in {', '.join(sorted(max(shared.values(), key=len)))} "
                            f"but has no entry")
    for e in entries:
        for r in sorted(e.get("exempt", {})):
            until = expired(e, r, today)
            if until is None or e["path"] not in trees.get(r, {}):
                continue
            data = show(remote(r), "origin/main", e["path"])
            if data is None or sha256(data) != row_bytes(e):
                problems.append(f"{e['path']}: the exemption of {r} expired on {until} and its copy on main still "
                                "differs (converge on the row's bytes, or move the date with a reason)")
        listed = set(e["repos"]) | set(e.get("exempt", {}))
        known_bytes = ({e["sha256"]} if "sha256" in e
                       else {k for k in e.get("pending", {}).get("variants", {}) if k != "absent"}
                       | (moving_bytes(e) if "pending" in e else set()))
        for r, files in trees.items():
            if r in listed or e["path"] not in files:
                continue
            data = show(remote(r), "origin/main", e["path"])
            got = sha256(data) if data is not None else ""
            if got and got in known_bytes and base is not None and r in base_listed.get(e["path"], set()):
                # not a rollout that landed elsewhere: the base lists this holder and the change dropped it
                problems.append(f"{e['path']}: {r} is listed in the base table and this change removed it (its main "
                                "still has the entry's bytes)")
                continue
            if got and got in known_bytes and not strict:
                # a rollout landed before the table was regenerated: the same bytes, not drift
                since = subprocess.run(["git", "-C", str(remote(r)), "log", "-1", "--format=%cs", "--diff-filter=A",
                                        "origin/main", "--", e["path"]], capture_output=True, text=True).stdout.strip()
                unlisted.append((e["path"], r, got, since or "?"))
                continue
            what = "the same bytes as its entry" if got in known_bytes else f"sha256 {got or '(unreadable)'}"
            problems.append(f"{e['path']}: present on {r} main ({what}), which the entry neither lists nor exempts")
    if unlisted:
        oldest = min(u[3] for u in unlisted)
        notes.append(f"unlisted holder, same bytes: {len(unlisted)} (oldest since {oldest}; regenerate the table"
                     " before the next publish)")
        notes += [f"  unlisted holder: {path} on {r} main, sha256 {got[:12]}, since {since}"
                  for path, r, got, since in unlisted]
    return problems, notes, counts(len(entries), len(trees), copies, pending), uniform_copies


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--table", required=True, type=Path)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--fetch", action="store_true", help="fetch each source commit and compare")
    mode.add_argument("--live", action="store_true", help="compare every listed repository's main")
    mode.add_argument("--repo", type=Path, help="a crate checkout to check against the table")
    ap.add_argument("--name", help="the crate's repository name (ALICE-…), with --repo")
    ap.add_argument("--expect-copies", type=int,
                    help="with --live: the number of copies that must be compared (count lock)")
    ap.add_argument("--today", help="with --live or --repo: the date pending rows and dated exemptions are aged against (default: today, UTC)")
    ap.add_argument("--lock-file", type=Path,
                    help="a file holding the count lock (`--expect-copies N`): N must equal the copies of uniform "
                         "rows the table lists")
    ap.add_argument("--strict", action="store_true",
                    help="with --live: an unlisted holder is a finding even with the same bytes (the regeneration "
                         "and landing path of this repository, and the pre-publish gate)")
    ap.add_argument("--base-table", type=Path,
                    help="the table this one replaces (origin/main's): more pending rows than it is a finding")
    a = ap.parse_args(argv)
    if (a.repo is None) != (a.name is None):
        ap.error("--repo and --name go together")
    notes: list[str] = []
    locked: int | None = None
    try:
        entries = load(a.table.read_text(encoding="utf-8"))
        lock = None if a.lock_file is None else lock_in(a.lock_file.read_text(encoding="utf-8"), str(a.lock_file))
        proofs = planned_proofs(a.table)
        base_pending = None
        base_entries = None
        base_since: dict[str, str] = {}
        base_planned: dict[str, dict] = {}
        base_variants: dict[str, dict] = {}
        base_uniform: dict[str, str] = {}
        if a.base_table is not None:
            base_entries = load(a.base_table.read_text(encoding="utf-8"))
            base_pending = pending_counts(base_entries)
            base_since = {e["path"]: e["pending"]["since"] for e in base_entries if "pending" in e}
            base_planned = {e["path"]: e["pending"] for e in base_entries if is_planned(e)}
            base_variants = {e["path"]: e["pending"]["variants"] for e in base_entries if "pending" in e}
            base_uniform = {e["path"]: e["sha256"] for e in base_entries if "sha256" in e}
        if a.repo is not None:
            if not is_repo_name(a.name):
                raise Unreadable(f"--name {a.name!r} is not a repository name (ALICE-… or a listed product)")
            problems, notes, c = check_repo(entries, a.repo, a.name,
                                            datetime.date.fromisoformat(a.today) if a.today else None)
            off = off_target(entries, a.repo, a.name)
            print(f"shared_files_check: {OFF_TARGET}: {len(off)}" + (f" ({', '.join(off)})" if off else ""))
        elif a.fetch or a.live:
            with tempfile.TemporaryDirectory() as d:
                remote = Remote(Path(d))
                if a.fetch:
                    problems, notes, c = fetch_sources(entries, remote)
                else:
                    today = (datetime.date.fromisoformat(a.today) if a.today
                             else datetime.datetime.now(datetime.timezone.utc).date())
                    problems, notes, c, locked = live(entries, remote, today, strict=a.strict, proofs=proofs,
                                                      base=base_entries)
        else:
            problems = []
            c = counts(len(entries), len({r for e in entries for r in e["repos"]}),
                       sum(len(e["repos"]) for e in entries), sum("pending" in e for e in entries))
    except (Unreadable, OSError, ValueError) as e:
        print(f"shared_files_check: {e}", file=sys.stderr)
        return 2
    if base_pending is not None:
        # a row pending in both tables keeps its date: moving `since` later would restart the age limits
        for e in entries:
            was = base_since.get(e["path"])
            if "pending" in e and was is not None and e["pending"]["since"] > was:
                problems.append(f"{e['path']}: pending since {e['pending']['since']}, the base table says {was} "
                                "(a pending row's date only stays or goes back)")
            # a planned row moved to other bytes names what it moved from: the base's planned id and target,
            # or the same move the base already recorded
            if not is_planned(e):
                continue
            p, b = e["pending"], base_planned.get(e["path"])
            m = p.get("moved_from")
            if m is not None:
                base_known = set(base_variants.get(e["path"], {})) | {p["target"], m["target"], "absent"}
                added = sorted(set(p["variants"]) - base_known)
                if added:
                    problems.append(f"{e['path']}: a moving row records variant(s) {', '.join(k[:12] for k in added)} "
                                    "the base table does not have (a variant counts only when recorded before the "
                                    "move)")
            if (b is not None and b.get("first_move") and not p.get("first_move")
                    and p["owner"] not in p["variants"].get(p["target"], [])):
                problems.append(f"{e['path']}: first_move dropped while the owner {p['owner']} does not hold the target "
                                f"{p['target'][:12]} (gen_shared_files.py drops the flag once the owner's main has it)")
            if b is not None and b.get("first_move") and b["planned"] != p["planned"]:
                # re-rolled before the owner landed it: still the one move, from the bytes the base moves from
                if m == b.get("moved_from"):
                    continue
                problems.append(f"{e['path']}: the base's first move to {b['planned'][:12]} has not landed: one planned "
                                f"move at a time (not {p['planned'][:12]})")
            elif b is not None and b["planned"] != p["planned"]:
                # from the base's planned bytes, or (a second re-roll before the owner landed the first) from the
                # bytes the base itself was moving from, which the mains still hold
                # (a new file re-rolled before any main holds it moves from nothing: no copy is anywhere yet)
                fresh = (m is None and "moved_from" not in b and set(p["variants"]) == {"absent"}
                         and set(base_variants.get(e["path"], {})) == {"absent"})
                if (not fresh and m != {"planned": b["planned"], "target": b["target"]}
                        and (m is None or m != b.get("moved_from"))):
                    problems.append(f"{e['path']}: the planned id moved from {b['planned'][:12]} to "
                                    f"{p['planned'][:12]} without moved_from naming the base's planned id and target")
            elif (m is not None and b is None and p.get("first_move") and base_uniform.get(e["path"]) == m["target"]
                  and set(p["variants"]) == {m["target"]}):
                pass  # the first move of a row the base records as uniform, from exactly those bytes, every copy there
            elif m is not None and (b is None or b.get("moved_from") != m):
                problems.append(f"{e['path']}: moved_from names {m['planned'][:12]}, which is not the base table's "
                                "planned id for this row")
        # a planned row leaves the table only at its target: closing it by hand (back to the bytes it moves from,
        # or dropping the row) and planning it again later would restart its clock, so a wrong plan rolls forward
        now = {e["path"]: e for e in entries}
        for path, b in sorted(base_planned.items()):
            e = now.get(path)
            if e is not None and ("pending" in e or e.get("sha256") == b["target"]):
                continue
            where = "is not in the table" if e is None else f"is uniform at {str(e.get('sha256'))[:12]}"
            problems.append(f"{path}: planned to {b['target'][:12]} in the base table, and {where} (a planned row "
                            "leaves the table only at its target: a wrong plan is re-rolled with --target)")
        planned, unplanned = pending_counts(entries)
        if planned + unplanned != c[3]:
            problems.append(f"the pending rows counted ({c[3]}) are not the planned and unplanned ones "
                            f"({planned} + {unplanned})")
        if unplanned > base_pending[1]:
            problems.append(f"{unplanned} unplanned pending rows, the base table has {base_pending[1]} (an unplanned "
                            "divergence only goes down; a rollout is a planned row, with the registry's next=)")
        else:
            print(f"shared_files_check: pending {c[3]} (planned {planned}, unplanned {unplanned}), the base table "
                  f"{sum(base_pending)} (planned {base_pending[0]}, unplanned {base_pending[1]})")
    if proofs:
        problems = planned_proof_problems(entries, proofs) + problems
        print(f"shared_files_check: planned bytes: {len(proofs)} file(s) in {PLANNED_DIR}/ compared with their rows")
    if lock is not None:
        listed = uniform_copies(entries)
        if lock != listed:
            problems.append(f"{a.lock_file}: the count lock says {lock}, the table lists {listed} copies of uniform "
                            "rows (regenerate with gen_shared_files.py --write --lock-file, which writes both)")
        else:
            print(f"shared_files_check: count lock in {a.lock_file}: {lock}, the table's copies of uniform rows")
    if a.expect_copies is not None:
        # with --live the lock is on the copies of uniform rows, which change only with the
        # table; the copies of a pending row come and go as its rollout lands
        got = locked if locked is not None else c[2]
        if got != a.expect_copies:
            problems.append(f"compared {got} copies of uniform rows, the count lock says {a.expect_copies}")
        else:
            print(f"shared_files_check: count lock: {got} copies of uniform rows")
    for n in notes:
        kind = "" if n.lstrip().startswith("unlisted holder") else "pending: "
        print(f"shared_files_check: {kind}{n}")
    for p in problems:
        print(f"shared_files_check: {p}", file=sys.stderr)
    print(f"shared_files_check: {summary(c)}, {len(problems)} finding(s)")
    if c[2] == 0 and not problems and not notes:
        print("shared_files_check: compared nothing", file=sys.stderr)
        return 2
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
