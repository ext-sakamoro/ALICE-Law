#!/usr/bin/env python3
"""ALICE-Law G11 (c): files shared byte for byte across the ALICE crates.

conformance/shared-files.toml (generated by scripts/gen_shared_files.py) has one entry per
shared file: its path, the SHA-256 of its bytes, a source commit on the source
repository's main that has those bytes at that path, the repositories that carry it, for a
repository that keeps it elsewhere that path, and for a repository that legitimately has a
different file at the same path an exemption with its reason.

  shared_files_check.py --table TABLE
      the schema only (offline: preflight and branch CI)
  shared_files_check.py --table TABLE --fetch
      also each source commit fetched from GitHub: an ancestor of its repository's main,
      with the entry's bytes at the entry's path
  shared_files_check.py --table TABLE --live
      every listed repository's main fetched from GitHub: each copy equal to its entry
      (with --expect-copies N, the number of copies compared must be N)
  shared_files_check.py --table TABLE --repo DIR --name ALICE-X
      a crate's own tree: every entry listing ALICE-X has its file at its path in DIR with
      the entry's SHA-256, and no table path is present in DIR for an entry that neither
      lists nor exempts ALICE-X (a shared file kept out of the table)

Every mode prints `compared: files N, repos M, copies K`. Exit 0 when everything compared is
equal, 1 on a difference, 2 when nothing was compared or the input cannot be read (an empty
table, a crate the table never names, a fetch that failed): a check that compared nothing is
not a pass.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

HEX40 = re.compile(r"^[0-9a-f]{40}$")
HEX64 = re.compile(r"^[0-9a-f]{64}$")
REPO = re.compile(r"^ALICE-[A-Za-z0-9-]+$")
GITHUB = "https://github.com/ext-sakamoro/"
MIN_REASON = 12
KEYS = {"path", "sha256", "source", "repos", "paths", "exempt"}
REQUIRED = {"path", "sha256", "source", "repos"}


class Unreadable(Exception):
    """The input cannot be compared (exit 2)."""


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def safe_path(p: object) -> bool:
    return (isinstance(p, str) and p != "" and not p.startswith("/") and "\\" not in p
            and all(part not in ("", ".", "..") for part in p.split("/")))


def load(text: str) -> list[dict]:
    """The entries of a table, checked against the schema (Unreadable on any defect)."""
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise Unreadable(f"not TOML: {e}") from None
    unknown = set(data) - {"file"}
    if unknown:
        raise Unreadable(f"unknown top-level keys: {sorted(unknown)}")
    files = data.get("file", [])
    if not isinstance(files, list) or not files:
        raise Unreadable("no [[file]] entry (compares nothing)")
    seen: set[str] = set()
    previous = ""
    for i, f in enumerate(files, 1):
        where = f"entry {i}"
        if not isinstance(f, dict):
            raise Unreadable(f"{where}: not a table")
        if set(f) - KEYS or REQUIRED - set(f):
            raise Unreadable(f"{where}: unknown keys {sorted(set(f) - KEYS)}, "
                             f"missing keys {sorted(REQUIRED - set(f))}")
        path = f["path"]
        if not safe_path(path):
            raise Unreadable(f"{where}: path {path!r} is not a relative path")
        where = f"entry {path}"
        if path in seen:
            raise Unreadable(f"{where}: listed twice")
        if path < previous:
            raise Unreadable(f"{where}: entries are not sorted by path")
        seen.add(path)
        previous = path
        if not isinstance(f["sha256"], str) or not HEX64.match(f["sha256"]):
            raise Unreadable(f"{where}: sha256 is not 64 lower-case hex digits")
        src = f["source"]
        if (not isinstance(src, dict) or set(src) != {"repo", "rev"} or not isinstance(src["repo"], str)
                or not REPO.match(src["repo"]) or not isinstance(src["rev"], str)
                or not HEX40.match(src["rev"])):
            raise Unreadable(f"{where}: source must be {{ repo = \"ALICE-…\", rev = \"<40 hex>\" }}")
        repos = f["repos"]
        if (not isinstance(repos, list) or not repos
                or not all(isinstance(r, str) and REPO.match(r) for r in repos)
                or len(set(repos)) != len(repos) or repos != sorted(repos)):
            raise Unreadable(f"{where}: repos must be a sorted list of distinct ALICE-… names")
        if src["repo"] not in repos:
            raise Unreadable(f"{where}: the source repository {src['repo']} is not in repos")
        alt = f.get("paths", {})
        if not isinstance(alt, dict) or not all(r in repos and safe_path(p) for r, p in alt.items()):
            raise Unreadable(f"{where}: paths must map listed repositories to relative paths")
        ex = f.get("exempt", {})
        if (not isinstance(ex, dict) or not all(REPO.match(r) and r not in repos for r in ex)
                or not all(isinstance(why, str) and len(why.strip()) >= MIN_REASON for why in ex.values())):
            raise Unreadable(f"{where}: exempt must map unlisted ALICE-… repositories to a reason "
                             f"of at least {MIN_REASON} characters")
    return files


def path_in(entry: dict, name: str) -> str:
    return entry.get("paths", {}).get(name, entry["path"])


def summary(files: int, repos: int, copies: int) -> str:
    return f"compared: files {files}, repos {repos}, copies {copies}"


def check_repo(entries: list[dict], root: Path, name: str) -> tuple[list[str], tuple[int, int, int]]:
    """Differences between a crate's tree and the table, and the counts compared."""
    problems: list[str] = []
    copies = 0
    for e in entries:
        if name in e["repos"]:
            rel = path_in(e, name)
            f = root / rel
            if not f.is_file():
                problems.append(f"{rel}: listed for {name} but missing")
                continue
            copies += 1
            got = sha256(f.read_bytes())
            if got != e["sha256"]:
                problems.append(f"{rel}: sha256 {got}, the table has {e['sha256']} "
                                f"(the bytes of {e['source']['repo']} at {e['source']['rev'][:12]})")
        elif name not in e.get("exempt", {}):
            for rel in sorted({e["path"], *e.get("paths", {}).values()}):
                if (root / rel).is_file():
                    problems.append(f"{rel}: a shared file the table neither lists nor exempts for {name} "
                                    f"(carried by {', '.join(e['repos'])})")
    if copies == 0 and not problems:
        raise Unreadable(f"the table lists no file for {name} (compared nothing)")
    return problems, (copies, 1, copies)


class Remote:
    """Blob-less clones of the repositories' main, one per repository (blobs fetched lazily)."""

    def __init__(self, base: Path):
        self.base = base
        self.made: dict[str, Path] = {}

    def __call__(self, repo: str) -> Path:
        if repo not in self.made:
            g = self.base / repo
            for args in (["init", "-q", str(g)], ["-C", str(g), "remote", "add", "origin", GITHUB + repo]):
                subprocess.run(["git", *args], check=True, capture_output=True)
            r = subprocess.run(["git", "-C", str(g), "fetch", "-q", "--filter=blob:none", "origin",
                                "+refs/heads/main:refs/remotes/origin/main"], capture_output=True, text=True)
            if r.returncode != 0:
                raise Unreadable(f"{repo}: fetching main failed: {r.stderr.strip()}")
            self.made[repo] = g
        return self.made[repo]


def show(g: Path, rev: str, rel: str) -> bytes | None:
    s = subprocess.run(["git", "-C", str(g), "show", f"{rev}:{rel}"], capture_output=True)
    return s.stdout if s.returncode == 0 else None


def fetch_sources(entries: list[dict], remote: Remote) -> tuple[list[str], tuple[int, int, int]]:
    """Each entry's source commit: on its repository's main, with the entry's bytes."""
    problems: list[str] = []
    copies = 0
    for e in entries:
        repo, rev = e["source"]["repo"], e["source"]["rev"]
        g = remote(repo)
        on_main = subprocess.run(["git", "-C", str(g), "merge-base", "--is-ancestor", rev, "origin/main"],
                                 capture_output=True)
        if on_main.returncode != 0:
            problems.append(f"{e['path']}: source {repo} {rev[:12]} is not on {repo}'s main")
            continue
        data = show(g, rev, path_in(e, repo))
        if data is None:
            problems.append(f"{e['path']}: not at {path_in(e, repo)} in {repo} {rev[:12]}")
            continue
        copies += 1
        if sha256(data) != e["sha256"]:
            problems.append(f"{e['path']}: {repo} {rev[:12]} has sha256 {sha256(data)}, the table {e['sha256']}")
    return problems, (len(entries), len({e["source"]["repo"] for e in entries}), copies)


def live(entries: list[dict], remote: Remote) -> tuple[list[str], tuple[int, int, int]]:
    """Every listed repository's main against the table; the count compared is locked."""
    problems: list[str] = []
    copies = 0
    for e in entries:
        for repo in e["repos"]:
            rel = path_in(e, repo)
            data = show(remote(repo), "origin/main", rel)
            if data is None:
                problems.append(f"{rel}: missing on {repo} main")
                continue
            copies += 1
            if sha256(data) != e["sha256"]:
                problems.append(f"{rel}: {repo} main has sha256 {sha256(data)}, the table {e['sha256']}")
    return problems, (len(entries), len({r for e in entries for r in e["repos"]}), copies)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--table", required=True, type=Path)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--fetch", action="store_true", help="fetch each source commit and compare")
    mode.add_argument("--live", action="store_true", help="compare every listed repository's main")
    mode.add_argument("--repo", type=Path, help="a crate checkout to check against the table")
    ap.add_argument("--name", help="the crate's repository name (ALICE-…), with --repo")
    ap.add_argument("--expect-copies", type=int,
                    help="with --live: the number of copies that must be compared (count lock)")
    a = ap.parse_args(argv)
    if (a.repo is None) != (a.name is None):
        ap.error("--repo and --name go together")
    try:
        entries = load(a.table.read_text(encoding="utf-8"))
        if a.repo is not None:
            if not REPO.match(a.name):
                raise Unreadable(f"--name {a.name!r} is not an ALICE-… repository name")
            problems, counts = check_repo(entries, a.repo, a.name)
        elif a.fetch or a.live:
            with tempfile.TemporaryDirectory() as d:
                remote = Remote(Path(d))
                problems, counts = (fetch_sources if a.fetch else live)(entries, remote)
        else:
            problems = []
            counts = (len(entries), len({r for e in entries for r in e["repos"]}),
                      sum(len(e["repos"]) for e in entries))
    except (Unreadable, OSError) as e:
        print(f"shared_files_check: {e}", file=sys.stderr)
        return 2
    if a.expect_copies is not None and counts[2] != a.expect_copies:
        problems.append(f"compared {counts[2]} copies, the count lock says {a.expect_copies}")
    for p in problems:
        print(f"shared_files_check: {p}", file=sys.stderr)
    print(f"shared_files_check: {summary(*counts)}, {len(problems)} difference(s)")
    if counts[2] == 0 and not problems:
        print("shared_files_check: compared nothing", file=sys.stderr)
        return 2
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
