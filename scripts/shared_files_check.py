#!/usr/bin/env python3
"""ALICE-Law G11 (c): files shared byte for byte across the ALICE crates.

conformance/shared-files.toml (generated by scripts/gen_shared_files.py) has one [[file]]
entry per shared file: its path, the repositories that carry it (with a path for one that
keeps it elsewhere, and an exemption with its reason for one that legitimately has a
different file at the same path), and either

  - the SHA-256 of its bytes and a source commit on the source repository's main that has
    those bytes (a uniform file), or
  - `pending`: the copies differ today. `variants` maps each SHA-256 found to the
    repositories that have it ("absent" for a listed repository without the file), `target`
    is the SHA-256 that becomes the file's bytes and `owner` the repository that holds them,
    `since` is the date the row became pending and `exit` says what ends it. A pending row
    pins no bytes and never makes a crate's cell a pass; it is listed and counted in every
    mode, and one older than PENDING_MAX_DAYS days is a finding (pending is not a parking
    place). With --base-table, a table with more pending rows than the base is a finding.

A repository that legitimately has a different file at a shared path is exempted on that
path's entry with its reason; the discovery scope itself has no exceptions.

  shared_files_check.py --table TABLE [--base-table BASE]
      the schema only (offline: preflight and branch CI), and the pending ratchet
  shared_files_check.py --table TABLE --fetch
      also each uniform entry's source commit fetched from GitHub: an ancestor of its
      repository's main, with the entry's bytes at the entry's path
  shared_files_check.py --table TABLE --live [--expect-copies N] [--today YYYY-MM-DD]
      every listed repository's main fetched from GitHub: each copy of a uniform file equal
      to its entry; the variants of each pending row listed (not a finding); a pending row
      past its time is a finding; and a discovery pass over every file under DISCOVERED of
      the table's repositories: one byte-identical in two or more of them with no entry, or
      a copy of a table path in a repository the entry neither lists nor exempts, is a
      finding
  shared_files_check.py --table TABLE --repo DIR --name ALICE-X
      a crate's tree: each uniform file listed for ALICE-X present with the entry's bytes;
      each pending file listed for it present as one of the row's variants (listed as
      pending, so the crate's cell is not a pass); a table path present for an entry that
      neither lists nor exempts ALICE-X is a finding

Every mode prints `compared: files N, repos M, copies K, pending P`. Exit 0 when everything
compared is equal, 1 on a finding, 2 when nothing was compared or the input cannot be read
(an empty table, a crate the table never names, a fetch that failed, no repository read).
"""
from __future__ import annotations

import argparse
import collections
import datetime
import hashlib
import re
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

HEX40 = re.compile(r"^[0-9a-f]{40}$")
HEX64 = re.compile(r"^[0-9a-f]{64}$")
REPO = re.compile(r"^ALICE-[A-Za-z0-9-]+$")
DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
GITHUB = "https://github.com/ext-sakamoro/"
MIN_REASON = 12
PENDING_MAX_DAYS = 21
DISCOVERED = ("scripts/", "tools/", ".github/workflows/", ".github/actions/")
UNIFORM_KEYS = {"path", "sha256", "source", "repos", "paths", "exempt"}
PENDING_KEYS = {"path", "pending", "repos", "paths", "exempt"}


class Unreadable(Exception):
    """The input cannot be compared (exit 2)."""


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def safe_path(p: object) -> bool:
    return (isinstance(p, str) and p != "" and not p.startswith("/") and "\\" not in p
            and all(part not in ("", ".", "..") for part in p.split("/")))


def reason(s: object) -> bool:
    return isinstance(s, str) and len(s.strip()) >= MIN_REASON


def is_repos(v: object) -> bool:
    return (isinstance(v, list) and bool(v) and all(isinstance(r, str) and REPO.match(r) for r in v)
            and len(set(v)) == len(v) and v == sorted(v))


def load_all(text: str) -> tuple[list[dict], list[dict]]:
    """The [[file]] entries of a table, checked against the schema (and an empty list)."""
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise Unreadable(f"not TOML: {e}") from None
    unknown = set(data) - {"file"}
    if unknown:
        raise Unreadable(f"unknown top-level keys: {sorted(unknown)}")
    files = data.get("file", [])
    if not isinstance(files, list) or not files:
        raise Unreadable("no [[file]] entry (compares nothing)")
    seen: set[str] = set()
    previous = ""
    for i, f in enumerate(files, 1):
        where = f"entry {i}"
        if not isinstance(f, dict):
            raise Unreadable(f"{where}: not a table")
        keys = PENDING_KEYS if "pending" in f else UNIFORM_KEYS
        required = {"path", "repos"} | ({"pending"} if "pending" in f else {"sha256", "source"})
        if set(f) - keys or required - set(f):
            raise Unreadable(f"{where}: unknown keys {sorted(set(f) - keys)}, missing keys {sorted(required - set(f))}")
        path = f["path"]
        if not safe_path(path):
            raise Unreadable(f"{where}: path {path!r} is not a relative path")
        where = f"entry {path}"
        if path in seen:
            raise Unreadable(f"{where}: listed twice")
        if path < previous:
            raise Unreadable(f"{where}: entries are not sorted by path")
        seen.add(path)
        previous = path
        repos = f["repos"]
        if not is_repos(repos):
            raise Unreadable(f"{where}: repos must be a sorted list of distinct ALICE-… names")
        if "pending" in f:
            p = f["pending"]
            if not isinstance(p, dict) or set(p) != {"since", "exit", "target", "owner", "variants"}:
                raise Unreadable(f"{where}: pending must be {{ since, exit, target, owner, variants }}")
            if not isinstance(p["target"], str) or not HEX64.match(p["target"]):
                raise Unreadable(f"{where}: pending.target must be the SHA-256 that becomes the file's bytes")
            if not isinstance(p["owner"], str) or not REPO.match(p["owner"]) or p["owner"] not in repos:
                raise Unreadable(f"{where}: pending.owner must be one of the listed repositories")
            if not isinstance(p["since"], str) or not DATE.match(p["since"]):
                raise Unreadable(f"{where}: pending.since must be YYYY-MM-DD")
            try:
                datetime.date.fromisoformat(p["since"])
            except ValueError:
                raise Unreadable(f"{where}: pending.since is not a date") from None
            if not reason(p["exit"]):
                raise Unreadable(f"{where}: pending.exit must say what ends it (at least {MIN_REASON} characters)")
            v = p["variants"]
            if (not isinstance(v, dict) or len(v) < 1 or not all(HEX64.match(k) or k == "absent" for k in v)
                    or not all(is_repos(rs) for rs in v.values())):
                raise Unreadable(f"{where}: pending.variants must map SHA-256 (or \"absent\") to sorted repositories")
            members = [r for rs in v.values() for r in rs]
            if sorted(members) != repos:
                raise Unreadable(f"{where}: pending.variants must cover each listed repository exactly once")
        else:
            if not isinstance(f["sha256"], str) or not HEX64.match(f["sha256"]):
                raise Unreadable(f"{where}: sha256 is not 64 lower-case hex digits")
            src = f["source"]
            if (not isinstance(src, dict) or set(src) != {"repo", "rev"} or not isinstance(src["repo"], str)
                    or not REPO.match(src["repo"]) or not isinstance(src["rev"], str)
                    or not HEX40.match(src["rev"])):
                raise Unreadable(f"{where}: source must be {{ repo = \"ALICE-…\", rev = \"<40 hex>\" }}")
            if src["repo"] not in repos:
                raise Unreadable(f"{where}: the source repository {src['repo']} is not in repos")
        alt = f.get("paths", {})
        if not isinstance(alt, dict) or not all(r in repos and safe_path(q) for r, q in alt.items()):
            raise Unreadable(f"{where}: paths must map listed repositories to relative paths")
        ex = f.get("exempt", {})
        if not isinstance(ex, dict) or not all(REPO.match(r) and r not in repos and reason(w) for r, w in ex.items()):
            raise Unreadable(f"{where}: exempt must map unlisted ALICE-… repositories to a reason "
                             f"of at least {MIN_REASON} characters")
    return files, []


def load(text: str) -> list[dict]:
    return load_all(text)[0]


def path_in(entry: dict, name: str) -> str:
    return entry.get("paths", {}).get(name, entry["path"])


def counts(files: int, repos: int, copies: int, pending: int) -> tuple[int, int, int, int]:
    return files, repos, copies, pending


def summary(c: tuple[int, int, int, int]) -> str:
    return f"compared: files {c[0]}, repos {c[1]}, copies {c[2]}, pending {c[3]}"


def check_repo(entries: list[dict], root: Path, name: str) -> tuple[list[str], list[str], tuple]:
    """Findings, pending notes and counts for a crate's tree."""
    problems: list[str] = []
    notes: list[str] = []
    copies = files = pending = 0
    for e in entries:
        if name in e["repos"]:
            files += 1
            rel = path_in(e, name)
            f = root / rel
            if "pending" in e:
                pending += 1
                mine = [k for k, rs in e["pending"]["variants"].items() if name in rs]
                if not f.is_file():
                    if mine != ["absent"]:
                        problems.append(f"{rel}: listed for {name} but missing")
                    else:
                        notes.append(f"{rel}: pending, absent here as recorded ({e['pending']['exit']})")
                    continue
                copies += 1
                got = sha256(f.read_bytes())
                if got not in e["pending"]["variants"]:
                    problems.append(f"{rel}: sha256 {got} is none of the pending row's variants")
                else:
                    on = "the target" if got == e["pending"]["target"] else "not yet the target"
                    notes.append(f"{rel}: pending since {e['pending']['since']}, {on} "
                                 f"(owner {e['pending']['owner']}: {e['pending']['exit']})")
                continue
            if not f.is_file():
                problems.append(f"{rel}: listed for {name} but missing")
                continue
            copies += 1
            got = sha256(f.read_bytes())
            if got != e["sha256"]:
                problems.append(f"{rel}: sha256 {got}, the table has {e['sha256']} "
                                f"(the bytes of {e['source']['repo']} at {e['source']['rev'][:12]})")
        elif name not in e.get("exempt", {}):
            for rel in sorted({e["path"], *e.get("paths", {}).values()}):
                if (root / rel).is_file():
                    problems.append(f"{rel}: a shared file the table neither lists nor exempts for {name} "
                                    f"(carried by {', '.join(e['repos'])})")
    if copies == 0 and not problems and not notes:
        raise Unreadable(f"the table lists no file for {name} (compared nothing)")
    return problems, notes, counts(files, 1, copies, pending)


class Remote:
    """Blob-less clones of the repositories' main, one per repository (blobs fetched lazily)."""

    def __init__(self, base: Path):
        self.base = base
        self.made: dict[str, Path] = {}

    def __call__(self, repo: str) -> Path:
        if repo not in self.made:
            g = self.base / repo
            for args in (["init", "-q", str(g)], ["-C", str(g), "remote", "add", "origin", GITHUB + repo]):
                subprocess.run(["git", *args], check=True, capture_output=True)
            r = subprocess.run(["git", "-C", str(g), "fetch", "-q", "--filter=blob:none", "origin",
                                "+refs/heads/main:refs/remotes/origin/main"], capture_output=True, text=True)
            if r.returncode != 0:
                raise Unreadable(f"{repo}: fetching main failed: {r.stderr.strip()}")
            self.made[repo] = g
        return self.made[repo]

    def prefetch(self, repo: str, rev: str, rels: list[str]) -> None:
        """Fetch the blobs of rels at rev in one request (instead of one lazy fetch each)."""
        prefetch(self(repo), rev, rels)


def prefetch(g: Path, rev: str, rels: list[str]) -> None:
    oids = []
    for rel in sorted(set(rels)):
        r = subprocess.run(["git", "-C", str(g), "rev-parse", "-q", "--verify", f"{rev}:{rel}"],
                           capture_output=True, text=True)
        if r.returncode == 0:
            oids.append(r.stdout.strip())
    missing = [o for o in oids
               if subprocess.run(["git", "-C", str(g), "cat-file", "-e", o], capture_output=True,
                                 env={"GIT_NO_LAZY_FETCH": "1", "PATH": "/usr/bin:/bin:/usr/local/bin:/opt/homebrew/bin"}
                                 ).returncode != 0]
    for i in range(0, len(missing), 200):
        r = subprocess.run(["git", "-C", str(g), "-c", "fetch.negotiationAlgorithm=noop", "fetch", "-q", "--no-tags",
                            "--no-write-fetch-head", "origin", *missing[i:i + 200]], capture_output=True, text=True)
        if r.returncode != 0:
            raise Unreadable(f"{g.name}: fetching {len(missing[i:i + 200])} blob(s) failed: {r.stderr.strip()}")


def show(g: Path, rev: str, rel: str) -> bytes | None:
    s = subprocess.run(["git", "-C", str(g), "show", f"{rev}:{rel}"], capture_output=True)
    return s.stdout if s.returncode == 0 else None


def tree(g: Path, rev: str = "origin/main") -> dict[str, str]:
    """path -> git blob id of every file at rev (no blob is fetched)."""
    out = subprocess.run(["git", "-C", str(g), "ls-tree", "-r", "-z", rev], check=True,
                         capture_output=True, text=True).stdout
    files = {}
    for item in out.split("\0"):
        if item:
            meta, path = item.split("\t", 1)
            mode, kind, blob = meta.split()
            if kind == "blob":
                files[path] = blob
    return files


def fetch_sources(entries: list[dict], remote: Remote) -> tuple[list[str], list[str], tuple]:
    """Each uniform entry's source commit: on its repository's main, with the entry's bytes."""
    problems: list[str] = []
    copies = 0
    uniform = [e for e in entries if "pending" not in e]
    want: dict[tuple[str, str], list[str]] = collections.defaultdict(list)
    for e in uniform:
        want[(e["source"]["repo"], e["source"]["rev"])].append(path_in(e, e["source"]["repo"]))
    for (repo, rev), rels in sorted(want.items()):
        remote.prefetch(repo, rev, rels)
    for e in uniform:
        repo, rev = e["source"]["repo"], e["source"]["rev"]
        g = remote(repo)
        on_main = subprocess.run(["git", "-C", str(g), "merge-base", "--is-ancestor", rev, "origin/main"],
                                 capture_output=True)
        if on_main.returncode != 0:
            problems.append(f"{e['path']}: source {repo} {rev[:12]} is not on {repo}'s main")
            continue
        data = show(g, rev, path_in(e, repo))
        if data is None:
            problems.append(f"{e['path']}: not at {path_in(e, repo)} in {repo} {rev[:12]}")
            continue
        copies += 1
        if sha256(data) != e["sha256"]:
            problems.append(f"{e['path']}: {repo} {rev[:12]} has sha256 {sha256(data)}, the table {e['sha256']}")
    return problems, [], counts(len(uniform), len({e["source"]["repo"] for e in uniform}), copies,
                                len(entries) - len(uniform))


def live(entries: list[dict], remote: Remote, today: datetime.date):
    """Every listed repository's main against the table, and the discovery pass."""
    problems: list[str] = []
    notes: list[str] = []
    copies = pending = 0
    repos = sorted({r for e in entries for r in e["repos"]} | {r for e in entries for r in e.get("exempt", {})})
    trees = {r: tree(remote(r)) for r in repos}
    if not trees:
        raise Unreadable("no repository read (compared nothing)")
    for r in repos:
        remote.prefetch(r, "origin/main", [path_in(e, r) for e in entries if r in e["repos"]])
    for e in entries:
        if "pending" in e:
            pending += 1
            since = datetime.date.fromisoformat(e["pending"]["since"])
            age = (today - since).days
            found: dict[str, list[str]] = collections.defaultdict(list)
            for r in e["repos"]:
                data = show(remote(r), "origin/main", path_in(e, r))
                found["absent" if data is None else sha256(data)].append(r)
                copies += data is not None
            recorded = {k: sorted(v) for k, v in e["pending"]["variants"].items()}
            moved = "" if dict(found) == recorded else " (the variants on the mains have moved since the table)"
            notes.append(f"{e['path']}: pending {age} day(s), {len(found)} variant(s): "
                         + "; ".join(f"{k[:12]} {','.join(v)}" for k, v in sorted(found.items())) + moved)
            if age > PENDING_MAX_DAYS:
                problems.append(f"{e['path']}: pending since {e['pending']['since']}, more than "
                                f"{PENDING_MAX_DAYS} days ({e['pending']['exit']})")
            continue
        for r in e["repos"]:
            rel = path_in(e, r)
            data = show(remote(r), "origin/main", rel)
            if data is None:
                problems.append(f"{rel}: missing on {r} main")
                continue
            copies += 1
            if sha256(data) != e["sha256"]:
                problems.append(f"{rel}: {r} main has sha256 {sha256(data)}, the table {e['sha256']}")
    # discovery
    known = {e["path"] for e in entries} | {q for e in entries for q in e.get("paths", {}).values()}
    by_path: dict[str, dict[str, list[str]]] = collections.defaultdict(lambda: collections.defaultdict(list))
    for r, files in trees.items():
        for path, blob in files.items():
            if path.startswith(DISCOVERED):
                by_path[path][blob].append(r)
    for path, blobs in sorted(by_path.items()):
        if path in known:
            continue
        shared = {b: rs for b, rs in blobs.items() if len(rs) >= 2}
        if shared:
            problems.append(f"{path}: byte-identical in {', '.join(sorted(max(shared.values(), key=len)))} "
                            f"but has no entry")
    for e in entries:
        listed = set(e["repos"]) | set(e.get("exempt", {}))
        for r, files in trees.items():
            if r not in listed and e["path"] in files:
                problems.append(f"{e['path']}: present on {r} main, which the entry neither lists nor exempts")
    return problems, notes, counts(len(entries), len(trees), copies, pending)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--table", required=True, type=Path)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--fetch", action="store_true", help="fetch each source commit and compare")
    mode.add_argument("--live", action="store_true", help="compare every listed repository's main")
    mode.add_argument("--repo", type=Path, help="a crate checkout to check against the table")
    ap.add_argument("--name", help="the crate's repository name (ALICE-…), with --repo")
    ap.add_argument("--expect-copies", type=int,
                    help="with --live: the number of copies that must be compared (count lock)")
    ap.add_argument("--today", help="with --live: the date pending rows are aged against (default: today, UTC)")
    ap.add_argument("--base-table", type=Path,
                    help="the table this one replaces (origin/main's): more pending rows than it is a finding")
    a = ap.parse_args(argv)
    if (a.repo is None) != (a.name is None):
        ap.error("--repo and --name go together")
    notes: list[str] = []
    try:
        entries = load(a.table.read_text(encoding="utf-8"))
        base_pending = None
        if a.base_table is not None:
            base_pending = sum("pending" in e for e in load(a.base_table.read_text(encoding="utf-8")))
        if a.repo is not None:
            if not REPO.match(a.name):
                raise Unreadable(f"--name {a.name!r} is not an ALICE-… repository name")
            problems, notes, c = check_repo(entries, a.repo, a.name)
        elif a.fetch or a.live:
            with tempfile.TemporaryDirectory() as d:
                remote = Remote(Path(d))
                if a.fetch:
                    problems, notes, c = fetch_sources(entries, remote)
                else:
                    today = (datetime.date.fromisoformat(a.today) if a.today
                             else datetime.datetime.now(datetime.timezone.utc).date())
                    problems, notes, c = live(entries, remote, today)
        else:
            problems = []
            c = counts(len(entries), len({r for e in entries for r in e["repos"]}),
                       sum(len(e["repos"]) for e in entries), sum("pending" in e for e in entries))
    except (Unreadable, OSError, ValueError) as e:
        print(f"shared_files_check: {e}", file=sys.stderr)
        return 2
    if base_pending is not None:
        if c[3] > base_pending:
            problems.append(f"{c[3]} pending rows, the base table has {base_pending} (pending only goes down)")
        else:
            print(f"shared_files_check: pending {c[3]}, the base table {base_pending}")
    if a.expect_copies is not None and c[2] != a.expect_copies:
        problems.append(f"compared {c[2]} copies, the count lock says {a.expect_copies}")
    for n in notes:
        print(f"shared_files_check: pending: {n}")
    for p in problems:
        print(f"shared_files_check: {p}", file=sys.stderr)
    print(f"shared_files_check: {summary(c)}, {len(problems)} finding(s)")
    if c[2] == 0 and not problems and not notes:
        print("shared_files_check: compared nothing", file=sys.stderr)
        return 2
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
