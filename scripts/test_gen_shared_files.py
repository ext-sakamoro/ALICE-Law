#!/usr/bin/env python3
"""Tests of scripts/gen_shared_files.py (python3 scripts/test_gen_shared_files.py)

The repositories' main is read from local bare repositories standing in for GitHub
(the fixtures of scripts/test_shared_files_check.py)."""
from __future__ import annotations

import sys
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_shared_files as gen  # noqa: E402
import shared_files_check as sfc  # noqa: E402
from test_shared_files_check import OTHER, SHARED, Base, h, run  # noqa: E402

TODAY = "2026-10-17"


class Generate(Base):
    def registry(self, text: str) -> Path:
        p = Path(self.tmp.name) / "registry.tsv"
        p.write_text(text, encoding="utf-8")
        return p

    def gen(self, *argv: str):
        return run(gen.main, ["--table", str(self.t), "--today", TODAY, *argv])

    def entries(self) -> dict[str, dict]:
        return {e["path"]: e for e in sfc.load(self.t.read_text(encoding="utf-8"))}

    def test_write_then_check_is_current_and_reads_back(self):
        reg = self.registry("# c\nscripts/s.sh\tALICE-A,ALICE-B\tenforced\n")
        # ALICE-C has no row, so it is not a table repository and is not widened in
        self.assertEqual(self.gen("--write", "--registry", str(reg))[0], 0)
        text = self.t.read_text(encoding="utf-8")
        self.assertTrue(text.startswith("# Generated by scripts/gen_shared_files.py"))
        e = self.entries()["scripts/s.sh"]
        self.assertEqual((e["sha256"], e["source"]["rev"]), (h(SHARED), self.w.revs["ALICE-A"]))
        self.assertEqual(self.gen("--check")[0], 0)

    def test_disagreeing_copies_become_a_pending_row_with_the_majority_target(self):
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B,ALICE-C\n")
        self.assertEqual(self.gen("--write", "--registry", str(reg))[0], 0)
        p = self.entries()["scripts/s.sh"]["pending"]
        self.assertEqual(p["variants"], {h(SHARED): ["ALICE-A", "ALICE-B"], h(OTHER): ["ALICE-C"]})
        self.assertEqual((p["target"], p["owner"], p["since"]), (h(SHARED), "ALICE-A", TODAY))

    def test_a_target_can_be_named(self):
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B,ALICE-C\n")
        self.gen("--write", "--registry", str(reg), "--target", f"scripts/s.sh={h(OTHER)}@ALICE-C")
        p = self.entries()["scripts/s.sh"]["pending"]
        self.assertEqual((p["target"], p["owner"]), (h(OTHER), "ALICE-C"))

    def test_a_row_moving_to_new_bytes_stays_pending_until_every_copy_has_them(self):
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B\tenforced\tnext=" + "0" * 40 + "\n")
        new = SHARED + b"# v2\n"
        self.gen("--write", "--registry", str(reg), "--target", f"scripts/s.sh={h(new)}@ALICE-A")
        self.assertIn("pending", self.entries()["scripts/s.sh"])
        # regenerated from the table: still pending, the mains still have the old bytes
        self.assertEqual(self.gen("--write")[0], 0)
        self.assertIn("pending", self.entries()["scripts/s.sh"])
        self.w.commit("ALICE-A", {"scripts/s.sh": new})
        self.gen("--write")
        self.assertIn("pending", self.entries()["scripts/s.sh"], "one copy moved, the other has not")
        self.w.commit("ALICE-B", {"scripts/s.sh": new})
        self.gen("--write")
        self.assertEqual(self.entries()["scripts/s.sh"]["sha256"], h(new))

    def test_a_rollout_becomes_a_planned_row_when_its_owner_lands_and_uniform_when_all_have(self):
        new = SHARED + b"# v2\n"
        reg = self.registry(f"scripts/s.sh\tALICE-A,ALICE-B\tpending\tnext={sfc.git_blob(new)}\n")
        # next= on no main yet: the row is what the copies say (uniform), not born pending
        self.assertEqual(self.gen("--write", "--registry", str(reg))[0], 0)
        self.assertEqual(self.entries()["scripts/s.sh"]["sha256"], h(SHARED))
        self.w.commit("ALICE-B", {"scripts/s.sh": new})
        self.assertEqual(self.gen("--write", "--next-from", str(reg))[0], 0)
        p = self.entries()["scripts/s.sh"]["pending"]
        self.assertEqual((p["planned"], p["target"], p["owner"], p["since"]),
                         (sfc.git_blob(new), h(new), "ALICE-B", TODAY))
        # regenerated from the table alone: the planned id is kept, and the table is current
        self.assertEqual(run(gen.main, ["--table", str(self.t), "--today", "2026-10-20", "--write"])[0], 0)
        self.assertEqual(self.entries()["scripts/s.sh"]["pending"]["since"], TODAY)
        self.assertEqual(self.gen("--check", "--strict")[0], 0)
        self.w.commit("ALICE-A", {"scripts/s.sh": new})
        self.gen("--write")
        self.assertEqual(self.entries()["scripts/s.sh"]["sha256"], h(new))

    def test_a_re_rolled_planned_id_keeps_the_date_it_became_planned(self):
        v2, v3 = SHARED + b"# v2\n", SHARED + b"# v3\n"
        reg = self.registry(f"scripts/s.sh\tALICE-A,ALICE-B\tpending\tnext={sfc.git_blob(v2)}\n")
        self.gen("--write", "--registry", str(reg))
        self.w.commit("ALICE-B", {"scripts/s.sh": v2})
        self.gen("--write", "--next-from", str(reg))
        self.assertEqual(self.entries()["scripts/s.sh"]["pending"]["since"], TODAY)
        # the target is re-rolled to v3 twelve days later: still the same rollout, the clock does not restart
        reg = self.registry(f"scripts/s.sh\tALICE-A,ALICE-B\tpending\tnext={sfc.git_blob(v3)}\n")
        self.w.commit("ALICE-B", {"scripts/s.sh": v3})
        self.assertEqual(run(gen.main, ["--table", str(self.t), "--today", "2026-10-29", "--write",
                                        "--next-from", str(reg)])[0], 0)
        p = self.entries()["scripts/s.sh"]["pending"]
        self.assertEqual((p["planned"], p["since"]), (sfc.git_blob(v3), TODAY))
        # and so it ages out on the original clock (15 days after it became planned)
        code, out = run(sfc.main, ["--table", str(self.t), "--live", "--today", "2026-11-01"])
        self.assertEqual(code, 1, out)
        self.assertIn("more than 14 days", out)

    def test_a_next_id_that_no_copy_has_does_not_make_a_planned_row(self):
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B,ALICE-C\tenforced\tnext=" + "1" * 40 + "\n")
        self.gen("--write", "--registry", str(reg))
        p = self.entries()["scripts/s.sh"]["pending"]
        self.assertNotIn("planned", p)  # ALICE-C differs: an unplanned divergence, as before

    def test_since_exit_target_and_exemptions_survive_regeneration(self):
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B,ALICE-C\n")
        run(gen.main, ["--table", str(self.t), "--today", "2026-10-01", "--write", "--registry", str(reg)])
        text = self.t.read_text(encoding="utf-8").replace(gen.EXIT_DIFFER, "ALICE-C takes the shared copy")
        self.t.write_text(text, encoding="utf-8")
        self.assertEqual(self.gen("--write")[0], 0)
        p = self.entries()["scripts/s.sh"]["pending"]
        self.assertEqual((p["since"], p["exit"]), ("2026-10-01", "ALICE-C takes the shared copy"))

    def test_rows_are_widened_to_every_table_repository_with_the_path(self):
        self.w.commit("ALICE-C", {"scripts/c.sh": b"c\n"})
        self.w.commit("ALICE-A", {"scripts/c.sh": b"c\n"})
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B\nscripts/c.sh\tALICE-A,ALICE-C\n")
        self.gen("--write", "--registry", str(reg))
        self.assertEqual(self.entries()["scripts/s.sh"]["repos"], ["ALICE-A", "ALICE-B", "ALICE-C"])

    def test_a_per_repository_row_is_kept_and_never_widened(self):
        self.w.commit("ALICE-C", {"scripts/c.sh": b"c\n"})
        self.w.commit("ALICE-A", {"scripts/c.sh": b"c\n"})
        rev = self.w.revs["ALICE-C"]
        rows = [self.w.per_repo(), {"path": "scripts/c.sh", "sha256": h(b"c\n"),
                                    "source": {"repo": "ALICE-C", "rev": rev},
                                    "repos": ["ALICE-A", "ALICE-C"], "paths": {}, "exempt": {}}]
        self.t.write_text(gen.render(rows), encoding="utf-8")
        self.assertEqual(self.gen("--write")[0], 0)
        e = self.entries()["scripts/s.sh"]
        self.assertEqual((e["repos"], sorted(e["exempt"])), ([], ["ALICE-A", "ALICE-B"]))

    def test_discover_adds_a_byte_identical_file_with_no_row(self):
        self.w.commit("ALICE-A", {"scripts/new.py": b"print(1)\n"})
        self.w.commit("ALICE-B", {"scripts/new.py": b"print(1)\n"})
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B\n")
        self.gen("--write", "--registry", str(reg), "--discover")
        self.assertEqual(self.entries()["scripts/new.py"]["repos"], ["ALICE-A", "ALICE-B"])

    def test_check_is_red_when_a_uniform_main_moved(self):
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B\n")
        self.gen("--write", "--registry", str(reg))
        self.w.commit("ALICE-B", {"scripts/s.sh": b"new\n"})
        self.assertEqual(self.gen("--check")[0], 1)

    def test_check_reports_but_passes_moved_variants_of_a_pending_row(self):
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B,ALICE-C\n")
        self.gen("--write", "--registry", str(reg))
        self.w.commit("ALICE-C", {"scripts/s.sh": b"third\n"})
        code, out = self.gen("--check")
        self.assertEqual(code, 0, out)
        self.assertIn("the variants on the mains have moved", out)

    def gained_holder(self, data: bytes):
        """the table lists s.sh on A and B; then ALICE-C, a table repository through c.sh, gains s.sh"""
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B\nscripts/c.sh\tALICE-A,ALICE-C\n")
        self.w.commit("ALICE-C", {"scripts/c.sh": b"c\n", "scripts/s.sh": None})
        self.w.commit("ALICE-A", {"scripts/c.sh": b"c\n"})
        self.gen("--write", "--registry", str(reg))
        self.w.commit("ALICE-C", {"scripts/s.sh": data})

    def test_check_reports_an_unlisted_holder_with_the_same_bytes(self):
        self.gained_holder(SHARED)
        code, out = self.gen("--check")
        self.assertEqual(code, 0, out)
        self.assertIn("unlisted holder, same bytes: scripts/s.sh on ALICE-C", out)

    def test_check_fails_when_a_holder_drops_the_file_while_another_gains_it(self):
        # gaining a same-bytes holder does not hide a carrier that lost the file
        self.gained_holder(SHARED)
        self.w.commit("ALICE-B", {"scripts/s.sh": None})
        self.assertEqual(self.gen("--check")[0], 1)

    def test_check_fails_when_a_pending_row_gains_a_holder_with_a_new_variant(self):
        # the table: s.sh pending between A (SHARED) and B (other bytes); C is a table repository via c.sh
        self.w.commit("ALICE-B", {"scripts/s.sh": b"b variant\n"})
        self.w.commit("ALICE-C", {"scripts/c.sh": b"c\n", "scripts/s.sh": None})
        self.w.commit("ALICE-A", {"scripts/c.sh": b"c\n"})
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B\nscripts/c.sh\tALICE-A,ALICE-C\n")
        self.gen("--write", "--registry", str(reg))
        self.assertIn("pending", self.entries()["scripts/s.sh"])
        # C gains s.sh with bytes no variant has: not a same-bytes holder
        self.w.commit("ALICE-C", {"scripts/s.sh": b"a third variant\n"})
        self.assertEqual(self.gen("--check")[0], 1)
        # with bytes of a recorded variant it is only reported
        self.w.commit("ALICE-C", {"scripts/s.sh": SHARED})
        code, out = self.gen("--check")
        self.assertEqual(code, 0, out)
        self.assertIn("unlisted holder, same bytes", out)

    def test_a_row_that_gained_and_lost_holders_is_not_put_back(self):
        # unit level: through the generator a dropped copy becomes an "absent" variant (a pending row),
        # so this branch is pinned on the function itself
        old = [{"path": "scripts/s.sh", "sha256": h(SHARED), "source": {"repo": "ALICE-A", "rev": "0" * 40},
                "repos": ["ALICE-A", "ALICE-B"]}]
        new = [{**old[0], "repos": ["ALICE-A", "ALICE-C"], "paths": {}, "exempt": {}}]
        out, held = gen.unlisted_same_bytes(old, new)
        self.assertEqual((out, held), (new, []))
        gained = [{**old[0], "repos": ["ALICE-A", "ALICE-B", "ALICE-C"], "paths": {}, "exempt": {}}]
        out, held = gen.unlisted_same_bytes(old, gained)
        self.assertEqual((out, held), (old, [("scripts/s.sh", ["ALICE-C"])]))

    def test_strict_check_fails_on_an_unlisted_holder(self):
        self.gained_holder(SHARED)
        self.assertEqual(self.gen("--check", "--strict")[0], 1)

    def test_check_fails_on_a_new_holder_with_other_bytes(self):
        self.gained_holder(b"different\n")
        self.assertEqual(self.gen("--check")[0], 1)

    def test_moved_pending_variants_are_reported_in_strict_mode_too(self):
        # a pending row's copies move during its rollout by definition: strict is about unlisted holders
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B,ALICE-C\n")
        self.gen("--write", "--registry", str(reg))
        self.w.commit("ALICE-C", {"scripts/s.sh": b"third\n"})
        self.assertEqual(self.gen("--check")[0], 0)
        code, out = self.gen("--check", "--strict")
        self.assertEqual(code, 0, out)
        self.assertIn("the variants on the mains have moved", out)

    def test_an_empty_registry_writes_nothing(self):
        reg = self.registry("# nothing\n")
        self.assertEqual(self.gen("--write", "--registry", str(reg))[0], 2)


if __name__ == "__main__":
    unittest.main()
