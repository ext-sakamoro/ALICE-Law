#!/usr/bin/env python3
"""Tests of scripts/gen_shared_files.py (python3 scripts/test_gen_shared_files.py)

The repositories' main is read from local bare repositories standing in for GitHub
(the fixtures of scripts/test_shared_files_check.py)."""
from __future__ import annotations

import sys
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_shared_files as gen  # noqa: E402
import shared_files_check as sfc  # noqa: E402
from test_shared_files_check import Base, run  # noqa: E402


class Generate(Base):
    def registry(self, text: str) -> Path:
        p = Path(self.tmp.name) / "registry.tsv"
        p.write_text(text, encoding="utf-8")
        return p

    def gen(self, *argv: str):
        return run(gen.main, ["--table", str(self.t), *argv])

    def test_write_then_check_is_current_and_reads_back(self):
        reg = self.registry("# c\nscripts/s.sh\tALICE-A,ALICE-B\tenforced\n")
        self.assertEqual(self.gen("--write", "--registry", str(reg))[0], 0)
        text = self.t.read_text(encoding="utf-8")
        self.assertTrue(text.startswith("# Generated by scripts/gen_shared_files.py"))
        self.assertEqual(sfc.load(text)[0]["source"]["rev"], self.w.revs["ALICE-A"])
        self.assertEqual(self.gen("--check")[0], 0)

    def test_check_is_red_when_a_main_moved(self):
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B\n")
        self.gen("--write", "--registry", str(reg))
        for name in ("ALICE-A", "ALICE-B"):
            self.w.commit(name, {"scripts/s.sh": b"new\n"})
        self.assertEqual(self.gen("--check")[0], 1)

    def test_disagreeing_copies_are_refused_or_skipped(self):
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-C\n")
        self.assertEqual(self.gen("--write", "--registry", str(reg))[0], 1)
        self.assertEqual(self.gen("--write", "--registry", str(reg), "--skip-disagreeing")[0], 2)

    def test_pending_and_next_rows_are_not_exported(self):
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B\tpending\n"
                            "README\tALICE-A,ALICE-B\tenforced\tnext=" + "0" * 40 + "\n")
        code, out = self.gen("--write", "--registry", str(reg))
        self.assertEqual(code, 2, out)
        self.assertIn("in rollout", out)

    def test_exemptions_survive_regeneration_from_the_registry(self):
        self.t.write_text(self.w.table(exempt={"ALICE-C": "a different script of its own"}), encoding="utf-8")
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B\n")
        self.assertEqual(self.gen("--write", "--registry", str(reg))[0], 0)
        self.assertEqual(sfc.load(self.t.read_text(encoding="utf-8"))[0]["exempt"],
                         {"ALICE-C": "a different script of its own"})


if __name__ == "__main__":
    unittest.main()
