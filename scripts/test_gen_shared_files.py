#!/usr/bin/env python3
"""Tests of scripts/gen_shared_files.py (python3 scripts/test_gen_shared_files.py)

The repositories' main is read from local bare repositories standing in for GitHub
(the fixtures of scripts/test_shared_files_check.py)."""
from __future__ import annotations

import sys
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_shared_files as gen  # noqa: E402
import shared_files_check as sfc  # noqa: E402
from test_shared_files_check import OTHER, SHARED, Base, h, run  # noqa: E402

TODAY = "2026-10-17"


class Generate(Base):
    def registry(self, text: str) -> Path:
        p = Path(self.tmp.name) / "registry.tsv"
        p.write_text(text, encoding="utf-8")
        return p

    def gen(self, *argv: str):
        return run(gen.main, ["--table", str(self.t), "--today", TODAY, *argv])

    def entries(self) -> dict[str, dict]:
        return {e["path"]: e for e in sfc.load(self.t.read_text(encoding="utf-8"))}

    def test_write_then_check_is_current_and_reads_back(self):
        reg = self.registry("# c\nscripts/s.sh\tALICE-A,ALICE-B\tenforced\n")
        # ALICE-C has no row, so it is not a table repository and is not widened in
        self.assertEqual(self.gen("--write", "--registry", str(reg))[0], 0)
        text = self.t.read_text(encoding="utf-8")
        self.assertTrue(text.startswith("# Generated by scripts/gen_shared_files.py"))
        e = self.entries()["scripts/s.sh"]
        self.assertEqual((e["sha256"], e["source"]["rev"]), (h(SHARED), self.w.revs["ALICE-A"]))
        self.assertEqual(self.gen("--check")[0], 0)

    def test_disagreeing_copies_become_a_pending_row_with_the_majority_target(self):
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B,ALICE-C\n")
        self.assertEqual(self.gen("--write", "--registry", str(reg))[0], 0)
        p = self.entries()["scripts/s.sh"]["pending"]
        self.assertEqual(p["variants"], {h(SHARED): ["ALICE-A", "ALICE-B"], h(OTHER): ["ALICE-C"]})
        self.assertEqual((p["target"], p["owner"], p["since"]), (h(SHARED), "ALICE-A", TODAY))

    def test_a_registry_line_can_carry_an_exempt_only_row(self):
        # a row every copy of which is exempted lists no repository; `-` in the repositories column says so, and the
        # exemptions come from the table as for every registry row (a registry run must not drop such a row)
        self.assertEqual(self.gen("--write", "--registry", str(self.registry("scripts/s.sh\tALICE-A,ALICE-B\n")))[0], 0)
        text = self.t.read_text(encoding="utf-8") + (
            '\n[[file]]\npath = "scripts/zz_own.toml"\nrepos = []\nexempt = { "ALICE-A" = "this repository\'s own list '
            'of its own files", "ALICE-B" = "this repository\'s own list of its own files" }\n')
        self.t.write_text(text, encoding="utf-8")
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B\nscripts/zz_own.toml\t-\n")
        code, out = self.gen("--write", "--registry", str(reg))
        self.assertEqual(code, 0, out)
        e = self.entries()["scripts/zz_own.toml"]
        self.assertEqual((e["repos"], sorted(e["exempt"])), ([], ["ALICE-A", "ALICE-B"]))
        self.assertEqual(self.gen("--check")[0], 0)

    def test_a_new_path_is_born_as_a_planned_row(self):
        # a file no main holds yet, moving into every listed repository: planned from the start (the registry's
        # next= and --target name its bytes and owner), so the rollout is explicit and the ratchet allows it
        v = b"#!/bin/sh\n# new shared file\n"
        self.assertEqual(self.gen("--write", "--registry", str(self.registry("scripts/s.sh\tALICE-A,ALICE-B\n")))[0], 0)
        base = Path(self.tmp.name) / "base.toml"
        base.write_text(self.t.read_text(encoding="utf-8"), encoding="utf-8")
        # (registry() writes one file: the registry with the new row is made after the base run)
        reg = self.registry(f"scripts/s.sh\tALICE-A,ALICE-B\nscripts/n.sh\tALICE-A,ALICE-B\tpending\tnext={sfc.git_blob(v)}\n")
        code, out = self.gen("--write", "--registry", str(reg), "--next-from", str(reg),
                             "--target", f"scripts/n.sh={h(v)}@ALICE-A")
        self.assertEqual(code, 0, out)
        p = self.entries()["scripts/n.sh"]["pending"]
        self.assertEqual((p["planned"], p["target"], p["owner"], p["since"], p["exit"]),
                         (sfc.git_blob(v), h(v), "ALICE-A", TODAY, gen.EXIT_NEXT))
        self.assertNotIn("first_move", p)
        self.assertNotIn("moved_from", p)
        self.assertEqual(p["variants"], {"absent": ["ALICE-A", "ALICE-B"]})
        # regenerating before the owner lands keeps the plan (from the table, as CI does)
        self.assertEqual(self.gen("--check", "--next-from", str(reg))[0], 0)
        self.assertEqual(self.gen("--check")[0], 0)
        code, out = run(sfc.main, ["--table", str(self.t), "--base-table", str(base)])
        self.assertEqual(code, 0, out)
        # live: the bytes must be real, on the owner's ci/ branch until its main holds them
        self.assertEqual(run(sfc.main, ["--table", str(self.t), "--live", "--today", TODAY])[0], 1)
        self.w.ci("ALICE-A", "n-v1", {"scripts/n.sh": v})
        code, out = run(sfc.main, ["--table", str(self.t), "--live", "--today", TODAY])
        self.assertEqual(code, 0, out)
        # the owner lands: still planned; every main has the file: uniform
        self.w.commit("ALICE-A", {"scripts/n.sh": v})
        self.assertEqual(self.gen("--write", "--next-from", str(reg))[0], 0)
        self.assertEqual(self.entries()["scripts/n.sh"]["pending"]["planned"], sfc.git_blob(v))
        self.w.commit("ALICE-B", {"scripts/n.sh": v})
        self.assertEqual(self.gen("--write", "--next-from", str(reg))[0], 0)
        self.assertEqual(self.entries()["scripts/n.sh"]["sha256"], h(v))

    def test_a_target_can_be_named(self):
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B,ALICE-C\n")
        self.gen("--write", "--registry", str(reg), "--target", f"scripts/s.sh={h(OTHER)}@ALICE-C")
        p = self.entries()["scripts/s.sh"]["pending"]
        self.assertEqual((p["target"], p["owner"]), (h(OTHER), "ALICE-C"))

    def test_a_row_moving_to_new_bytes_stays_pending_until_every_copy_has_them(self):
        reg = self.registry("scripts/s.sh\tALICE-A,ALICE-B\tenforced\tnext=" + "0" * 40 + "\n")
        new = SHARED + b"# v2\n"
        self.gen("--write", "--registry", str(reg), "--target", f"scripts/s.sh={h(new)}@ALICE-A")
        self.assertIn("pending", self.entries()["scripts/s.sh"])
        # regenerated from the table: still pending, the mains still have the old bytes
        self.assertEqual(self.gen("--write")[0], 0)
        self.assertIn("pending", self.entries()["scripts/s.sh"])
        self.w.commit("ALICE-A", {"scripts/s.sh": new})
        self.gen("--write")
        self.assertIn("pending", self.entries()["scripts/s.sh"], "one copy moved, the other has not")
        self.w.commit("ALICE-B", {"scripts/s.sh": new})
        self.gen("--write")
        self.assertEqual(self.entries()["scripts/s.sh"]["sha256"], h(new))

    def test_a_rollout_becomes_a_planned_row_when_its_owner_lands_and_uniform_when_all_have(self):
        new = SHARED + b"# v2\n"
        reg = self.registry(f"scripts/s.sh\tALICE-A,ALICE-B\tpending\tnext={sfc.git_blob(new)}\n")
        # next= on no main yet: the row is what the copies say (uniform), not born pending
        self.assertEqual(self.gen("--write", "--registry", str(reg))[0], 0)
        self.assertEqual(self.entries()["scripts/s.sh"]["sha256"], h(SHARED))
        self.w.commit("ALICE-B", {"scripts/s.sh": new})
        self.assertEqual(self.gen("--write", "--next-from", str(reg))[0], 0)
        p = self.entries()["scripts/s.sh"]["pending"]
        self.assertEqual((p["planned"], p["target"], p["owner"], p["since"]),
                         (sfc.git_blob(new), h(new), "ALICE-B", TODAY))
        # regenerated from the table alone: the planned id is kept, and the table is current
        self.assertEqual(run(gen.main, ["--table", str(self.t), "--today", "2026-10-20", "--write"])[0], 0)
        self.assertEqual(self.entries()["scripts/s.sh"]["pending"]["since"], TODAY)
        self.assertEqual(self.gen("--check", "--strict")[0], 0)
        self.w.commit("ALICE-A", {"scripts/s.sh": new})
        self.gen("--write")
        self.assertEqual(self.entries()["scripts/s.sh"]["sha256"], h(new))

    def test_a_uniform_row_is_planned_to_bytes_no_main_holds_with_their_sha256(self):
        # without a planned row no copy could take the new bytes (each repository's own check refuses a copy the
        # table does not record), so the first move of a uniform row is planned from the table, with --target
        v2 = SHARED + b"# v2\n"
        self.assertEqual(self.gen("--write", "--registry", str(self.registry("scripts/s.sh\tALICE-A,ALICE-B\n")))[0], 0)
        base = Path(self.tmp.name) / "base.toml"
        base.write_text(self.t.read_text(encoding="utf-8"), encoding="utf-8")
        reg = self.registry(f"scripts/s.sh\tALICE-A,ALICE-B\tpending\tnext={sfc.git_blob(v2)}\n")
        self.assertEqual(self.gen("--write", "--next-from", str(reg), "--target",
                                  f"scripts/s.sh={h(v2)}@ALICE-A")[0], 0)
        p = self.entries()["scripts/s.sh"]["pending"]
        self.assertEqual((p["planned"], p["target"], p["owner"], p["since"], p["exit"]),
                         (sfc.git_blob(v2), h(v2), "ALICE-A", TODAY, gen.EXIT_NEXT))
        self.assertEqual(p["moved_from"], {"planned": sfc.git_blob(SHARED), "target": h(SHARED)})
        # a planned row, explained by the base's uniform bytes: the ratchet holds, live passes, the table is current
        code, out = run(sfc.main, ["--table", str(self.t), "--base-table", str(base)])
        self.assertEqual(code, 0, out)
        self.assertIn("pending 1 (planned 1, unplanned 0), the base table 0 (planned 0, unplanned 0)", out)
        # the planned bytes must exist: on no branch of the owner yet, live is red
        code, out = run(sfc.main, ["--table", str(self.t), "--live", "--today", TODAY])
        self.assertEqual(code, 1, out)
        self.assertIn("on the tip of neither its main nor a ci/ branch", out)
        # the owner's ci/ branch holds them: live passes
        self.w.ci("ALICE-A", "s-v2", {"scripts/s.sh": v2})
        code, out = run(sfc.main, ["--table", str(self.t), "--live", "--today", TODAY])
        self.assertEqual(code, 0, out)
        self.assertIn("moving to", out)
        self.assertEqual(self.gen("--check", "--strict", "--next-from", str(reg))[0], 0)
        # the owner lands: still planned; every main has the bytes: uniform
        self.w.commit("ALICE-A", {"scripts/s.sh": v2})
        self.assertEqual(self.gen("--write", "--next-from", str(reg))[0], 0)
        self.assertEqual(self.entries()["scripts/s.sh"]["pending"]["planned"], sfc.git_blob(v2))
        self.w.commit("ALICE-B", {"scripts/s.sh": v2})
        self.gen("--write", "--next-from", str(reg))
        self.assertEqual(self.entries()["scripts/s.sh"]["sha256"], h(v2))

    def test_a_first_move_needs_its_target_and_a_listed_owner(self):
        v2 = SHARED + b"# v2\n"
        self.assertEqual(self.gen("--write", "--registry", str(self.registry("scripts/s.sh\tALICE-A,ALICE-B\n")))[0], 0)
        reg = self.registry(f"scripts/s.sh\tALICE-A,ALICE-B\tpending\tnext={sfc.git_blob(v2)}\n")
