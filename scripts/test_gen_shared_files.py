    def test_a_planned_row_whose_bytes_left_every_main_is_refused_not_dropped(self):
        self.landed_v2()
        self.w.commit("ALICE-A", {"scripts/s.sh": SHARED})
        self.w.commit("ALICE-B", {"scripts/s.sh": SHARED})
