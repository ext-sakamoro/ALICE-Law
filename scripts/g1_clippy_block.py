#!/usr/bin/env python3
"""Write (or check) G1's methods inside each clippy configuration of a repository, as one generated region.

    g1_clippy_block.py --write <repo>
    g1_clippy_block.py --check <repo>

G1 (conformance/gates.toml) bans the f32 / f64 methods whose results IEEE 754 does not pin; a crate shows it with a
clippy configuration that lists every banned method for both widths (and a CI clippy run that denies the lint; the
daily g1_coverage_live job checks both in every Law-bearing repository). Clippy reads one clippy.toml per crate, and
the repositories keep other entries in the same `disallowed-methods` array (clock sources, max/min, ...) and other
keys (`disallowed-types`, `disallowed-macros`, `msrv`), so G1's entries cannot be a whole-file copy. They are one
region inside the array:

    disallowed-methods = [
        # >>> ALICE-Law G1 (generated by scripts/g1_clippy_block.py; do not edit) >>>
        { path = "f32::acos", reason = "G1: ..." },
        ...
        # <<< ALICE-Law G1 <<<
        { path = "std::time::Instant::now", reason = "..." },   # the repository's own, kept as written
    ]

--write: every clippy.toml / .clippy.toml in the repository (found by walking it, `.github/clippy-lib/` included;
not under target/, .git/, tests/ fixtures or fuzz/) gets the region with exactly the methods gates.toml bans (and the
pending ones banned by default), for f32 and f64, with gates.toml's reasons; a G1 entry already standing outside the
region is moved into it (one line, one entry), never duplicated; every other line of the file stays byte for byte. A
repository with no clippy configuration gets a root clippy.toml holding the array alone. The result must parse and
name no path twice in the array, or nothing is written.
--check: every file's region is the generated one; 0 files is a failure (exit 2).
Exit 0 / 1 (a file differs, --check) / 2 (nothing found, a file that does not parse, or an unsafe edit).
"""
from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
GATES = HERE.parent / "conformance" / "gates.toml"
BEGIN = "# >>> ALICE-Law G1 (generated by scripts/g1_clippy_block.py; do not edit) >>>"
END = "# <<< ALICE-Law G1 <<<"
NAMES = ("clippy.toml", ".clippy.toml")
SKIP = {"target", ".git", "fuzz", "node_modules"}
ENTRY_PATH_RE = re.compile(r'^\s*(?:\{\s*path\s*=\s*)?"((?:(?:core|std)::)?(f32|f64)::([a-z_0-9]+))"')


class Unsafe(Exception):
    pass


def g1_methods() -> list[tuple[str, str]]:
    """(method, reason) G1 bans: verdict banned, and pending whose default is banned"""
    gates = tomllib.loads(GATES.read_text(encoding="utf-8"))["gate"]
    g1 = next(g for g in gates if g["id"] == "G1")
    out = []
    for m in g1["methods"]:
        if m["verdict"] == "banned" or (m["verdict"] == "pending" and m.get("default") == "banned"):
            out.append((m["name"], m.get("reason", "")))
    if not out:
        raise Unsafe("conformance/gates.toml bans no G1 method")
    return sorted(out)


def region(methods: list[tuple[str, str]], indent: str = "    ") -> list[str]:
    lines = [indent + BEGIN]
    for name, reason in methods:
        for w in ("f32", "f64"):
            r = (f"G1: {reason}" if reason else "G1").replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'{indent}{{ path = "{w}::{name}", reason = "{r}" }},')
    lines.append(indent + END)
    return lines


def configs(repo: Path) -> list[Path]:
    out = []
    for p in sorted(repo.rglob("*")):
        rel = p.relative_to(repo).parts
        if p.name in NAMES and p.is_file() and not SKIP.intersection(rel[:-1]) and "tests" not in rel[:-1]:
            out.append(p)
    return out


def array_bounds(lines: list[str]) -> tuple[int, int] | None:
    """(index of the `disallowed-methods = [` line, index of its closing `]` line), None when the key is absent; an
    array opened and closed on one line, or a bracket inside a value, is refused (the edit would not be safe)"""
    start = next((i for i, ln in enumerate(lines) if re.match(r"^\s*disallowed-methods\s*=", ln)), None)
    if start is None:
        return None
    if not re.match(r"^\s*disallowed-methods\s*=\s*\[\s*(#.*)?$", lines[start]):
        raise Unsafe("disallowed-methods is not an array opened alone on its line")
    for j in range(start + 1, len(lines)):
        if re.match(r"^\s*\]\s*(#.*)?$", lines[j]):
            return start, j
        if "]" in lines[j].split("#", 1)[0].replace('"]"', "") and "[" not in lines[j]:
            raise Unsafe(f"line {j + 1}: a closing bracket that is not alone on its line")
    raise Unsafe("disallowed-methods has no closing bracket alone on a line")


def rewrite(text: str, methods: list[tuple[str, str]]) -> str:
    g1 = {f"{w}::{n}" for n, _ in methods for w in ("f32", "f64")}
    lines = text.splitlines()
    bounds = array_bounds(lines)
    if bounds is None:
        body = "disallowed-methods = [\n" + "\n".join(region(methods)) + "\n]\n"
        if not text.strip():
            return body
        return text + ("" if text.endswith("\n") else "\n") + body
    start, end = bounds
    inner = lines[start + 1:end]
    kept, inside = [], False
    for ln in inner:
        s = ln.strip()
        if s == BEGIN:
            inside = True
            continue
        if s == END:
            inside = False
            continue
        if inside:
            continue
        m = ENTRY_PATH_RE.match(ln)
        if m and f"{m.group(2)}::{m.group(3)}" in g1:
            if len(re.findall(r"\bpath\s*=", ln)) > 1 or len(re.findall(r'"(?:(?:core|std)::)?f(?:32|64)::', ln)) > 1:
                raise Unsafe(f"a line holds more than one entry: {s[:60]}")
            continue  # a G1 entry outside the region: moved into it
        kept.append(ln)
    if inside:
        raise Unsafe("the G1 region has no end marker")
    indent = re.match(r"^(\s*)", next((ln for ln in kept if ln.strip()), "    ")).group(1) or "    "
    new = lines[:start + 1] + region(methods, indent) + kept + lines[end:]
    return "\n".join(new) + ("\n" if text.endswith("\n") else "")


def validate(text: str, methods: list[tuple[str, str]]) -> None:
    data = tomllib.loads(text)
    paths = [e["path"] if isinstance(e, dict) else e for e in data.get("disallowed-methods", [])]
    dup = sorted({p for p in paths if paths.count(p) > 1})
    if dup:
        raise Unsafe(f"a path is named twice in disallowed-methods: {dup[:3]}")
    for n, _ in methods:
        for w in ("f32", "f64"):
            if f"{w}::{n}" not in paths:
                raise Unsafe(f"{w}::{n} is missing after the edit")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", type=Path, metavar="REPO")
    g.add_argument("--check", type=Path, metavar="REPO")
    a = ap.parse_args(argv)
    repo = a.write or a.check
    try:
        methods = g1_methods()
        files = configs(repo)
        if not files:
            if a.check:
                print(f"g1_clippy_block: {repo}: no clippy configuration (compared nothing)", file=sys.stderr)
                return 2
            files = [repo / "clippy.toml"]
        differ = []
        for f in files:
            old = f.read_text(encoding="utf-8") if f.exists() else ""
            if old:
                tomllib.loads(old)
            new = rewrite(old, methods)
            validate(new, methods)
            if new != old:
                differ.append(f)
                if a.write:
                    f.write_text(new, encoding="utf-8")
    except (Unsafe, tomllib.TOMLDecodeError, OSError) as e:
        print(f"g1_clippy_block: {e}", file=sys.stderr)
        return 2
    for f in differ:
        print(f"g1_clippy_block: {'wrote' if a.write else 'differs'}: {f.relative_to(repo)}")
    print(f"g1_clippy_block: {len(files)} file(s), {len(differ)} {'written' if a.write else 'differ'}, "
          f"{len(methods) * 2} G1 entries each")
    return 1 if (a.check and differ) else 0


if __name__ == "__main__":
    sys.exit(main())
