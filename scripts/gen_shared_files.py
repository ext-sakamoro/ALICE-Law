#!/usr/bin/env python3
"""Generate conformance/shared-files.toml (ALICE-Law G11 (c)).

The rows (path, repositories, alternative paths, exemptions) come from the existing table,
or with --registry from a registry of shared files: lines `path<TAB>repo,repo[:alt-path]
[<TAB>state[<TAB>next=<blob>]]`, `#` comments. With --discover, every file under
shared_files_check.DISCOVERED that is byte-identical in two or more of the rows'
repositories and has no row becomes a row too. Every row lists each of the rows'
repositories that has the path on main (a different file there shows as a variant until it
is exempted with its reason).

For each row the bytes are read from every listed repository's main. When they agree the
entry records their SHA-256 and, as its source, the last commit of the first listed
repository's main that changed the file. When they do not, or the registry row is pending
or moving to new bytes (next=), the entry is `pending`: the variants found, the date it
became pending, what ends it, the target bytes and their owner (all kept from the existing
table; new rows take the variant most repositories have, the first of them in name order on
a tie, unless --target PATH=SHA256@ALICE-X names it). Nothing that differs is left out, and
no bytes being replaced are pinned. A pending row becomes uniform only when every copy has
its target bytes.

  gen_shared_files.py --table conformance/shared-files.toml (--write | --check)
                      [--registry FILE] [--discover] [--checkouts DIR] [--today YYYY-MM-DD]
                      [--target PATH=SHA256@ALICE-X ...]

--check regenerates in memory and exits 1 when the table differs, except for the variants
of a pending row, which are reported (the copies of a pending file are moving by
definition). The repositories' main is fetched from GitHub (blob-less), or read from
DIR/<repo> (its origin/main) with --checkouts. A run that would write no entry exits 2.
"""
from __future__ import annotations

import argparse
import collections
import copy
import datetime
import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import shared_files_check as sfc  # noqa: E402

HEADER = ("# Generated by scripts/gen_shared_files.py from the shared-file rows and each listed\n"
          "# repository's main; do not edit by hand, except a pending row's `exit`, `target`\n"
          "# and `owner` or an `exempt` (kept on regeneration). ALICE-Law G11 (c), checked by\n"
          "# scripts/shared_files_check.py\n")
EXIT_DIFFER = "the copies converge on one variant, or each differing repository is exempted with its reason"
EXIT_PENDING = "the registry row becomes enforced and every listed main has the same bytes"
EXIT_NEXT = "every listed main has the bytes the registry row moves to ({})"


def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def inline(d: dict) -> str:
    return "{ " + ", ".join(f"{q(k)} = {q(v)}" for k, v in sorted(d.items())) + " }"


def render(entries: list[dict]) -> str:
    out = [HEADER]
    for e in sorted(entries, key=lambda e: e["path"]):
        out.append("\n[[file]]\n")
        out.append(f"path = {q(e['path'])}\n")
        if "pending" in e:
            p = e["pending"]
            variants = ", ".join(f"{q(k)} = [" + ", ".join(q(r) for r in sorted(v)) + "]"
                                 for k, v in sorted(p["variants"].items()))
            out.append(f"pending = {{ since = {q(p['since'])}, exit = {q(p['exit'])}, target = {q(p['target'])}, "
                       f"owner = {q(p['owner'])}, variants = {{ {variants} }} }}\n")
        else:
            out.append(f"sha256 = {q(e['sha256'])}\n")
            out.append(f"source = {{ repo = {q(e['source']['repo'])}, rev = {q(e['source']['rev'])} }}\n")
        out.append("repos = [" + ", ".join(q(r) for r in e["repos"]) + "]\n")
        if e.get("paths"):
            out.append(f"paths = {inline(e['paths'])}\n")
        if e.get("exempt"):
            out.append(f"exempt = {inline(e['exempt'])}\n")
    return "".join(out)


def rows_from_registry(text: str) -> list[dict]:
    rows: dict[str, dict] = {}
    for n, raw in enumerate(text.splitlines(), 1):
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        cols = raw.split("\t")
        if len(cols) < 2:
            raise sfc.Unreadable(f"registry line {n}: needs path<TAB>repos")
        state = cols[2].strip() if len(cols) > 2 and cols[2].strip() else "enforced"
        nxt = cols[3].strip()[len("next="):] if len(cols) > 3 and cols[3].strip().startswith("next=") else ""
        order: list[str] = []
        paths: dict[str, str] = {}
        for item in cols[1].split(","):
            repo, _, alt = item.strip().partition(":")
            order.append(repo)
            if alt:
                paths[repo] = alt
        hold = EXIT_NEXT.format(nxt[:12]) if nxt else (EXIT_PENDING if state != "enforced" else "")
        row = {"path": cols[0].strip(), "order": order, "paths": paths, "exempt": {}, "hold": hold}
        prev = rows.get(row["path"])
        if prev is not None and (sorted(prev["order"]) != sorted(order) or prev["paths"] != paths):
            raise sfc.Unreadable(f"registry line {n}: {row['path']} listed twice with different repositories")
        rows.setdefault(row["path"], row)
    return list(rows.values())


def rows_from_table(entries: list[dict]) -> list[dict]:
    rows = []
    for e in entries:
        first = e["source"]["repo"] if "source" in e else e["repos"][0]
        order = [first] + [r for r in e["repos"] if r != first]
        rows.append({"path": e["path"], "order": order, "paths": dict(e.get("paths", {})),
                     "exempt": dict(e.get("exempt", {})), "hold": ""})
    return rows


def discover(rows: list[dict], repo_of) -> list[dict]:
    repos = sorted({r for row in rows for r in row["order"]})
    known = {row["path"] for row in rows} | {p for row in rows for p in row["paths"].values()}
    by_path: dict[str, dict[str, list[str]]] = collections.defaultdict(lambda: collections.defaultdict(list))
    for r in repos:
        for path, blob in sfc.tree(repo_of(r)).items():
            if path.startswith(sfc.DISCOVERED) and path not in known:
                by_path[path][blob].append(r)
    found = []
    for path, blobs in sorted(by_path.items()):
        if any(len(rs) >= 2 for rs in blobs.values()):
            holders = sorted(r for rs in blobs.values() for r in rs)
            found.append({"path": path, "order": holders, "paths": {}, "exempt": {}, "hold": ""})
    return found


class Checkouts:
    def __init__(self, root: Path):
        self.root = root

    def __call__(self, repo: str) -> Path:
        g = self.root / repo
        if not (g / ".git").exists():
            raise sfc.Unreadable(f"{g}: no checkout of {repo}")
        return g


def widen(rows: list[dict], repo_of) -> None:
    """Add to each row every one of the rows' repositories that has its path on main."""
    universe = sorted({r for row in rows for r in row["order"]} | {r for row in rows for r in row["exempt"]})
    trees = {r: sfc.tree(repo_of(r)) for r in universe}
    for row in rows:
        for r in universe:
            if r not in row["order"] and r not in row["exempt"] and row["path"] in trees[r]:
                row["order"].append(r)


def build(rows: list[dict], repo_of, old: dict[str, dict], today: str,
          targets: dict[str, tuple[str, str]]) -> list[dict]:
    entries = []
    wanted: dict[str, list[str]] = collections.defaultdict(list)
    for row in rows:
        for repo in row["order"]:
            wanted[repo].append(row["paths"].get(repo, row["path"]))
    for repo, rels in sorted(wanted.items()):
        sfc.prefetch(repo_of(repo), "origin/main", rels)
    for row in rows:
        found: dict[str, list[str]] = collections.defaultdict(list)
        for repo in row["order"]:
            data = sfc.show(repo_of(repo), "origin/main", row["paths"].get(repo, row["path"]))
            found["absent" if data is None else hashlib.sha256(data).hexdigest()].append(repo)
        base = {"path": row["path"], "repos": sorted(row["order"]), "paths": row["paths"], "exempt": row["exempt"]}
        prev = old.get(row["path"], {}).get("pending")
        goal = targets.get(row["path"], (prev["target"], "") if prev else None)
        # a pending row resolves only when every copy has its target bytes
        settled = goal is None or next(iter(found)) == goal[0]
        if len(found) == 1 and "absent" not in found and settled and (not row["hold"] or goal is not None):
            src = row["order"][0]
            rel = row["paths"].get(src, row["path"])
            rev = subprocess.run(["git", "-C", str(repo_of(src)), "log", "-1", "--format=%H", "origin/main", "--", rel],
                                 check=True, capture_output=True, text=True).stdout.strip()
            entries.append({**base, "sha256": next(iter(found)), "source": {"repo": src, "rev": rev}})
        else:
            exit_ = prev["exit"] if prev else (row["hold"] or EXIT_DIFFER)
            variants = {k: sorted(v) for k, v in found.items()}
            if row["path"] in targets:
                target, owner = targets[row["path"]]
            elif prev:
                target, owner = prev["target"], prev["owner"]
            else:
                present = {k: v for k, v in variants.items() if k != "absent"}
                if not present:
                    raise sfc.Unreadable(f"{row['path']}: no listed repository has the file (no target to take)")
                target = sorted(present, key=lambda k: (-len(present[k]), sorted(present[k])[0]))[0]
                owner = sorted(present[target])[0]
            if owner not in base["repos"]:
                raise sfc.Unreadable(f"{row['path']}: the owner {owner} is not one of the listed repositories")
            entries.append({**base, "pending": {"since": prev["since"] if prev else today, "exit": exit_,
                                                "target": target, "owner": owner, "variants": variants}})
    return entries


def without_variants(text: str) -> tuple[str, dict[str, dict]]:
    entries = sfc.load(text)
    stripped = copy.deepcopy(entries)
    variants = {}
    for e in stripped:
        if "pending" in e:
            variants[e["path"]] = e["pending"]["variants"]
            e["pending"]["variants"] = {"absent": e["repos"]}
    return render(stripped), variants


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--table", required=True, type=Path)
    act = ap.add_mutually_exclusive_group(required=True)
    act.add_argument("--write", action="store_true")
    act.add_argument("--check", action="store_true")
    ap.add_argument("--registry", type=Path)
    ap.add_argument("--discover", action="store_true")
    ap.add_argument("--checkouts", type=Path)
    ap.add_argument("--today", help="the date a new pending row records (default: today, UTC)")
    ap.add_argument("--target", action="append", default=[],
                    help="PATH=SHA256@ALICE-X: the bytes a pending row moves to and their owner")
    a = ap.parse_args(argv)
    today = a.today or datetime.datetime.now(datetime.timezone.utc).date().isoformat()
    try:
        targets = {}
        for t in a.target:
            path, _, rest = t.partition("=")
            sha, _, owner = rest.partition("@")
            if not path or not sfc.HEX64.match(sha) or not sfc.REPO.match(owner):
                raise sfc.Unreadable(f"--target {t!r}: needs PATH=SHA256@ALICE-X")
            targets[path] = (sha, owner)
        old_entries = (sfc.load(a.table.read_text(encoding="utf-8"))
                       if a.table.exists() and a.table.read_text(encoding="utf-8").strip() != HEADER.strip() else [])
        old = {e["path"]: e for e in old_entries}
        if a.registry is not None:
            rows = rows_from_registry(a.registry.read_text(encoding="utf-8"))
            for r in rows:
                r["exempt"] = dict(old.get(r["path"], {}).get("exempt", {}))
        else:
            if not old_entries:
                raise sfc.Unreadable(f"{a.table}: no entry to regenerate from (give --registry)")
            rows = rows_from_table(old_entries)
        with tempfile.TemporaryDirectory() as d:
            repo_of = Checkouts(a.checkouts) if a.checkouts else sfc.Remote(Path(d))
            if a.discover:
                rows += discover(rows, repo_of)
            widen(rows, repo_of)
            entries = build(rows, repo_of, old, today, targets)
    except (sfc.Unreadable, OSError, ValueError, subprocess.CalledProcessError) as e:
        print(f"gen_shared_files: {e}", file=sys.stderr)
        return 2
    if not entries:
        print("gen_shared_files: no entry to write (compared nothing)", file=sys.stderr)
        return 2
    text = render(entries)
    sfc.load_all(text)  # what is written must read back under the schema
    n = sum(len(e["repos"]) for e in entries)
    p = sum("pending" in e for e in entries)
    if a.check:
        current = a.table.read_text(encoding="utf-8") if a.table.exists() else ""
        try:
            cur_plain, cur_var = without_variants(current)
        except sfc.Unreadable as e:
            print(f"gen_shared_files: {a.table}: {e}", file=sys.stderr)
            return 1
        new_plain, new_var = without_variants(text)
        for path in sorted(set(cur_var) & set(new_var)):
            if cur_var[path] != new_var[path]:
                print(f"gen_shared_files: pending {path}: the variants on the mains have moved since the table")
        if cur_plain != new_plain:
            print(f"gen_shared_files: {a.table} is out of date (regenerate with --write)", file=sys.stderr)
            return 1
        print(f"gen_shared_files: {a.table} is current ({len(entries)} files, {n} copies, {p} pending)")
        return 0
    a.table.write_text(text, encoding="utf-8")
    print(f"gen_shared_files: wrote {a.table} ({len(entries)} files, {n} copies, {p} pending)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
