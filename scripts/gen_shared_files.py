#!/usr/bin/env python3
"""Generate conformance/shared-files.toml (ALICE-Law G11 (c)).

The rows (path, repositories, alternative paths, exemptions) come from the existing table,
or with --registry from a registry of shared files: lines `path<TAB>repo,repo[:alt-path]
[<TAB>state[<TAB>next=<blob>]]`, `#` comments, only rows whose state is `enforced` (the
default when the column is absent) and that declare no `next=` (a row moving to new bytes
is left out until the move is complete, so the table never pins the bytes being replaced). For each row the bytes are read from every listed
repository's main; they must agree, and the entry records their SHA-256 and, as its
source, the last commit of the first listed repository's main that changed the file.

  gen_shared_files.py --table conformance/shared-files.toml (--write | --check)
                      [--registry FILE] [--checkouts DIR] [--skip-disagreeing]

--check regenerates in memory and exits 1 when the table differs. The repositories' main
is fetched from GitHub (blob-less), or read from DIR/<repo> (its origin/main) with
--checkouts. A row whose copies disagree is refused (exit 1), or with --skip-disagreeing
left out of the table and named; a run that would write no entry exits 2.
"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import shared_files_check as sfc  # noqa: E402

HEADER = ("# Generated by scripts/gen_shared_files.py from the shared-file rows and each listed\n"
          "# repository's main; do not edit by hand (ALICE-Law G11 (c), checked by\n"
          "# scripts/shared_files_check.py)\n")


def toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(entries: list[dict]) -> str:
    out = [HEADER]
    for e in sorted(entries, key=lambda e: e["path"]):
        out.append("\n[[file]]\n")
        out.append(f"path = {toml_str(e['path'])}\n")
        out.append(f"sha256 = {toml_str(e['sha256'])}\n")
        out.append(f"source = {{ repo = {toml_str(e['source']['repo'])}, rev = {toml_str(e['source']['rev'])} }}\n")
        out.append("repos = [" + ", ".join(toml_str(r) for r in e["repos"]) + "]\n")
        if e.get("paths"):
            out.append("paths = { " + ", ".join(f"{toml_str(r)} = {toml_str(p)}"
                                                for r, p in sorted(e["paths"].items())) + " }\n")
        if e.get("exempt"):
            out.append("exempt = { " + ", ".join(f"{toml_str(r)} = {toml_str(w)}"
                                                 for r, w in sorted(e["exempt"].items())) + " }\n")
    return "".join(out)


def rows_from_registry(text: str) -> list[dict]:
    rows: dict[str, dict] = {}
    for n, raw in enumerate(text.splitlines(), 1):
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        cols = raw.split("\t")
        state = cols[2].strip() if len(cols) > 2 and cols[2].strip() else "enforced"
        if state != "enforced":
            continue
        if len(cols) > 3 and cols[3].strip().startswith("next="):
            # moving to new bytes: exported once every listed main has them and the
            # declaration is removed, never at the bytes being replaced
            print(f"gen_shared_files: skipped: {cols[0].strip()}: in rollout ({cols[3].strip()[:17]}…)",
                  file=sys.stderr)
            continue
        if len(cols) < 2:
            raise sfc.Unreadable(f"registry line {n}: needs path<TAB>repos")
        order: list[str] = []
        paths: dict[str, str] = {}
        for item in cols[1].split(","):
            repo, _, alt = item.strip().partition(":")
            order.append(repo)
            if alt:
                paths[repo] = alt
        row = {"path": cols[0].strip(), "order": order, "paths": paths, "exempt": {}}
        prev = rows.get(row["path"])
        if prev is not None and (sorted(prev["order"]) != sorted(order) or prev["paths"] != paths):
            raise sfc.Unreadable(f"registry line {n}: {row['path']} listed twice with different repositories")
        rows.setdefault(row["path"], row)
    return list(rows.values())


def rows_from_table(entries: list[dict]) -> list[dict]:
    rows = []
    for e in entries:
        order = [e["source"]["repo"]] + [r for r in e["repos"] if r != e["source"]["repo"]]
        rows.append({"path": e["path"], "order": order, "paths": dict(e.get("paths", {})),
                     "exempt": dict(e.get("exempt", {}))})
    return rows


class Checkouts:
    def __init__(self, root: Path):
        self.root = root

    def __call__(self, repo: str) -> Path:
        g = self.root / repo
        if not (g / ".git").exists():
            raise sfc.Unreadable(f"{g}: no checkout of {repo}")
        return g


def build(rows: list[dict], repo_of) -> tuple[list[dict], list[str]]:
    entries, refused = [], []
    for row in rows:
        blobs: dict[str, str] = {}
        for repo in row["order"]:
            rel = row["paths"].get(repo, row["path"])
            data = sfc.show(repo_of(repo), "origin/main", rel)
            blobs[repo] = "missing" if data is None else hashlib.sha256(data).hexdigest()
        if len(set(blobs.values())) != 1 or "missing" in blobs.values():
            refused.append(f"{row['path']}: the copies disagree: "
                           + ", ".join(f"{r} {h[:12]}" for r, h in blobs.items()))
            continue
        src = row["order"][0]
        g = repo_of(src)
        rel = row["paths"].get(src, row["path"])
        rev = subprocess.run(["git", "-C", str(g), "log", "-1", "--format=%H", "origin/main", "--", rel],
                             check=True, capture_output=True, text=True).stdout.strip()
        entries.append({"path": row["path"], "sha256": blobs[src], "source": {"repo": src, "rev": rev},
                        "repos": sorted(row["order"]), "paths": row["paths"], "exempt": row["exempt"]})
    return entries, refused


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--table", required=True, type=Path)
    act = ap.add_mutually_exclusive_group(required=True)
    act.add_argument("--write", action="store_true")
    act.add_argument("--check", action="store_true")
    ap.add_argument("--registry", type=Path)
    ap.add_argument("--checkouts", type=Path)
    ap.add_argument("--skip-disagreeing", action="store_true")
    a = ap.parse_args(argv)
    try:
        if a.registry is not None:
            rows = rows_from_registry(a.registry.read_text(encoding="utf-8"))
            old = sfc.load(a.table.read_text(encoding="utf-8")) if a.table.exists() else []
            exempt = {e["path"]: e.get("exempt", {}) for e in old}
            for r in rows:
                r["exempt"] = dict(exempt.get(r["path"], {}))
        else:
            rows = rows_from_table(sfc.load(a.table.read_text(encoding="utf-8")))
        with tempfile.TemporaryDirectory() as d:
            repo_of = Checkouts(a.checkouts) if a.checkouts else sfc.Remote(Path(d))
            entries, refused = build(rows, repo_of)
    except (sfc.Unreadable, OSError, subprocess.CalledProcessError) as e:
        print(f"gen_shared_files: {e}", file=sys.stderr)
        return 2
    for r in refused:
        print(f"gen_shared_files: {'skipped' if a.skip_disagreeing else 'refused'}: {r}", file=sys.stderr)
    if refused and not a.skip_disagreeing:
        return 1
    if not entries:
        print("gen_shared_files: no entry to write (compared nothing)", file=sys.stderr)
        return 2
    text = render(entries)
    sfc.load(text)  # what is written must read back under the schema
    n = sum(len(e["repos"]) for e in entries)
    if a.check:
        current = a.table.read_text(encoding="utf-8") if a.table.exists() else ""
        if current != text:
            print(f"gen_shared_files: {a.table} is out of date (regenerate with --write)", file=sys.stderr)
            return 1
        print(f"gen_shared_files: {a.table} is current ({len(entries)} files, {n} copies)")
        return 0
    a.table.write_text(text, encoding="utf-8")
    print(f"gen_shared_files: wrote {a.table} ({len(entries)} files, {n} copies)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
