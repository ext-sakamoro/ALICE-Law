#!/usr/bin/env python3
"""Generate conformance/shared-files.toml (ALICE-Law G11 (c)).

The rows (path, repositories, alternative paths, exemptions) come from the existing table,
or with --registry from a registry of shared files: lines `path<TAB>repo,repo[:alt-path]
[<TAB>state[<TAB>next=<blob>]]` (`-` for the repositories of a row every copy of which is exempted, the
exemptions kept from the table), `#` comments. With --discover, every file under
shared_files_check.DISCOVERED that is byte-identical in two or more of the rows'
repositories and has no row becomes a row too. Every row lists each of the rows'
repositories that has the path on main (a different file there shows as a variant until it
is exempted with its reason).

For each row the bytes are read from every listed repository's main. When they agree the
entry records their SHA-256 and, as its source, the last commit of the first listed
repository's main that changed the file. When they do not, or the registry row is pending
or moving to new bytes (next=), the entry is `pending`: the variants found, the date it
became pending, what ends it, the target bytes and their owner (all kept from the existing
table; new rows take the variant most repositories have, the first of them in name order on
a tie, unless --target PATH=SHA256@ALICE-X names it). Nothing that differs is left out, and
no bytes being replaced are pinned. A pending row becomes uniform only when every copy has
its target bytes.

A rollout is a planned row: with --next-from REGISTRY (only the registry's next= blob ids are
read; the rows still come from the table or --registry) or a planned id kept from the table,
a row one of whose copies has that blob id becomes pending with `planned` = the id, the
target = those bytes and the owner = the repository holding them (the existing owner when it
holds them). A next= that no main has yet changes nothing (the row stays what its copies
say), and a planned row all of whose copies have the target becomes uniform. A planned row keeps
the date it became planned when its id moves to newer bytes (a re-rolled target does not restart
the age limit). A planned row whose next= moves to bytes no main holds yet (a re-roll after some
mains already took the earlier bytes) stays planned only with --target PATH=SHA256@ALICE-X for
the new bytes: it records `moved_from` (the earlier planned id and target) until no main holds
those; without --target it is an error, never a silent drop to an unplanned divergence. The
first move of a uniform row to bytes no main holds (the --next-from id, with --target for the
bytes and their owner) is planned too, marked `first_move` with `moved_from` = the uniform
bytes; it is not re-rolled before its owner lands (an error).

  gen_shared_files.py --table conformance/shared-files.toml (--write | --check)
                      [--registry FILE] [--discover] [--checkouts DIR] [--today YYYY-MM-DD]
                      [--target PATH=SHA256@ALICE-X ...] [--next-from REGISTRY]
                      [--lock-file .github/workflows/conformance-live.yml]

--lock-file names the file holding the live check's count lock (`--expect-copies N`, the copies
of uniform rows): --write sets N from the table it writes, and --check is red when N is not
the regenerated table's (so is shared_files_check.py --lock-file, offline, against the table).

--check regenerates in memory and exits 1 when the table differs, except for the variants
of a pending row, which are reported (the copies of a pending file are moving by
definition), and for a row that only gained holders carrying the row's own bytes (a
rollout that landed before the table was regenerated), which is reported as an unlisted
holder; with --strict an unlisted holder is a difference too (a pending row's variants are
expected to move during its rollout, so they stay reported in every mode). The repositories' main is fetched from GitHub (blob-less), or read from
DIR/<repo> (its origin/main) with --checkouts. A run that would write no entry exits 2.
"""
from __future__ import annotations

import argparse
import collections
import copy
import datetime
import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import shared_files_check as sfc  # noqa: E402

HEADER = ("# Generated by scripts/gen_shared_files.py from the shared-file rows and each listed\n"
          "# repository's main; do not edit by hand, except a pending row's `exit`, `target`\n"
          "# and `owner` or an `exempt` (kept on regeneration). ALICE-Law G11 (c), checked by\n"
          "# scripts/shared_files_check.py\n")
EXIT_DIFFER = "the copies converge on one variant, or each differing repository is exempted with its reason"
EXIT_PENDING = "the registry row becomes enforced and every listed main has the same bytes"
# the blob is not quoted: the registry's next= moves during a rollout, and a quoted id goes stale
EXIT_NEXT = "every listed repository's main has the bytes the registry row moves to (its target)"


def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def inline(d: dict) -> str:
    return "{ " + ", ".join(f"{q(k)} = {inline(v) if isinstance(v, dict) else q(v)}"
                            for k, v in sorted(d.items())) + " }"


def render(entries: list[dict]) -> str:
    out = [HEADER]
    for e in sorted(entries, key=lambda e: e["path"]):
        out.append("\n[[file]]\n")
        out.append(f"path = {q(e['path'])}\n")
        if not e["repos"]:
            pass  # per-repository data: no bytes
        elif "pending" in e:
            p = e["pending"]
            variants = ", ".join(f"{q(k)} = [" + ", ".join(q(r) for r in sorted(v)) + "]"
                                 for k, v in sorted(p["variants"].items()))
            planned = f", planned = {q(p['planned'])}" if "planned" in p else ""
            if "moved_from" in p:
                m = p["moved_from"]
                planned += f", moved_from = {{ planned = {q(m['planned'])}, target = {q(m['target'])} }}"
            if p.get("first_move"):
                planned += ", first_move = true"
            out.append(f"pending = {{ since = {q(p['since'])}, exit = {q(p['exit'])}, target = {q(p['target'])}, "
                       f"owner = {q(p['owner'])}{planned}, variants = {{ {variants} }} }}\n")
        else:
            out.append(f"sha256 = {q(e['sha256'])}\n")
            out.append(f"source = {{ repo = {q(e['source']['repo'])}, rev = {q(e['source']['rev'])} }}\n")
        out.append("repos = [" + ", ".join(q(r) for r in e["repos"]) + "]\n")
        if e.get("paths"):
            out.append(f"paths = {inline(e['paths'])}\n")
        if e.get("exempt"):
            out.append(f"exempt = {inline(e['exempt'])}\n")
    return "".join(out)


def rows_from_registry(text: str) -> list[dict]:
    rows: dict[str, dict] = {}
    for n, raw in enumerate(text.splitlines(), 1):
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        cols = raw.split("\t")
        if len(cols) < 2:
            raise sfc.Unreadable(f"registry line {n}: needs path<TAB>repos")
        state = cols[2].strip() if len(cols) > 2 and cols[2].strip() else "enforced"
        nxt = cols[3].strip()[len("next="):] if len(cols) > 3 and cols[3].strip().startswith("next=") else ""
        order: list[str] = []
        paths: dict[str, str] = {}
        # `-`: a row that lists no repository (every copy is exempted; the exemptions come from the table)
        for item in ([] if cols[1].strip() == "-" else cols[1].split(",")):
            repo, _, alt = item.strip().partition(":")
            order.append(repo)
            if alt:
                paths[repo] = alt
        hold = EXIT_NEXT if nxt else (EXIT_PENDING if state != "enforced" else "")
        row = {"path": cols[0].strip(), "order": order, "paths": paths, "exempt": {}, "hold": hold, "next": nxt}
        prev = rows.get(row["path"])
        if prev is not None and (sorted(prev["order"]) != sorted(order) or prev["paths"] != paths):
            raise sfc.Unreadable(f"registry line {n}: {row['path']} listed twice with different repositories")
        rows.setdefault(row["path"], row)
    return list(rows.values())


def next_ids(text: str) -> dict[str, str]:
    """path -> the registry's next= blob id (rows without one are left out)"""
    return {r["path"]: r["next"] for r in rows_from_registry(text) if r.get("next")}


def rows_from_table(entries: list[dict]) -> list[dict]:
    rows = []
    for e in entries:
        if not e["repos"]:
            rows.append({"path": e["path"], "order": [], "paths": {}, "exempt": dict(e["exempt"]), "hold": ""})
            continue
        first = e["source"]["repo"] if "source" in e else e["repos"][0]
        order = [first] + [r for r in e["repos"] if r != first]
        rows.append({"path": e["path"], "order": order, "paths": dict(e.get("paths", {})),
                     "exempt": dict(e.get("exempt", {})), "hold": ""})
    return rows


def discover(rows: list[dict], repo_of) -> list[dict]:
    repos = sorted({r for row in rows for r in row["order"]})
    known = {row["path"] for row in rows} | {p for row in rows for p in row["paths"].values()}
    by_path: dict[str, dict[str, list[str]]] = collections.defaultdict(lambda: collections.defaultdict(list))
    for r in repos:
        for path, blob in sfc.tree(repo_of(r)).items():
            if path.startswith(sfc.DISCOVERED) and path not in known:
                by_path[path][blob].append(r)
    found = []
    for path, blobs in sorted(by_path.items()):
        if any(len(rs) >= 2 for rs in blobs.values()):
            holders = sorted(r for rs in blobs.values() for r in rs)
            found.append({"path": path, "order": holders, "paths": {}, "exempt": {}, "hold": ""})
    return found


class Checkouts:
    def __init__(self, root: Path):
        self.root = root

    def __call__(self, repo: str) -> Path:
        g = self.root / repo
        if not (g / ".git").exists():
            raise sfc.Unreadable(f"{g}: no checkout of {repo}")
        return g


def widen(rows: list[dict], repo_of) -> None:
    """Add to each row every one of the rows' repositories that has its path on main."""
    universe = sorted({r for row in rows for r in row["order"]} | {r for row in rows for r in row["exempt"]})
    trees = {r: sfc.tree(repo_of(r)) for r in universe}
    for row in rows:
        if not row["order"]:
            continue  # per-repository data: a new holder is the live check's finding, not a new copy
        for r in universe:
            if r not in row["order"] and r not in row["exempt"] and row["path"] in trees[r]:
                row["order"].append(r)


def build(rows: list[dict], repo_of, old: dict[str, dict], today: str,
          targets: dict[str, tuple[str, str]], planned_ids: dict[str, str] | None = None) -> list[dict]:
    entries = []
    wanted: dict[str, list[str]] = collections.defaultdict(list)
    for row in rows:
        for repo in row["order"]:
            wanted[repo].append(row["paths"].get(repo, row["path"]))
    for repo, rels in sorted(wanted.items()):
        sfc.prefetch(repo_of(repo), "origin/main", rels)
    for row in rows:
        if not row["order"]:
            entries.append({"path": row["path"], "repos": [], "paths": {}, "exempt": row["exempt"]})
            continue
        found: dict[str, list[str]] = collections.defaultdict(list)
        blobs: dict[str, str] = {}  # git blob id -> sha256
        for repo in row["order"]:
            data = sfc.show(repo_of(repo), "origin/main", row["paths"].get(repo, row["path"]))
            found["absent" if data is None else hashlib.sha256(data).hexdigest()].append(repo)
            if data is not None:
                blobs[sfc.git_blob(data)] = hashlib.sha256(data).hexdigest()
        base = {"path": row["path"], "repos": sorted(row["order"]), "paths": row["paths"], "exempt": row["exempt"]}
        prev = old.get(row["path"], {}).get("pending")
        # a rollout: the registry's next= (or the planned id the table keeps) held by one of the mains
        nxt = (planned_ids or {}).get(row["path"]) or row.get("next") or (prev or {}).get("planned")
        was_planned = prev is not None and "planned" in prev
        variants = {k: sorted(v) for k, v in found.items()}
        if nxt and nxt in blobs:
            target = blobs[nxt]
            if set(found) != {target}:
                holders = [r for r in row["order"] if r in found[target]]
                # the owner is whoever holds the planned bytes: the recorded one while it does, else the first holder
                # (a non-owner landing a new file first becomes its owner: the bytes, not the name, are the plan)
                owner = prev["owner"] if prev and prev["owner"] in holders else holders[0]
                # the clock runs from when the row became pending, under whatever id: a re-rolled target does not
                # restart it, and neither does planning a row that was already pending unplanned (the table refuses
                # a pending row's date moving later); only a row that was not pending starts today
                pending = {"since": prev["since"] if prev is not None else today, "exit": EXIT_NEXT,
                           "target": target, "owner": owner, "planned": nxt, "variants": variants}
                moved = prev.get("moved_from") if was_planned else None
                if moved and moved["target"] in found:
                    pending["moved_from"] = moved  # copies with the earlier bytes remain
                entries.append({**base, "pending": pending})
                continue
            prev = None  # converged: a uniform row below
        elif nxt and was_planned:
            # the planned bytes are on no main: a re-roll to bytes no main holds yet. The row stays planned
            # with the new target only when its bytes are given (or already recorded); it is never dropped
            # to what the copies say (that would turn a rollout into an unplanned divergence silently)
            if nxt == prev["planned"] and ("moved_from" in prev
                                           or set(found) == set(prev.get("variants", {})) == {"absent"}):
                # moved from recorded bytes, or a new file no main held when it was planned and none holds yet: the
                # plan stands until the owner lands (a row whose copies were there and are all gone now is the owner
                # moving off the planned bytes, refused below, not a new file)
                entries.append({**base, "pending": {**prev, "variants": variants}})
                continue
            fresh = "moved_from" not in prev and set(found) == set(prev.get("variants", {})) == {"absent"}
            # a first move whose owner already holds its target has landed (the table was not regenerated since):
            # its re-roll moves from those landed bytes like any planned row, below
            unlanded_first = prev.get("first_move") and prev["owner"] not in found.get(prev["target"], [])
            if unlanded_first or fresh:
                # the owner has not landed the plan: it is re-rolled in place, on the date it became planned (closing
                # it by hand and planning it again later would restart its clock, and the table refuses that)
                if row["path"] not in targets:
                    raise sfc.Unreadable(f"{row['path']}: the registry's next= {nxt[:12]} re-rolls the plan to "
                                         f"{prev['planned'][:12]}, which has not landed: give the new bytes' SHA-256 "
                                         "and owner with --target PATH=SHA256@ALICE-X")
                target, owner = targets[row["path"]]
                if owner not in base["repos"]:
                    raise sfc.Unreadable(f"{row['path']}: the owner {owner} is not one of the listed repositories")
                pending = {"since": prev["since"], "exit": EXIT_NEXT, "target": target, "owner": owner,
                           "planned": nxt}
                if prev.get("first_move"):
                    if set(found) != {prev["moved_from"]["target"]}:
                        raise sfc.Unreadable(f"{row['path']}: the first move is from {prev['moved_from']['target'][:12]}"
                                             ", which not every listed main holds any more")
                    pending.update({"moved_from": prev["moved_from"], "first_move": True})
                entries.append({**base, "pending": {**pending, "variants": variants}})
                continue
            if nxt == prev["planned"]:
                raise sfc.Unreadable(f"{row['path']}: the planned bytes {nxt[:12]} are on no listed main any more "
                                     "(the owner moved off them: give the bytes the rollout goes to with --target "
                                     "and the registry's next=; a planned row leaves the table only at its target)")
            if row["path"] not in targets:
                raise sfc.Unreadable(f"{row['path']}: the registry's next= {nxt[:12]} moves the planned row to bytes "
                                     "no listed main holds yet: give their SHA-256 and owner with --target "
                                     "PATH=SHA256@ALICE-X (a planned row is not dropped silently)")
            target, owner = targets[row["path"]]
            if owner not in base["repos"]:
                raise sfc.Unreadable(f"{row['path']}: the owner {owner} is not one of the listed repositories")
            # the bytes the row moves from: the planned ones a main still holds, or what an earlier move recorded
            moved = ({"planned": prev["planned"], "target": prev["target"]} if prev["target"] in found
                     else prev.get("moved_from"))
            if moved is None or moved["target"] not in found:
                raise sfc.Unreadable(f"{row['path']}: no listed main holds the bytes the planned row moves from")
            entries.append({**base, "pending": {"since": prev["since"], "exit": EXIT_NEXT, "target": target,
                                                "owner": owner, "planned": nxt, "moved_from": moved,
                                                "variants": variants}})
            continue
        if (nxt and not prev and nxt == (planned_ids or {}).get(row["path"]) and row["path"] in targets
                and len(found) == 1 and "absent" not in found):
            # the first move of a uniform row to bytes no main holds yet: without a planned row no copy could take
            # them (each repository's own check refuses a copy the table does not record), so it is planned now,
            # moving from the bytes every main has (moved_from), to the --target bytes
            target, owner = targets[row["path"]]
            if owner not in base["repos"]:
                raise sfc.Unreadable(f"{row['path']}: the owner {owner} is not one of the listed repositories")
            sha = next(iter(found))
            moved = {"planned": next(b for b, h in blobs.items() if h == sha), "target": sha}
            entries.append({**base, "pending": {"since": today, "exit": EXIT_NEXT, "target": target, "owner": owner,
                                                "planned": nxt, "moved_from": moved, "first_move": True,
                                                "variants": variants}})
            continue
        if (nxt and not prev and nxt == (planned_ids or {}).get(row["path"]) and row["path"] in targets
                and set(found) == {"absent"}):
            # a new file, in no listed main yet: planned from the start, to the --target bytes and owner (nothing to
            # move from), so the rollout is explicit instead of an unplanned divergence
            target, owner = targets[row["path"]]
            if owner not in base["repos"]:
                raise sfc.Unreadable(f"{row['path']}: the owner {owner} is not one of the listed repositories")
            entries.append({**base, "pending": {"since": today, "exit": EXIT_NEXT, "target": target, "owner": owner,
                                                "planned": nxt, "variants": variants}})
            continue
        if nxt and (not prev):
            row = {**row, "hold": ""}  # a next= no main holds (yet) holds nothing back
        goal = targets.get(row["path"], (prev["target"], "") if prev else None)
        # a pending row resolves only when every copy has its target bytes
        settled = goal is None or next(iter(found)) == goal[0]
        if len(found) == 1 and "absent" not in found and settled and (not row["hold"] or goal is not None):
            src = row["order"][0]
            rel = row["paths"].get(src, row["path"])
            rev = subprocess.run(["git", "-C", str(repo_of(src)), "log", "-1", "--format=%H", "origin/main", "--", rel],
                                 check=True, capture_output=True, text=True, encoding="utf-8").stdout.strip()
            entries.append({**base, "sha256": next(iter(found)), "source": {"repo": src, "rev": rev}})
        else:
            exit_ = prev["exit"] if prev else (row["hold"] or EXIT_DIFFER)
            variants = {k: sorted(v) for k, v in found.items()}
            if row["path"] in targets:
                target, owner = targets[row["path"]]
            elif prev:
                target, owner = prev["target"], prev["owner"]
            else:
                present = {k: v for k, v in variants.items() if k != "absent"}
                if not present:
                    raise sfc.Unreadable(f"{row['path']}: no listed repository has the file (no target to take)")
                target = sorted(present, key=lambda k: (-len(present[k]), sorted(present[k])[0]))[0]
                owner = sorted(present[target])[0]
            if owner not in base["repos"]:
                raise sfc.Unreadable(f"{row['path']}: the owner {owner} is not one of the listed repositories")
            entries.append({**base, "pending": {"since": prev["since"] if prev else today, "exit": exit_,
                                                "target": target, "owner": owner, "variants": variants}})
    return entries


def unlisted_same_bytes(old: list[dict], new: list[dict],
                        base: list[dict] | None = None) -> tuple[list[dict], list[tuple[str, list[str]]]]:
    """new entries with each row that differs from the table only by added holders carrying the row's own
    bytes put back to the table's row, and the (path, added holders) of those rows"""
    before = {e["path"]: e for e in old}
    base_repos = {e["path"]: e["repos"] for e in (base or [])}
    out, held = [], []
    for e in new:
        o = before.get(e["path"])
        if o is None or not e["repos"] or not o["repos"]:
            out.append(e)
            continue
        added = [r for r in e["repos"] if r not in o["repos"]]
        dropped = sorted(set(added) & set(base_repos.get(e["path"], ())))
        if dropped:
            # the base table listed them: the change removed them, which is not a rollout that landed elsewhere
            print(f"gen_shared_files: {e['path']}: {', '.join(dropped)} is listed in the base table and this change "
                  "removed it", file=sys.stderr)
            out.append(e)
            continue
        if not added or [r for r in o["repos"] if r not in e["repos"]]:
            out.append(e)
            continue
        def rest(d: dict, drop: str) -> dict:
            return {k: v for k, v in d.items() if k != drop and v != {}}  # an absent paths / exempt reads as {}

        if "sha256" in o and "sha256" in e and e["sha256"] == o["sha256"]:
            same = rest(e, "repos") == rest(o, "repos")
        elif "pending" in o and "pending" in e:
            known = set(o["pending"]["variants"]) - {"absent"}
            added_bytes = {k for k, rs in e["pending"]["variants"].items() if set(rs) & set(added)}
            same = (added_bytes <= known and rest(e["pending"], "variants") == rest(o["pending"], "variants")
                    and rest({k: v for k, v in e.items() if k != "pending"}, "repos")
                    == rest({k: v for k, v in o.items() if k != "pending"}, "repos"))
        else:
            same = False
        if same:
            out.append(o)
            held.append((e["path"], added))
        else:
            out.append(e)
    return out, held


def converged_since_base(old: list[dict], new: list[dict],
                         base: list[dict]) -> tuple[list[dict], list[tuple[str, list[str]]]]:
    """new entries with each row that only converged since the base put back to the table's row, and those (path,
    added holders): the table's row is planned and equal to the base's in everything but the variants (the change left
    it), and the regenerated row is uniform (with the table's repositories, or more: a holder that took the target bytes
    while a change was checked); any other difference stays. A uniform row at other bytes than the target, or one that
    lost a holder, never reaches here: the regeneration refuses a planned row its owner moved off, and a dropped copy
    leaves the row pending; the regenerated row keeps the table's paths and exemptions"""
    before = {e["path"]: e for e in old}
    planned = {e["path"]: e for e in base if sfc.is_planned(e)}
    out, done = [], []
    for e in new:
        o, b = before.get(e["path"]), planned.get(e["path"])
        if (o is not None and b is not None and sfc.is_planned(o) and "sha256" in e
                and sfc.row_but_variants(o) == sfc.row_but_variants(b)):
            out.append(o)
            done.append((e["path"], [r for r in e["repos"] if r not in o["repos"]]))
        else:
            out.append(e)
    return out, done


def without_variants(text: str) -> tuple[str, dict[str, dict]]:
    entries = sfc.load(text)
    stripped = copy.deepcopy(entries)
    variants = {}
    for e in stripped:
        if "pending" in e:
            variants[e["path"]] = e["pending"]["variants"]
            e["pending"]["variants"] = {"absent": e["repos"]}
    return render(stripped), variants


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--table", required=True, type=Path)
    act = ap.add_mutually_exclusive_group(required=True)
    act.add_argument("--write", action="store_true")
    act.add_argument("--check", action="store_true")
    ap.add_argument("--registry", type=Path)
    ap.add_argument("--discover", action="store_true")
    ap.add_argument("--checkouts", type=Path)
    ap.add_argument("--today", help="the date a new pending row records (default: today, UTC)")
    ap.add_argument("--base-table", type=Path,
                    help="with --check: the table at the base (origin/main); a holder it lists that the table under "
                         "check dropped is a difference, not an unlisted holder that landed elsewhere")
    ap.add_argument("--strict", action="store_true",
                    help="with --check: a row that gained holders with its own bytes is a difference too (the"
                         " regeneration and landing path, and the pre-publish gate)")
    ap.add_argument("--target", action="append", default=[],
                    help="PATH=SHA256@ALICE-X: the bytes a pending row moves to and their owner")
    ap.add_argument("--next-from", type=Path,
                    help="a shared-file registry whose next= blob ids mark rollouts (planned rows)")
    ap.add_argument("--lock-file", type=Path,
                    help="the file holding the count lock (`--expect-copies N`): --write sets N, --check compares it")
    a = ap.parse_args(argv)
    today = a.today or datetime.datetime.now(datetime.timezone.utc).date().isoformat()
    try:
        targets = {}
        for t in a.target:
            path, _, rest = t.partition("=")
            sha, _, owner = rest.partition("@")
            if not path or not sfc.HEX64.match(sha) or not sfc.is_repo_name(owner):
                raise sfc.Unreadable(f"--target {t!r}: needs PATH=SHA256@ALICE-X")
            targets[path] = (sha, owner)
        old_entries = (sfc.load(a.table.read_text(encoding="utf-8"))
                       if a.table.exists() and a.table.read_text(encoding="utf-8").strip() != HEADER.strip() else [])
        old = {e["path"]: e for e in old_entries}
        if a.registry is not None:
            rows = rows_from_registry(a.registry.read_text(encoding="utf-8"))
            for r in rows:
                r["exempt"] = dict(old.get(r["path"], {}).get("exempt", {}))
        else:
            if not old_entries:
                raise sfc.Unreadable(f"{a.table}: no entry to regenerate from (give --registry)")
            rows = rows_from_table(old_entries)
        with tempfile.TemporaryDirectory() as d:
            repo_of = Checkouts(a.checkouts) if a.checkouts else sfc.Remote(Path(d))
            if a.discover:
                rows += discover(rows, repo_of)
            widen(rows, repo_of)
            planned_ids = next_ids(a.next_from.read_text(encoding="utf-8")) if a.next_from else None
            entries = build(rows, repo_of, old, today, targets, planned_ids)
        if not entries:
            print("gen_shared_files: no entry to write (compared nothing)", file=sys.stderr)
            return 2
        text = render(entries)
        sfc.load_all(text)  # what is written must read back under the schema (a refusal, not a crash)
    except (sfc.Unreadable, OSError, ValueError, subprocess.CalledProcessError) as e:
        print(f"gen_shared_files: {e}", file=sys.stderr)
        return 2
    n = sum(len(e["repos"]) for e in entries)
    p = sum("pending" in e for e in entries)
    if a.check:
        current = a.table.read_text(encoding="utf-8") if a.table.exists() else ""
        try:
            cur_plain, cur_var = without_variants(current)
        except sfc.Unreadable as e:
            print(f"gen_shared_files: {a.table}: {e}", file=sys.stderr)
            return 1
        if not a.strict:
            # a rollout that landed before the table was regenerated: a row that only gained holders with
            # the row's own bytes is reported, not a difference (--strict: it is one)
            base = sfc.load(a.base_table.read_text(encoding="utf-8")) if a.base_table else None
            entries, held = unlisted_same_bytes(sfc.load(current), entries, base)
            for path, repos in held:
                print(f"gen_shared_files: unlisted holder, same bytes: {path} on {', '.join(repos)}"
                      " (regenerate the table before the next publish)")
            if base is not None:
                entries, done = converged_since_base(sfc.load(current), entries, base)
                for path, added in done:
                    print(f"gen_shared_files: converged since the base: {path} (every copy has the target"
                          + (f", and {', '.join(added)} took it as an unlisted holder" if added else "")
                          + "; the next table makes it uniform)")
            text = render(entries)
        new_plain, new_var = without_variants(text)
        for path in sorted(set(cur_var) & set(new_var)):
            if cur_var[path] != new_var[path]:
                print(f"gen_shared_files: pending {path}: the variants on the mains have moved since the table")
        if cur_plain != new_plain:
            print(f"gen_shared_files: {a.table} is out of date (regenerate with --write)", file=sys.stderr)
            return 1
        if a.lock_file is not None:
            try:
                lock = sfc.lock_in(a.lock_file.read_text(encoding="utf-8"), str(a.lock_file))
            except (sfc.Unreadable, OSError) as e:
                print(f"gen_shared_files: {e}", file=sys.stderr)
                return 2
            want = sfc.uniform_copies(sfc.load(text))
            if lock != want:
                print(f"gen_shared_files: {a.lock_file}: the count lock says {lock}, the table has {want} copies of "
                      "uniform rows (regenerate with --write --lock-file)", file=sys.stderr)
                return 1
        print(f"gen_shared_files: {a.table} is current ({len(entries)} files, {n} copies, {p} pending)")
        return 0
    lock_text = None
    if a.lock_file is not None:
        try:
            lock_text = sfc.with_lock(a.lock_file.read_text(encoding="utf-8"), str(a.lock_file),
                                      sfc.uniform_copies(entries))
        except (sfc.Unreadable, OSError) as e:
            print(f"gen_shared_files: {e}", file=sys.stderr)
            return 2
    a.table.write_text(text, encoding="utf-8")
    print(f"gen_shared_files: wrote {a.table} ({len(entries)} files, {n} copies, {p} pending)")
    if lock_text is not None:
        a.lock_file.write_text(lock_text, encoding="utf-8")
        print(f"gen_shared_files: wrote the count lock {sfc.uniform_copies(entries)} to {a.lock_file}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
