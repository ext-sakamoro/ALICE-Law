#!/usr/bin/env python3
"""G15 surface-claims: the surfaces a crate says it can be used from are the ones it has, and CI builds them.

A crate declares its surfaces in its Cargo.toml:

    [package.metadata.alice]
    surfaces = ["rust", "browser", "c"]

from the fixed vocabulary rust / browser / wasi / c / python / unity / unreal (browser = wasm-bindgen
for a web page; wasi = a wasm32-wasip1 build run outside a browser, which is not a browser surface).
The check compares, for a repository (its tracked files):

  1. declared == detected, per crate: rust (src/lib.rs), browser (#[wasm_bindgen]), c (extern "C" with
     no_mangle), python (PyO3 attributes), unity (a C# file whose DllImport names the crate's library),
     unreal (an Unreal Build.cs naming the library, or a C++ header under a ue4 / ue5 / unreal directory
     declaring extern "C", for a crate with a C surface), wasi (a push-triggered workflow building
     wasm32-wasip1); comments and #[cfg(test)] items do not count
  2. the README surface table equals the union of the declared surfaces: the table between
     `<!-- surfaces -->` and `<!-- /surfaces -->` in README.md (and README_JP.md when it exists, with
     the same set), one surface per row in its first cell; prose mentions are not read
  3. every declared binding surface is built by a step of a push-triggered workflow (browser / wasi /
     c / python), and browser / python also run what they built; unity and unreal, which no CI runner
     can build, need the c surface declared and built; continue-on-error steps do not count
  4. something was compared: exit 2 when the repository has no crate manifest, no Rust source, or no
     declaration at all, and when a declared binding surface had no workflow file to look in

Threat model: the careless forms are all caught (a missing declaration, a stale README table, a
surface CI does not build, wasi written as browser, a C# port written as a binding); deliberate
obfuscation (an attribute generated by a macro, a workflow step built from a variable) is out of scope
and left to review.

    surface_claims_check.py --repo DIR
    surface_claims_check.py --repo DIR --baseline FILE --name REPOSITORY
        compare the finding counts by kind with the repository's row of the baseline: more is a
        finding, fewer is a stale row (the baseline only shrinks); a repository without a row has none
    surface_claims_check.py --write-baseline FILE NAME=DIR [NAME=DIR ...]
        the baseline of these repositories (generated, never edited by hand)

Exit 0 when nothing is found, 1 on a finding, 2 when nothing was compared or an input could not be read.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tomllib
from pathlib import Path

VOCABULARY = ("rust", "browser", "wasi", "c", "python", "unity", "unreal")
BUILT_IN_CI = ("browser", "wasi", "c", "python")
RUN_IN_CI = ("browser", "python")

RX_WASM = re.compile(r"#\[\s*wasm_bindgen\b")
RX_NO_MANGLE = re.compile(r"#\[\s*(?:unsafe\s*\(\s*)?no_mangle\b")
RX_EXTERN_C = re.compile(r'\bextern\s+"C"')
RX_PYO3 = re.compile(r"#\[\s*(?:pyfunction|pymodule|pyclass|pymethods)\b")
RX_DLLIMPORT = re.compile(r"\[\s*DllImport\s*\(\s*([^,\)]+)")
RX_STRING = re.compile(r'"(?:\\.|[^"\\])*"')

CI_BUILD = {
    "browser": [r"wasm32-unknown-unknown", r"\bwasm-pack\b", r"\bwasm-bindgen\b", r"build_wasm_pkg", r"npm run build"],
    "wasi": [r"wasm32-wasip1"],
    "c": [r"--crate-type[ =]+(?:cdylib|staticlib)", r"--features[ =]+\"?[^\"\n]*\bffi\b", r"\bcbindgen\b"],
    "python": [r"\bmaturin\b"],
}
CI_RUN = {
    "browser": [r"\bnode\s+--test\b", r"run_js_binding_tests", r"\bwasm-bindgen-test", r"\bplaywright\b", r"npm run smoke"],
    "python": [r"(?s)(?:\.whl|maturin develop).*\b(?:pytest|test)"],
}


class InputError(Exception):
    pass


# ---------------------------------------------------------------------------------------------
# reading


def tracked(repo: Path) -> list[str]:
    r = subprocess.run(["git", "-C", str(repo), "ls-files", "-z"], capture_output=True)
    if r.returncode != 0:
        raise InputError(f"{repo}: git ls-files failed")
    return [p for p in r.stdout.decode("utf-8", "replace").split("\0") if p]


def read(repo: Path, rel: str) -> str:
    try:
        return (repo / rel).read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        raise InputError(f"{rel}: {e}") from e


def strip_rust(text: str) -> str:
    """the code without comments and without #[cfg(test)] items (string literals kept)"""
    out, i, n = [], 0, len(text)
    while i < n:
        if text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            i = n if j < 0 else j + 2
        elif text[i] == '"' and (m := RX_STRING.match(text, i)):
            out.append(m.group(0))
            i = m.end()
        else:
            out.append(text[i])
            i += 1
    code, res, pos = "".join(out), [], 0
    for m in re.finditer(r"#\[cfg\(\s*test\s*\)\]", code):
        if m.start() < pos:
            continue
        brace, semi = code.find("{", m.end()), code.find(";", m.end())
        if brace < 0 or 0 <= semi < brace:
            continue
        depth, k = 0, brace
        while k < len(code):
            depth += {"{": 1, "}": -1}.get(code[k], 0)
            if depth == 0:
                break
            k += 1
        res.append(code[pos:m.start()])
        pos = k + 1
    res.append(code[pos:])
    return "".join(res)


def dllimport_names(text: str) -> set[str]:
    consts = dict(re.findall(r"\bconst\s+string\s+([A-Za-z_]\w*)\s*=\s*\"([^\"]+)\"", text))
    names = set()
    for arg in RX_DLLIMPORT.findall(text):
        arg = arg.strip()
        name = arg.strip('"') if arg.startswith('"') else consts.get(arg.split(".")[-1])
        if name:
            names.add(re.sub(r"^lib|\.(?:dll|so|dylib)$", "", name))
    return names


def run_steps(text: str) -> list[str]:
    steps, cur = [], []
    for line in text.splitlines():
        if re.match(r"^\s*-\s+(?:name|uses|run|id|if|with|env|shell|working-directory|continue-on-error)\b", line):
            if cur:
                steps.append("\n".join(cur))
            cur = [line]
        elif cur:
            cur.append(line)
    if cur:
        steps.append("\n".join(cur))
    return [s for s in steps if not re.search(r"continue-on-error:\s*true", s)]


def push_triggered(text: str) -> bool:
    m = re.search(r"^on:(.*?)(?=^\S)", text + "\nEND", re.M | re.S)
    if not m:
        return False
    block = m.group(1)
    return bool(re.search(r"\bpush\b", block.split("\n")[0]) or re.search(r"^\s{2}push:", block, re.M))


# ---------------------------------------------------------------------------------------------
# one repository


def crates(repo: Path, files: list[str]) -> list[dict]:
    res = []
    for rel in files:
        if Path(rel).name != "Cargo.toml":
            continue
        data = tomllib.loads(read(repo, rel))
        pkg = data.get("package")
        if not isinstance(pkg, dict) or "name" not in pkg:
            continue
        d = str(Path(rel).parent)
        d = "" if d == "." else d
        lib = (data.get("lib") or {}).get("name") or pkg["name"].replace("-", "_")
        meta = ((pkg.get("metadata") or {}).get("alice") or {})
        declared = meta.get("surfaces")
        if declared is not None and (not isinstance(declared, list) or not all(isinstance(s, str) for s in declared)):
            raise InputError(f"{rel}: [package.metadata.alice] surfaces is not a list of strings")
        res.append({"name": pkg["name"], "dir": d, "lib": lib, "declared": declared, "manifest": rel})
    return res


def under(rel: str, d: str) -> bool:
    return d == "" or rel == d or rel.startswith(d + "/")


def detect(repo: Path, files: list[str], crate: dict, others: list[str], workflows: dict[str, str]) -> dict[str, list[str]]:
    """the surfaces of `crate` found in the repository, each with the files that show it; `others` are
    the directories of the other crates (a file under a nested crate belongs to it)"""
    d = crate["dir"]
    src = f"{d}/src/" if d else "src/"
    nested = [o for o in others if o != d and (d == "" or o.startswith(d + "/"))]
    mine = lambda rel: under(rel, d) and not any(under(rel, o) for o in nested)
    found: dict[str, list[str]] = {}
    if f"{src}lib.rs" in files:
        found["rust"] = [f"{src}lib.rs"]
    for rel in files:
        if not (rel.startswith(src) and rel.endswith(".rs") and mine(rel)):
            continue
        code = strip_rust(read(repo, rel))
        if RX_WASM.search(code):
            found.setdefault("browser", []).append(rel)
        if RX_NO_MANGLE.search(code) and RX_EXTERN_C.search(code):
            found.setdefault("c", []).append(rel)
        if RX_PYO3.search(code):
            found.setdefault("python", []).append(rel)
    for rel in files:
        if rel.endswith(".cs") and not rel.endswith(".Build.cs") and crate["lib"] in dllimport_names(read(repo, rel)):
            found.setdefault("unity", []).append(rel)
    plugins = {str(Path(r).parent) for r in files if r.endswith(".uplugin")}
    for rel in files:
        if rel.endswith(".Build.cs") and any(under(rel, p) for p in plugins) and crate["lib"] in read(repo, rel):
            found.setdefault("unreal", []).append(rel)
    if "c" in found:
        for rel in files:
            parts = Path(rel).parts[:-1]
            if rel.endswith(".h") and any(re.fullmatch(r"(?i)ue[45]|unreal[-_ a-z]*", p) for p in parts) \
                    and RX_EXTERN_C.search(read(repo, rel)):
                found.setdefault("unreal", []).append(rel)
    for name, text in workflows.items():
        if push_triggered(text) and any(re.search(rx, s) for s in run_steps(text) for rx in CI_BUILD["wasi"]):
            if "rust" in found:
                found.setdefault("wasi", []).append(name)
    return found


def readme_table(text: str) -> set[str] | None:
    m = re.search(r"<!--\s*surfaces\s*-->(.*?)<!--\s*/surfaces\s*-->", text, re.S)
    if not m:
        return None
    rows, body = set(), False
    for line in m.group(1).splitlines():
        if not line.strip().startswith("|"):
            continue
        cells = [c.strip().strip("`").strip().lower() for c in line.strip().strip("|").split("|")]
        if all(re.fullmatch(r":?-+:?", c) for c in cells):
            body = True  # the rows after the header's separator
            continue
        if body and cells[0]:
            rows.add(cells[0])
    return rows


def check_repo(repo: Path, require_declaration: bool = True) -> tuple[list[tuple[str, str]], int]:
    """(findings as (kind, text), number of comparisons); with require_declaration=False (the baseline
    and the comparison with it) a crate without a declaration is one `undeclared` finding and is checked
    as if it declared what was found, so the CI and README gaps of a repository that has not adopted the
    gate are still counted"""
    files = tracked(repo)
    cs = crates(repo, files)
    if not cs:
        raise InputError("no crate manifest (Cargo.toml with [package]) is tracked")
    if not any(f.endswith(".rs") for f in files):
        raise InputError("no Rust source is tracked")
    workflows = {f: read(repo, f) for f in files if f.startswith(".github/workflows/") and f.endswith((".yml", ".yaml"))}
    dirs = [c["dir"] for c in cs]
    findings: list[tuple[str, str]] = []
    compared = 0
    union: set[str] = set()
    founds = {c["manifest"]: detect(repo, files, c, dirs, workflows) for c in cs}
    # an engine binding names the library a facade crate is built into, while the extern "C" items may live
    # in the engine crate it re-exports (ALICE-Physics): the c surface is a property of the repository here
    repo_c = any("c" in f or "c" in (c["declared"] or []) for c, f in zip(cs, founds.values()))
    for c in cs:
        found = founds[c["manifest"]]
        if c["declared"] is None:
            if require_declaration:
                if set(found) - {"rust"}:
                    findings.append(("undeclared", f"{c['manifest']}: no [package.metadata.alice] surfaces, found {sorted(found)}"))
                continue
            findings.append(("undeclared", f"{c['manifest']}: no [package.metadata.alice] surfaces, found {sorted(found)}"))
        decl = set(c["declared"] if c["declared"] is not None else found)
        for bad in sorted(decl - set(VOCABULARY)):
            findings.append(("vocabulary", f"{c['manifest']}: {bad!r} is not a surface ({', '.join(VOCABULARY)})"))
        decl &= set(VOCABULARY)
        union |= decl
        for s in VOCABULARY:
            compared += 1
            if s in decl and s not in found:
                findings.append(("declared-not-found", f"{c['manifest']}: declares {s}, none found"))
            elif s in found and s not in decl:
                findings.append(("found-not-declared", f"{c['manifest']}: {s} found in {found[s][0]}, not declared"))
        for s in sorted(decl & {"unity", "unreal"}):
            if not repo_c:
                findings.append(("engine-without-c", f"{c['manifest']}: declares {s}, and no crate of the repository has the c surface it binds"))
        for s in sorted(decl & set(BUILT_IN_CI) | ({"c"} if decl & {"unity", "unreal"} and repo_c else set())):
            if not workflows:
                raise InputError(f"{c['manifest']} declares {s}, and no workflow file is tracked to look in")
            steps = [st for t in workflows.values() if push_triggered(t) for st in run_steps(t)]
            compared += 1
            if not any(re.search(rx, st) for st in steps for rx in CI_BUILD[s]):
                findings.append(("ci-not-built", f"{c['manifest']}: no push-triggered workflow step builds {s}"))
            if s in RUN_IN_CI:
                compared += 1
                if not any(re.search(rx, st) for st in steps for rx in CI_RUN[s]):
                    findings.append(("ci-not-run", f"{c['manifest']}: no push-triggered workflow step runs the built {s}"))
    if require_declaration and not any(c["declared"] is not None for c in cs):
        raise InputError("no crate declares [package.metadata.alice] surfaces (compared nothing)")
    tables = {}
    for name in ("README.md", "README_JP.md"):
        if name in files:
            tables[name] = readme_table(read(repo, name))
    if "README.md" not in tables:
        findings.append(("readme", "README.md is not tracked"))
    for name, rows in tables.items():
        compared += 1
        if rows is None:
            findings.append(("readme", f"{name}: no <!-- surfaces --> table"))
        elif rows != union:
            findings.append(("readme", f"{name}: the surface table lists {sorted(rows)}, the crates declare {sorted(union)}"))
    return findings, compared


# ---------------------------------------------------------------------------------------------
# baseline (generated, shrink-only)


def counts(findings: list[tuple[str, str]]) -> dict[str, int]:
    res: dict[str, int] = {}
    for kind, _ in findings:
        res[kind] = res.get(kind, 0) + 1
    return dict(sorted(res.items()))


def compare_baseline(name: str, now: dict[str, int], baseline: dict) -> list[str]:
    row = (baseline.get("repository") or {}).get(name, {})
    out = []
    for kind in sorted(set(now) | set(row)):
        have, allowed = now.get(kind, 0), int(row.get(kind, 0))
        if have > allowed:
            out.append(f"{kind}: {have} finding(s), the baseline allows {allowed}")
        elif have < allowed:
            out.append(f"{kind}: {have} finding(s), the baseline still allows {allowed} (stale: lower the row)")
    return out


def render_baseline(rows: dict[str, dict[str, int]]) -> str:
    lines = [
        "# Generated by scripts/surface_claims_check.py --write-baseline; do not edit by hand.",
        "# The G15 finding counts by kind each repository is allowed while it adopts the gate; a count",
        "# only goes down (a lower count than allowed is a stale row and fails too).",
        "",
    ]
    for name in sorted(rows):
        if not rows[name]:
            continue
        lines.append(f'[repository."{name}"]')
        lines += [f'"{k}" = {v}' for k, v in rows[name].items()]
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--repo")
    ap.add_argument("--baseline")
    ap.add_argument("--name")
    ap.add_argument("--write-baseline", nargs="+", metavar=("FILE", "NAME=DIR"))
    a = ap.parse_args(argv)
    if a.write_baseline:
        out, *pairs = a.write_baseline
        if not pairs:
            print("surface_claims_check: --write-baseline needs at least one NAME=DIR (compared nothing)", file=sys.stderr)
            return 2
        rows = {}
        for pair in pairs:
            name, _, d = pair.partition("=")
            try:
                findings, _ = check_repo(Path(d), require_declaration=False)
            except InputError as e:
                findings = [("unverified", str(e))]
            rows[name] = counts(findings)
        Path(out).write_text(render_baseline(rows), encoding="utf-8")
        print(f"baseline: {len(rows)} repositories, {sum(1 for r in rows.values() if r)} with findings")
        return 0
    if not a.repo:
        ap.error("--repo or --write-baseline is required")
    try:
        findings, compared = check_repo(Path(a.repo), require_declaration=not a.baseline)
    except InputError as e:
        print(f"surface_claims_check: {e}", file=sys.stderr)
        return 2
    if compared == 0:
        print("surface_claims_check: compared nothing", file=sys.stderr)
        return 2
    if a.baseline:
        if not a.name:
            ap.error("--baseline needs --name")
        baseline = tomllib.loads(Path(a.baseline).read_text(encoding="utf-8"))
        problems = compare_baseline(a.name, counts(findings), baseline)
        for f in findings:
            print(f"note (baseline): {f[1]}")
        for p in problems:
            print(f"surface claims: {a.name}: {p}")
        print(f"compared: {compared}, findings {len(findings)}, against the baseline {len(problems)}")
        return 1 if problems else 0
    for kind, text in findings:
        print(f"surface claims ({kind}): {text}")
    print(f"compared: {compared}, findings {len(findings)}")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
