#!/usr/bin/env python3
"""Generate the Status section of README.md (and README_JP.md) from the committed files.

The section between `<!-- law-status:begin -->` and `<!-- law-status:end -->` is rendered from:

- `release-train.toml`: each crate's version, state, order, repository and tag, and the
  steps expected to fail until a release (`[expected-failure.*]`);
- `e2e/golden/run.digest`: the end to end run digest recorded for each alice-det-math release;
- `conformance/gates.toml` and `conformance/missing-manifests.toml`: the number of gates and the crates
  whose manifest is not written yet.

The status counts of each crate's alice-law-conformance.toml at its main are not committed: the
Conformance (live) workflow computes them from the mains and publishes them in its job summary, which
the section points to.

Only committed files are read, so the output is the same on every machine: no date, no
"measured" sentence, no CI conclusion (the workflows' runs are the CI results).

    gen_law_status.py            rewrite the section in each README that has the markers
    gen_law_status.py --check    exit 1 when a README's section differs from the rendering

README.md must have the markers; README_JP.md, when it exists, must have them too. A marker
missing, doubled or out of order, or an input with nothing to render, exits 2.
"""
from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- law-status:begin -->"
END = "<!-- law-status:end -->"
READMES = {"en": "README.md", "ja": "README_JP.md"}

LABELS = {
    "en": {
        "lead": "Generated by `scripts/gen_law_status.py` from `release-train.toml`, `e2e/golden/run.digest` "
                "and `conformance/` (do not edit by hand; CI fails when it differs). The CI results are the "
                "workflows' runs.",
        "train": "Release train",
        "train_h": "| crate | version | state | order | repository | tag |",
        "expected": "Steps expected to fail until a release",
        "expected_h": "| step | until | why |",
        "expected_none": "None.",
        "golden": "End to end run digest per alice-det-math release",
        "golden_h": "| alice-det-math | run digest |",
        "conformance": "Conformance manifests ({gates} gates)",
        "conformance_note": "The status counts of each repository's manifest at main are computed from the mains by the "
                            "Conformance (live) workflow and shown in its job summary (they are not committed here).",
        "missing": "Crates whose manifest is not written yet",
        "missing_h": "| crate | added in | why |",
        "missing_none": "None.",
        "tag_default": "(none)",
    },
    "ja": {
        "lead": "`scripts/gen_law_status.py` が `release-train.toml`・`e2e/golden/run.digest`・`conformance/` から"
                "生成する (手で編集しない、生成結果と違えば CI が失敗する) CI の結果は各 workflow の run を見る",
        "train": "Release train",
        "train_h": "| crate | 版 | 状態 | 順 | repository | tag |",
        "expected": "公開まで失敗を予期する step",
        "expected_h": "| step | 期限 | 理由 |",
        "expected_none": "なし",
        "golden": "alice-det-math の版ごとの end to end の run digest",
        "golden_h": "| alice-det-math | run digest |",
        "conformance": "Conformance manifest ({gates} gate)",
        "conformance_note": "各 repository の main の manifest の状態の件数は Conformance (live) の workflow が各 main から"
                            "計算し、その job summary に出す (ここには commit しない)",
        "missing": "manifest がまだ無い crate",
        "missing_h": "| crate | 追加する repository | 理由 |",
        "missing_none": "なし",
        "tag_default": "(なし)",
    },
}


class InputError(Exception):
    pass


def load(path: Path) -> dict:
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as e:
        raise InputError(f"{path.name}: {e}") from e


def cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def render(lang: str, root: Path | None = None) -> str:
    root = ROOT if root is None else root
    L = LABELS[lang]
    roster = load(root / "release-train.toml")
    crates = roster.get("crate", {})
    if not crates:
        raise InputError("release-train.toml lists no crate")
    golden = [ln.split() for ln in (root / "e2e" / "golden" / "run.digest").read_text(encoding="utf-8").splitlines()
              if ln.strip() and not ln.startswith("#")]
    if not golden or any(len(g) != 2 for g in golden):
        raise InputError("e2e/golden/run.digest: expected lines of `<alice-det-math version> <digest>`")
    missing_path = root / "conformance" / "missing-manifests.toml"
    missing = load(missing_path).get("missing", {}) if missing_path.exists() else {}

    out = [BEGIN, "", L["lead"], "", f"### {L['train']}", "", L["train_h"], "|---|---|---|---|---|---|"]
    for name, c in sorted(crates.items(), key=lambda kv: (kv[1].get("order", 0), kv[0])):
        # the tag the release train names (scripts/release_train.py tag_name: `v{version}` unless the
        # roster gives another form); an exempt crate is not released
        tag = c.get("tag", "v{version}").replace("{version}", c["version"]) if c.get("state") != "exempt" \
            else L["tag_default"]
        out.append("| " + " | ".join(cell(v) for v in (name, c["version"], c["state"], c.get("order", ""),
                                                        c.get("repo", ""), tag)) + " |")
    out += ["", f"### {L['expected']}", ""]
    ef = roster.get("expected-failure", {})
    if ef:
        out += [L["expected_h"], "|---|---|---|"]
        for name in sorted(ef):
            e = ef[name]
            out.append("| " + " | ".join(cell(v) for v in (e["step"], e["until"], e["why"])) + " |")
    else:
        out.append(L["expected_none"])
    out += ["", f"### {L['golden']}", "", L["golden_h"], "|---|---|"]
    for version, digest in golden:
        out.append(f"| {cell(version)} | `{cell(digest)}` |")
    gates = load(root / "conformance" / "gates.toml").get("gate", [])
    if not gates:
        raise InputError("conformance/gates.toml lists no gate")
    out += ["", f"### {L['conformance'].format(gates=len(gates))}", "", L["conformance_note"]]
    out += ["", f"### {L['missing']}", ""]
    if missing:
        out += [L["missing_h"], "|---|---|---|"]
        for name in sorted(missing):
            out.append("| " + " | ".join(cell(v) for v in (name, missing[name]["fixed-in"], missing[name]["why"])) + " |")
    else:
        out.append(L["missing_none"])
    out += ["", END]
    return "\n".join(out)


def splice(text: str, block: str, name: str) -> str:
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise InputError(f"{name}: the markers {BEGIN} / {END} must appear once each, in that order")
    a = text.index(BEGIN)
    b = text.index(END) + len(END)
    return text[:a] + block + text[b:]


def main(argv: list[str] | None = None, root: Path | None = None) -> int:
    # the default root is read at call time (a test can point ROOT elsewhere)
    root = ROOT if root is None else root
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    differs = []
    compared = 0
    try:
        for lang, name in READMES.items():
            path = root / name
            if not path.exists():
                if lang == "en":
                    raise InputError(f"{name} is missing")
                continue
            text = path.read_text(encoding="utf-8")
            new = splice(text, render(lang, root), name)
            compared += 1
            if new != text:
                if a.check:
                    differs.append(name)
                else:
                    path.write_text(new, encoding="utf-8")
                    print(f"law-status: wrote {name}")
    except InputError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    if compared == 0:
        print("error: no README was compared", file=sys.stderr)
        return 2
    for name in differs:
        print(f"found: {name}: the Status section differs from scripts/gen_law_status.py (run it and commit)")
    print(f"law-status: {compared} README(s) compared, {len(differs)} differ")
    return 1 if differs else 0


if __name__ == "__main__":
    sys.exit(main())
